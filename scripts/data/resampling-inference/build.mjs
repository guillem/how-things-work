#!/usr/bin/env node
/**
 * Builds `src/routes/resampling-inference/penguins-data.ts`, the subset of the Palmer penguins
 * the resampling page uses.
 *
 *   node scripts/data/resampling-inference/build.mjs <path to penguins.csv>
 *
 * Download (outside the repository):
 *   https://raw.githubusercontent.com/allisonhorst/palmerpenguins/8957207b78d6ccd1b4654a9dd9c9041b657478ab/inst/extdata/penguins.csv
 *
 * Source: Horst, A. M., Hill, A. P. and Gorman, K. B. (2020). palmerpenguins: Palmer
 * Archipelago (Antarctica) penguin data. R package, https://allisonhorst.github.io/palmerpenguins/,
 * doi:10.5281/zenodo.3960218. Data collected by Dr. Kristen Gorman with the Palmer Station
 * Long Term Ecological Research Program (Gorman, K. B., Williams, T. D. and Fraser, W. R. 2014,
 * PLoS ONE 9(3): e90081, doi:10.1371/journal.pone.0090081). Licence: CC0 1.0.
 *
 * Subset: the 342 penguins whose flipper length and body mass were measured (the two rows
 * without measurements are dropped), in the file's order, with four columns: species, island,
 * flipper length (mm) and body mass (g). Values are copied unchanged.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
	console.error('usage: build.mjs <penguins.csv>');
	process.exit(1);
}
const lines = fs.readFileSync(src, 'utf8').trim().split(/\r?\n/);
const head = lines[0].split(',');
const col = (name) => head.indexOf(name);
const iS = col('species');
const iI = col('island');
const iF = col('flipper_length_mm');
const iM = col('body_mass_g');
const rows = [];
for (const line of lines.slice(1)) {
	const c = line.split(',');
	if (c[iF] === 'NA' || c[iM] === 'NA') continue;
	rows.push(`${c[iS]},${c[iI]},${Number(c[iF])},${Number(c[iM])}`);
}
if (rows.length !== 342) throw new Error(`expected 342 measured penguins, got ${rows.length}`);

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '../../../src/routes/resampling-inference/penguins-data.ts');
const body = `/**
 * The Palmer penguins: the 342 penguins with flipper length and body mass measured. GENERATED by
 * scripts/data/resampling-inference/build.mjs: do not edit by hand.
 *
 * Horst, Hill & Gorman (2020), palmerpenguins (R package, CC0 1.0), from data collected by
 * Kristen Gorman with the Palmer Station Long Term Ecological Research Program (Gorman, Williams
 * & Fraser 2014, PLoS ONE 9(3): e90081).
 */
/** One penguin per line: species, island, flipper length (mm), body mass (g). */
export const PENGUINS_CSV = \`species,island,flipper_mm,mass_g
${rows.join('\n')}
\`;
`;
fs.writeFileSync(out, body);
console.log(`wrote ${out}: ${rows.length} penguins`);
