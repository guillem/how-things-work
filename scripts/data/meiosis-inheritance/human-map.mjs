#!/usr/bin/env node
/**
 * Builds `src/routes/meiosis-inheritance/human-map.ts`: a coarse genetic map of
 * the 22 human autosomes, for the "why siblings differ" step.
 *
 *   node scripts/data/meiosis-inheritance/human-map.mjs <dir with plink.chrN.GRCh38.map>
 *
 * Sources
 * - Genetic map: the Beagle GRCh38 PLINK-format map (Xiaowen Tian), lifted over
 *   from Adam Auton's GRCh37 map, which is the HapMap phase II sex-averaged map
 *   (The International HapMap Consortium, "A second generation human haplotype
 *   map of over 3.1 million SNPs", Nature 449, 851–861, 2007).
 *   https://bochet.gcc.biostat.washington.edu/beagle/genetic_maps/plink.GRCh38.map.zip
 *   (folder no_chr_in_chrom_field). No licence statement accompanies the files.
 * - Physical lengths: UCSC hg38 chrom.sizes,
 *   https://hgdownload.soe.ucsc.edu/goldenPath/hg38/bigZips/hg38.chrom.sizes
 *
 * Subset: for each autosome, the map's total length in cM (last marker minus
 * first), and 41 knots at evenly spaced genetic positions (0, 2.5%, …, 100% of
 * the length) giving the physical position in Mb (2 decimals) of the marker
 * nearest below each knot, linearly interpolated. Before the first marker (the
 * short arms of the acrocentric chromosomes 13, 14, 15, 21 and 22, and every
 * chromosome's first few kb) the map has no recombination: the scene draws
 * that stretch as not recombining.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) {
	console.error('usage: node scripts/data/meiosis-inheritance/human-map.mjs <map dir>');
	process.exit(1);
}

// hg38 chrom.sizes (bp), chromosomes 1–22.
const SIZES = [
	248956422, 242193529, 198295559, 190214555, 181538259, 170805979, 159345973, 145138636, 138394717,
	133797422, 135086622, 133275309, 114364328, 107043718, 101991189, 90338345, 83257441, 80373285,
	58617616, 64444167, 46709983, 50818468
];
const KNOTS = 41;

const chromosomes = [];
for (let c = 1; c <= 22; c++) {
	const rows = readFileSync(path.join(dir, `plink.chr${c}.GRCh38.map`), 'utf8')
		.trim()
		.split('\n')
		.map((l) => l.trim().split(/\s+/))
		.map(([, , cm, bp]) => ({ cm: Number(cm), bp: Number(bp) }));
	const cm0 = rows[0].cm;
	const length = rows[rows.length - 1].cm - cm0;
	const mb = [];
	let j = 0;
	for (let k = 0; k < KNOTS; k++) {
		const target = cm0 + (length * k) / (KNOTS - 1);
		while (j < rows.length - 2 && rows[j + 1].cm < target) j++;
		const a = rows[j];
		const b = rows[j + 1];
		const u = b.cm > a.cm ? Math.min(1, Math.max(0, (target - a.cm) / (b.cm - a.cm))) : 0;
		mb.push(Math.round((a.bp + u * (b.bp - a.bp)) / 1e4) / 100);
	}
	chromosomes.push({
		n: c,
		mb: Math.round(SIZES[c - 1] / 1e4) / 100,
		cM: Math.round(length * 10) / 10,
		knots: mb
	});
}

const total = chromosomes.reduce((s, c) => s + c.cM, 0);
const out = `// Generated by scripts/data/meiosis-inheritance/human-map.mjs — do not edit.
//
// A coarse genetic map of the 22 human autosomes. Genetic lengths: the HapMap
// phase II sex-averaged map (International HapMap Consortium, Nature 449,
// 851–861, 2007), as the Beagle GRCh38 PLINK map (lifted over by Xiaowen Tian
// from Adam Auton's GRCh37 map;
// https://bochet.gcc.biostat.washington.edu/beagle/genetic_maps/, no licence
// statement given). Physical lengths: UCSC hg38 chrom.sizes.
// \`knots[k]\` is the physical position (Mb) at genetic position k/${KNOTS - 1} of
// the chromosome's map; before knots[0] the map has no recombination.
// Total autosomal length: ${total.toFixed(1)} cM.

export interface HumanChromosome {
	/** Chromosome number. */
	n: number;
	/** Physical length, Mb (hg38). */
	mb: number;
	/** Genetic length, centimorgans (sex-averaged). */
	cM: number;
	/** Physical positions (Mb) at evenly spaced genetic positions along the map. */
	knots: number[];
}

export const HUMAN_AUTOSOMES: HumanChromosome[] = ${JSON.stringify(chromosomes)};
`;
const file = 'src/routes/meiosis-inheritance/human-map.ts';
writeFileSync(file, out);
console.log(`wrote ${file}: ${chromosomes.length} autosomes, ${total.toFixed(1)} cM`);
