// Builds src/routes/kv-cache-inference/weights-data.ts: the trained weights of the tiny
// character-level GPT of training-a-tiny-language-model (width 32, context 64 characters, all of
// the training text, 3,000 steps), trained with that page's own code (`train.ts`, `tiny-gpt.ts`,
// imported as they are), so the KV-cache page can generate text with it. The weights are stored
// as float32 (base64); the page widens them back to float64, the model's own arithmetic.
//
// Data: Tiny Shakespeare (Karpathy's char-rnn, MIT; the text is public domain), the copy the
// n-gram page ships, split as nanoGPT does (first 90% to learn from).
//
// Usage (Node ≥ 23 runs TypeScript directly; about 10 minutes on one core):
//   node scripts/data/kv-cache-inference/build.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { Alphabet, split } from '../../../src/routes/ngram-text-models/ngram.ts';
import { Run } from '../../../src/routes/training-a-tiny-language-model/train.ts';

const ROUTE = new URL('../../../src/routes/kv-cache-inference/', import.meta.url);
const TEXT = new URL('../../../src/routes/ngram-text-models/tinyshakespeare.txt', import.meta.url);

const WIDTH = 32;
const CONTEXT = 64;

const text = readFileSync(TEXT, 'utf8');
const chars = new Alphabet(text).chars;
const index = new Map(chars.map((c, i) => [c, i]));
const enc = (s: string) => Int32Array.from(Array.from(s), (c) => index.get(c) ?? 0);
const { train, heldOut } = split(text);
const run = new Run(chars, enc(train), enc(heldOut), WIDTH, CONTEXT, Infinity);
const t0 = performance.now();
while (!run.done) {
	run.advance();
	if (run.step % 250 === 0)
		console.log(`step ${run.step}, ${((performance.now() - t0) / 1000).toFixed(0)} s`);
}
const last = run.progress.points[run.progress.points.length - 1];
console.log(`train ${last.train.toFixed(3)}, held-out ${last.val.toFixed(3)} nats/char`);

const f32 = Float32Array.from(run.model.weights);
const b64 = Buffer.from(f32.buffer).toString('base64');
const out = `// Generated by scripts/data/kv-cache-inference/build.ts: do not edit.
// The tiny GPT of training-a-tiny-language-model (width ${WIDTH}, ${run.model.config.heads} heads,
// ${run.model.config.layers} layers, context ${CONTEXT}), trained for ${run.step} steps on Tiny Shakespeare
// (public domain; the char-rnn copy is MIT): held-out loss ${last.val.toFixed(3)} nats per character.
// Weights as little-endian float32, base64.
export const weightsData = {
	chars: ${JSON.stringify(chars.join(''))},
	width: ${WIDTH},
	context: ${CONTEXT},
	heads: ${run.model.config.heads},
	layers: ${run.model.config.layers},
	heldOutLoss: ${last.val.toFixed(4)},
	weights:
		'${b64}'
};
`;
writeFileSync(new URL('weights-data.ts', ROUTE), out);
console.log(`wrote weights-data.ts (${(out.length / 1024).toFixed(0)} kB)`);
