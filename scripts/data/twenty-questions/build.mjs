// Builds src/routes/twenty-questions/data.ts: the animal board and the thousand-page dictionary.
//
// Usage (the inputs are not committed):
//   curl -sSL -o <dir>/zoo.zip https://archive.ics.uci.edu/static/public/111/zoo.zip
//   unzip <dir>/zoo.zip -d <dir>
//   node scripts/data/twenty-questions/build.mjs <dir>/zoo.data [/usr/share/dict/web2]
//
// The animals: the UCI Zoo dataset (Richard Forsyth, 1990; UCI Machine Learning Repository,
// doi:10.24432/C5R59V, CC BY 4.0): 101 rows of an animal's name, 15 yes/no features, its number
// of legs and its class. Two rows are left out: "girl" (a person, not an animal for this board)
// and the second of the two "frog" rows (two tiles named "frog" would puzzle the reader; the
// second differs from the first only in being venomous). A few names are written out in plain
// words ("vampire" is a vampire bat, "pussycat" a cat). 99 animals are left. Three plain mistakes
// are corrected (FIXES below).
//
// The dictionary: the word list of Webster's Second International Dictionary (1934), as shipped
// in BSD and macOS at /usr/share/dict/web2 (its README: "The 1934 copyright has lapsed"). The
// words that start with a small letter (no names of people or places), in alphabetical order,
// are cut into 1,000 pages of nearly the same size; only the first and last word of each page
// are kept.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [zooFile, dictFile = '/usr/share/dict/web2'] = process.argv.slice(2);
if (!zooFile) throw new Error('usage: node build.mjs <zoo.data> [web2]');
const OUT = new URL('../../../src/routes/twenty-questions/data.ts', import.meta.url);
const sha = (b) => createHash('sha256').update(b).digest('hex');

// ---- animals ----------------------------------------------------------------------------------
const zooRaw = readFileSync(zooFile);
const NAMES = {
	vampire: 'vampire bat',
	pussycat: 'cat',
	fruitbat: 'fruit bat',
	pitviper: 'pit viper',
	seasnake: 'sea snake',
	slowworm: 'slow-worm',
	sealion: 'sea lion',
	seawasp: 'sea wasp',
	housefly: 'housefly',
	ladybird: 'ladybird',
	starfish: 'starfish',
	dogfish: 'dogfish',
	stingray: 'stingray',
	seahorse: 'seahorse',
	honeybee: 'honeybee'
};
// Plain mistakes of the dataset, corrected (the page says so): a crab has ten legs (eight for
// walking and two claws), a squirrel four, and a sea snake breathes air.
const FIXES = { crab: { legs: 10 }, squirrel: { legs: 4 }, seasnake: { breathes: '1' } };
const seen = new Set();
const animals = [];
for (const line of zooRaw.toString('utf8').trim().split('\n')) {
	const f = line.trim().split(',');
	const name = f[0];
	if (name === 'girl' || seen.has(name)) continue;
	seen.add(name);
	// hair feathers eggs milk airborne aquatic predator toothed backbone breathes venomous fins
	// legs tail domestic catsize type
	let bits = f.slice(1, 13).join('') + f[14] + f[15] + f[16];
	const fix = FIXES[name];
	if (fix?.breathes) bits = bits.slice(0, 9) + fix.breathes + bits.slice(10);
	animals.push({
		name: NAMES[name] ?? name,
		bits,
		legs: fix?.legs ?? Number(f[13]),
		type: Number(f[17])
	});
}

// ---- dictionary -------------------------------------------------------------------------------
const dictRaw = readFileSync(dictFile);
const words = [
	...new Set(
		dictRaw
			.toString('utf8')
			.split('\n')
			.map((w) => w.trim())
			.filter((w) => /^[a-z]+$/.test(w))
	)
].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const PAGES = 1000;
const pages = [];
for (let p = 0; p < PAGES; p++) {
	const a = Math.floor((p * words.length) / PAGES);
	const b = Math.floor(((p + 1) * words.length) / PAGES) - 1;
	pages.push([words[a], words[b]]);
}

const out = `// Generated by scripts/data/twenty-questions/build.mjs: do not edit by hand.
// Animals: UCI Zoo dataset (Richard Forsyth, 1990), UCI Machine Learning Repository,
// https://archive.ics.uci.edu/dataset/111/zoo (doi:10.24432/C5R59V), CC BY 4.0.
// zoo.data SHA-256 ${sha(zooRaw)}; "girl" and the second "frog" left out;
// corrected: crab 10 legs (not 4), squirrel 4 legs (not 2), sea snake breathes air.
// Dictionary: Webster's Second International (1934) word list, /usr/share/dict/web2
// (public domain), SHA-256 ${sha(dictRaw)}; ${words.length} words in small letters, in 1,000 pages.

/**
 * The animals: name; the yes/no answers in the order hair, feathers, eggs, milk, flies, lives in
 * water, hunts, teeth, backbone, breathes air, venomous, fins, tail, kept by people, bigger than a
 * cat ('1' yes, '0' no); the number of legs; the dataset's class (1 mammal, 2 bird, 3 reptile,
 * 4 fish, 5 amphibian, 6 insect, 7 other animals without a backbone).
 */
export const ANIMALS: readonly { name: string; bits: string; legs: number; type: number }[] = ${JSON.stringify(animals)};

/** How many words the dictionary holds. */
export const WORD_COUNT = ${words.length};

/** The 1,000 pages of the dictionary: the first and the last word on each. */
export const PAGES: readonly (readonly [string, string])[] = ${JSON.stringify(pages)};
`;
writeFileSync(OUT, out);
console.log(`${animals.length} animals, ${words.length} words, ${PAGES} pages`);
