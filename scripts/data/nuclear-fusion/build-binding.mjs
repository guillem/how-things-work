#!/usr/bin/env node
/**
 * Builds `src/routes/nuclear-fusion/binding.ts` from the Atomic Mass Evaluation 2020.
 *
 *   curl -o mass_1.mas20.txt https://www-nds.iaea.org/amdc/ame2020/mass_1.mas20.txt
 *   node scripts/data/nuclear-fusion/build-binding.mjs mass_1.mas20.txt
 *
 * Source: M. Wang, W. J. Huang, F. G. Kondev, G. Audi and S. Naimi, "The AME 2020 atomic mass
 * evaluation (II). Tables, graphs and references", Chinese Physics C 45, 030003 (2021),
 * open access under CC BY 3.0; data file mass_1.mas20.txt from the IAEA Atomic Mass Data
 * Center. The file is fixed-width (Fortran format a1,i3,i5,i5,i5,1x,a3,a4,1x,f14.6,f12.6,
 * f13.5,1x,f10.5,…); values marked `#` are estimates from systematics, not measurements, and
 * are skipped.
 *
 * Kept: (1) for every mass number A, the measured nuclide with the largest binding energy per
 * nucleon (the bottom of the valley of stability, which is the usual binding-energy curve);
 * (2) the mass excesses of the nuclides the explainer's reactions use.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const src = process.argv[2];
if (!src) {
	console.error('usage: build-binding.mjs mass_1.mas20.txt');
	process.exit(1);
}
const out = resolve(
	dirname(fileURLToPath(import.meta.url)),
	'../../../src/routes/nuclear-fusion/binding.ts'
);

const lines = readFileSync(src, 'utf8').split('\n');
const start = lines.findIndex((l) => /^0\s+1\s+1\s+0\s+1\s+n\b/.test(l));
if (start < 0) throw new Error('data start not found');

const rows = [];
for (const l of lines.slice(start)) {
	if (l.length < 80) continue;
	const n = Number(l.slice(4, 9));
	const z = Number(l.slice(9, 14));
	const a = Number(l.slice(14, 19));
	const el = l.slice(20, 23).trim();
	const dRaw = l.slice(28, 42);
	const beRaw = l.slice(54, 67);
	if (dRaw.includes('#') || beRaw.includes('#')) continue;
	const delta = Number(dRaw);
	const be = Number(beRaw);
	if (!Number.isFinite(delta) || !Number.isFinite(be) || n + z !== a) continue;
	rows.push({ z, n, a, el, delta, be });
}

const best = new Map();
for (const r of rows) {
	const b = best.get(r.a);
	if (!b || r.be > b.be) best.set(r.a, r);
}
const curve = [...best.values()].sort((p, q) => p.a - q.a);

const wanted = [
	['n', 0, 1],
	['H-1', 1, 1],
	['H-2', 1, 2],
	['H-3', 1, 3],
	['He-3', 2, 3],
	['He-4', 2, 4],
	['Li-6', 3, 6],
	['C-12', 6, 12],
	['Fe-56', 26, 56],
	['Ni-62', 28, 62],
	['Kr-92', 36, 92],
	['Zr-92', 40, 92],
	['Ba-141', 56, 141],
	['Pr-141', 59, 141],
	['U-235', 92, 235]
];
const named = wanted.map(([name, z, a]) => {
	const r = rows.find((x) => x.z === z && x.a === a);
	if (!r) throw new Error(`missing ${name}`);
	return { name, z, a, delta: r.delta, be: r.be };
});

const header = `/**
 * Generated by \`scripts/data/nuclear-fusion/build-binding.mjs\` from the Atomic Mass Evaluation
 * 2020: do not edit by hand.
 *
 * Source: M. Wang, W. J. Huang, F. G. Kondev, G. Audi and S. Naimi, "The AME 2020 atomic mass
 * evaluation (II). Tables, graphs and references", Chinese Physics C 45, 030003 (2021), open
 * access (CC BY 3.0); file mass_1.mas20.txt from the IAEA Atomic Mass Data Center,
 * https://www-nds.iaea.org/amdc/ame2020/mass_1.mas20.txt. Estimated (#) values are left out.
 *
 * \`curve\`: for each mass number A, the measured nuclide with the largest binding energy per
 * nucleon, as [A, Z, binding energy per nucleon in keV]. \`nuclides\`: mass excesses (keV) of
 * the nuclides used in the explainer's reactions (atomic mass = A u + mass excess).
 */
`;
const body =
	`export const curve: readonly (readonly [number, number, number])[] = [\n` +
	curve.map((r) => `\t[${r.a}, ${r.z}, ${r.be}]`).join(',\n') +
	`\n];\n\n` +
	`export const nuclides = {\n` +
	named
		.map(
			(r) =>
				`\t'${r.name}': { z: ${r.z}, a: ${r.a}, massExcess: ${r.delta}, bindingPerNucleon: ${r.be} }`
		)
		.join(',\n') +
	`\n} as const;\n\nexport type NuclideName = keyof typeof nuclides;\n`;
writeFileSync(out, header + body);
console.log(`wrote ${out}: ${curve.length} points, ${named.length} nuclides`);
