#!/usr/bin/env node
/**
 * Builds `src/routes/dark-matter/sparc.ts`: measured rotation curves and their
 * baryonic mass models for four galaxies of the SPARC database.
 *
 *   node scripts/data/dark-matter/build-sparc.mjs <dir with the three .mrt files>
 *
 * Source: Lelli, F., McGaugh, S. S. & Schombert, J. M. (2016), "SPARC: Mass
 * Models for 175 Disk Galaxies with Spitzer Photometry and Accurate Rotation
 * Curves", The Astronomical Journal 152, 157, https://doi.org/10.3847/0004-6256/152/6/157.
 * Files from https://astroweb.cwru.edu/SPARC/ (no licence stated; the site asks
 * users to cite the paper and, where relevant, the original rotation-curve
 * sources, which are kept per galaxy in `refs`):
 *   - MassModels_Lelli2016c.mrt (Table 2: R, Vobs, e_Vobs, Vgas, Vdisk, Vbul per radius)
 *   - SPARC_Lelli2016c.mrt      (Table 1: distance, inclination, L[3.6], M_HI, Vflat, quality)
 *   - Bulges.mrt                (bulge luminosities at 3.6 µm)
 *
 * Subset: every radius of NGC 3198, NGC 2403, DDO 154 and NGC 2841, unchanged
 * (km/s, kpc). Vdisk and Vbul are for a mass-to-light ratio of 1 M☉/L☉ at
 * 3.6 µm; Vgas already includes the factor 1.33 for helium. Velocities can be
 * negative (a component that pulls outwards at that radius): combine them as
 * V·|V|, never V².
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: build-sparc.mjs <dir with the SPARC .mrt files>');
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/dark-matter/sparc.ts');

const GALAXIES = ['NGC3198', 'NGC2403', 'DDO154', 'NGC2841'];

const t2 = readFileSync(path.join(dir, 'MassModels_Lelli2016c.mrt'), 'utf8').split('\n');
const t1 = readFileSync(path.join(dir, 'SPARC_Lelli2016c.mrt'), 'utf8').split('\n');
const bul = readFileSync(path.join(dir, 'Bulges.mrt'), 'utf8').split('\n');

/** Fixed-width field (1-based inclusive byte range, as in the .mrt header). */
const field = (line, a, b) => line.slice(a - 1, b).trim();

const out = [];
for (const id of GALAXIES) {
	// Table 1's columns drift from its byte-by-byte header: split on whitespace
	// (19 fields: Galaxy T D e_D f_D Inc e_Inc L e_L Reff SBeff Rdisk SBdisk MHI
	// RHI Vflat e_Vflat Q Ref; Ref has no spaces).
	const line = t1.find((l) => l.trim().split(/\s+/)[0] === id);
	if (!line) throw new Error(`${id} missing from Table 1`);
	const row = line.trim().split(/\s+/);
	if (row.length !== 19) throw new Error(`${id}: ${row.length} fields in Table 1`);
	const lbulRow = bul.find((l) => l.split(/\s+/)[0] === id);
	if (!lbulRow) throw new Error(`${id} missing from Bulges.mrt`);
	const points = t2
		.filter((l) => field(l, 1, 11) === id)
		.map((l) => ({
			r: Number(field(l, 20, 25)),
			v: Number(field(l, 27, 32)),
			e: Number(field(l, 34, 38)),
			gas: Number(field(l, 40, 45)),
			disk: Number(field(l, 47, 52)),
			bulge: Number(field(l, 54, 59))
		}));
	if (points.length < 5) throw new Error(`${id}: only ${points.length} points`);
	for (const p of points) {
		for (const [k, v] of Object.entries(p)) if (!Number.isFinite(v)) throw new Error(`${id} ${k}`);
	}
	out.push({
		id,
		hubbleType: Number(row[1]),
		distance: Number(row[2]),
		inclination: Number(row[5]),
		lum36: Number(row[7]),
		lumBulge: Number(lbulRow.split(/\s+/)[1]),
		mHI: Number(row[13]),
		vFlat: Number(row[15]),
		quality: Number(row[17]),
		refs: row[18],
		points
	});
}

const body = out
	.map((g) => {
		const pts = g.points
			.map((p) => `[${p.r}, ${p.v}, ${p.e}, ${p.gas}, ${p.disk}, ${p.bulge}]`)
			.join(',\n\t\t\t');
		return `\t${g.id}: {
		id: '${g.id}',
		hubbleType: ${g.hubbleType},
		distance: ${g.distance},
		inclination: ${g.inclination},
		lum36: ${g.lum36},
		lumBulge: ${g.lumBulge},
		mHI: ${g.mHI},
		vFlat: ${g.vFlat},
		quality: ${g.quality},
		refs: '${g.refs}',
		// [R kpc, Vobs, e_Vobs, Vgas, Vdisk, Vbul] in km/s
		points: [
			${pts}
		]
	}`;
	})
	.join(',\n');

const ts = `/**
 * Measured rotation curves and baryonic mass models of four SPARC galaxies.
 * GENERATED by scripts/data/dark-matter/build-sparc.mjs — do not edit by hand.
 *
 * Source: Lelli, McGaugh & Schombert (2016), "SPARC: Mass Models for 175 Disk
 * Galaxies with Spitzer Photometry and Accurate Rotation Curves", AJ 152, 157,
 * https://doi.org/10.3847/0004-6256/152/6/157; data from https://astroweb.cwru.edu/SPARC/
 * (Table 1, Table 2 "Mass Models", Bulges.mrt). No licence is stated; cite the
 * paper and the original rotation-curve sources (\`refs\`, keys as in SPARC
 * Table 1: Be87/Be91 Begeman 1987, 1991; Da06 Daigle et al. 2006; Fr02 Fraternali
 * et al. 2002; CB89 Carignan & Beaulieu 1989; Di08 Dicaire et al. 2008).
 *
 * Subset: every tabulated radius of the four galaxies, unchanged. Vdisk and Vbul
 * are the speeds the stellar disc and bulge alone would give for a mass-to-light
 * ratio of 1 M☉/L☉ at 3.6 µm; Vgas includes the factor 1.33 for helium. A
 * component's speed can be negative (it pulls outwards there): combine as V·|V|.
 * e_Vobs is the random error only (non-circular motions, asymmetries), not the
 * systematic one from the inclination.
 */

export interface SparcGalaxy {
	id: string;
	/** Hubble type, 0 = S0 … 5 = Sc … 10 = Im. */
	hubbleType: number;
	/** Mpc. */
	distance: number;
	/** Degrees (90 = edge-on). */
	inclination: number;
	/** Total luminosity at 3.6 µm, 10⁹ L☉. */
	lum36: number;
	/** Bulge luminosity at 3.6 µm, 10⁹ L☉ (included in lum36). */
	lumBulge: number;
	/** Atomic hydrogen mass, 10⁹ M☉ (without helium). */
	mHI: number;
	/** Speed of the flat outer part, km/s. */
	vFlat: number;
	/** 1 = high, 2 = medium, 3 = low. */
	quality: number;
	refs: string;
	points: readonly (readonly [number, number, number, number, number, number])[];
}

export const SPARC = {
${body}
} as const satisfies Record<string, SparcGalaxy>;
`;
writeFileSync(OUT, ts);
console.log(`wrote ${OUT}: ${out.map((g) => `${g.id} ${g.points.length}`).join(', ')}`);
