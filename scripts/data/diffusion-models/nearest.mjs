/**
 * For every finished digit the diffusion-models page shows (the last frame of each run in
 * src/routes/diffusion-models/mnist-sequences.ts), finds the nearest of MNIST's 60,000 training
 * digits, and, as the yardstick, does the same for all 10,000 test digits (which the network never
 * saw). Writes src/routes/diffusion-models/mnist-nearest.ts, which backs the page's "generated,
 * not copied" note (checked in e2e/diffusion-models-model.e2e.ts). It does not need the trained
 * weights, only the shipped digits and MNIST:
 *
 *   node scripts/data/diffusion-models/train.mjs nearest <cache dir>
 *
 * (sequences.mjs runs it too, on the runs it has just sampled.) About 3 minutes on one core.
 *
 * Distance: Euclidean, over the 784 pixels on the network's scale (−1 = black paper, 1 = white
 * ink), so 0 = the same image and 56 = every pixel inverted; one pixel flipped from paper to ink
 * alone adds 2. The generated digits are stored with 16 grey levels, so the training and test
 * digits are first rounded to the same 16 levels (v ↦ round(v / 255 · 15)): all three are
 * compared at the same precision.
 */
import fs from 'node:fs';
import path from 'node:path';
import { loadMnist } from './mnist.mjs';

const OUT = path.resolve(
	import.meta.dirname,
	'../../../src/routes/diffusion-models/mnist-nearest.ts'
);
const PX = 784;

/** MNIST bytes (0 … 255) → the 16 levels of the shipped digits, as nibbles 0 … 15. */
const levels = (bytes) => Uint8Array.from(bytes, (v) => Math.round((v / 255) * 15));

/** A shipped 4-bit image (base64, two pixels per byte, high nibble first) → nibbles. */
const unpack = (b64) => {
	const b = Buffer.from(b64, 'base64');
	const out = new Uint8Array(b.length * 2);
	for (let i = 0; i < b.length; i++) {
		out[2 * i] = b[i] >> 4;
		out[2 * i + 1] = b[i] & 15;
	}
	return out;
};
const pack = (nib) => {
	const out = new Uint8Array(nib.length / 2);
	for (let i = 0; i < nib.length; i += 2) out[i / 2] = (nib[i] << 4) | nib[i + 1];
	return Buffer.from(out).toString('base64');
};

/**
 * Nearest training digit to `x` (nibbles): its index and the distance. Nibble differences are
 * scaled by 2 / 15 (one level on the [−1, 1] scale) at the end.
 */
function nearestOf(train, x, off = 0) {
	let best = Infinity;
	let at = -1;
	for (let j = 0; j < train.n; j++) {
		const o = j * PX;
		let s = 0;
		for (let p = 0; p < PX; p++) {
			const d = x[off + p] - train.q[o + p];
			s += d * d;
			if (s >= best) break;
		}
		if (s < best) {
			best = s;
			at = j;
		}
	}
	return { index: at, distance: (Math.sqrt(best) * 2) / 15 };
}

const round3 = (v) => Math.round(v * 1000) / 1000;

/** `runs`: the SEQUENCES to check (default: the shipped ones). */
export async function nearest(cache, runs) {
	if (!runs)
		({ SEQUENCES: runs } = await import('../../../src/routes/diffusion-models/mnist-sequences.ts'));
	const tr = await loadMnist(cache, 'train');
	const te = await loadMnist(cache, 'test');
	const train = { n: tr.n, q: levels(tr.pixels) };
	const started = Date.now();

	const NEAREST = runs.map((r) => {
		const x = unpack(r.frames[r.frames.length - 1].x);
		const { index, distance } = nearestOf(train, x);
		return {
			digit: r.digit,
			seed: r.seed,
			guidance: r.guidance,
			steps: r.steps,
			distance: round3(distance),
			index,
			label: tr.labels[index],
			pixels: pack(train.q.subarray(index * PX, (index + 1) * PX))
		};
	});

	const test = levels(te.pixels);
	const by = Array.from({ length: 10 }, () => []);
	for (let k = 0; k < te.n; k++) {
		by[te.labels[k]].push(nearestOf(train, test, k * PX).distance);
		if (k % 500 === 499)
			process.stdout.write(
				`\rtest digits: ${k + 1} of ${te.n}, ${Math.round((Date.now() - started) / 1000)} s  `
			);
	}
	console.log();
	const TEST = by.map((d, digit) => {
		const s = d.sort((a, b) => a - b);
		return {
			digit,
			n: s.length,
			mean: round3(s.reduce((a, v) => a + v, 0) / s.length),
			// percentile k (0 = the nearest-to-training test digit, 100 = the farthest), by rank
			percentiles: Array.from({ length: 101 }, (_, k) =>
				round3(s[Math.round((k / 100) * (s.length - 1))])
			)
		};
	});

	const out = `/**
 * GENERATED by scripts/data/diffusion-models/nearest.mjs — do not edit by hand.
 *
 * How far each finished digit of ./mnist-sequences.ts (the last frame of each run, in the same
 * order) is from the nearest of MNIST's 60,000 training digits, and the same for MNIST's 10,000
 * test digits, which the network never saw (MNIST: Yann LeCun, Corinna Cortes and Christopher
 * J. C. Burges, http://yann.lecun.com/exdb/mnist/; LeCun et al., Proc. IEEE 86, 2278–2324,
 * 1998; fetched from https://ossci-datasets.s3.amazonaws.com/mnist/, the files' SHA-256 sums in
 * scripts/data/diffusion-models/mnist.mjs; the original page states no licence). Used by the
 * tests, not by the page.
 *
 * Distance: Euclidean over the 784 pixels on the network's scale (−1 = paper, 1 = ink): 0 = the
 * same image, 56 = every pixel inverted. Training and test digits are rounded to the 16 grey
 * levels the generated digits are stored with before comparing.
 * NEAREST: per run, the distance, and the index (in the training set), label and pixels (4 bits
 * per pixel, as in ./mnist-sequences.ts) of the nearest training digit.
 * TEST: per digit, how many test digits, their mean distance to the nearest training digit, and
 * its percentiles 0 … 100 (0 = the closest test digit, 100 = the farthest).
 */

export interface Nearest {
	digit: number;
	seed: number;
	guidance: number;
	steps: number;
	distance: number;
	index: number;
	label: number;
	pixels: string;
}
export interface TestNearest {
	digit: number;
	n: number;
	mean: number;
	percentiles: number[];
}

export const NEAREST: Nearest[] = ${JSON.stringify(NEAREST)};
export const TEST: TestNearest[] = ${JSON.stringify(TEST)};
`;
	fs.writeFileSync(OUT, out);
	console.log(
		`wrote ${OUT} (${Math.round(out.length / 1024)} KB) in ${Math.round((Date.now() - started) / 1000)} s; run prettier on it`
	);
}
