#!/usr/bin/env node
// Builds the temperature and oxygen records of the deep-time explainer
// (src/routes/deep-time/data/records.ts) from raw downloads. No dependencies (uses the `unzip`
// command to read the spreadsheet). Usage:
//
//   node scripts/data/deep-time/records.mjs <raw-dir>
//
// <raw-dir> must contain (download them there first, outside the repository):
//
//   PhanDA_GMSTandCO2_percentiles.csv
//     https://raw.githubusercontent.com/EJJudd/PhanDA/main/5_Outputs/PhanDA_GMSTandCO2_percentiles.csv
//     Judd, E.J., Tierney, J.E., Lunt, D.J., Montañez, I.P., Huber, B.T., Wing, S.L. & Valdes, P.J.
//     (2024), A 485-million-year history of Earth's surface temperature, Science 385, eadk3705,
//     doi:10.1126/science.adk3705. The repository states no licence.
//   Mills_etal_2023_AREPS_O2.xlsx
//     https://raw.githubusercontent.com/bjwmills/AREPS_2023_O2_estimate/main/Mills_etal_2023_AREPS_O2.xlsx
//     Mills, B.J.W., Krause, A.J., Jarvis, I. & Cramer, B.D. (2023), Evolution of atmospheric O2
//     through the Phanerozoic, revisited, Annual Review of Earth and Planetary Sciences 51,
//     253–276, doi:10.1146/annurev-earth-032320-095425 (the paper is CC BY 4.0; the data
//     repository, which the paper points to for download, states no licence).
//
// What the script does:
// - temperature: PhanDA's global mean surface temperature, one value per geological stage (85
//   stages, from the Holocene back to the Tremadocian, 487 Ma): the stage's age range (Ma) and
//   the 5th, 16th, 50th, 84th and 95th percentiles of the reconstruction (°C), rounded to 0.1.
// - oxygen: Mills et al.'s consensus curve of atmospheric O2 (% of the air by volume), best
//   guess and the low and high ends of the uncertainty window, every 1 Myr from 541 Ma to the
//   present, rounded to 0.1.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const raw = process.argv[2];
if (!raw) {
	console.error('usage: node scripts/data/deep-time/records.mjs <raw-dir>');
	process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../src/routes/deep-time/data');
mkdirSync(out, { recursive: true });
const r1 = (v) => Math.round(v * 10) / 10;
const r3 = (v) => Math.round(v * 1000) / 1000;

// ---------------------------------------------------------------- PhanDA
const csv = readFileSync(join(raw, 'PhanDA_GMSTandCO2_percentiles.csv'), 'utf8').trim().split('\n');
const head = csv[0].split(',');
const col = (row, name) => row[head.indexOf(name)];
const stages = csv.slice(1).map((line) => {
	const row = line.split(',');
	return [
		col(row, 'Stage'),
		r3(Number(col(row, 'UpperAge'))),
		r3(Number(col(row, 'LowerAge'))),
		...['GMST_05', 'GMST_16', 'GMST_50', 'GMST_84', 'GMST_95'].map((n) => r1(Number(col(row, n))))
	];
});

// ---------------------------------------------------------------- Mills et al. 2023
const xml = execFileSync(
	'unzip',
	['-p', join(raw, 'Mills_etal_2023_AREPS_O2.xlsx'), 'xl/worksheets/sheet1.xml'],
	{
		encoding: 'utf8',
		maxBuffer: 1 << 26
	}
);
const rows = [...xml.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)].map((m) =>
	[...m[1].matchAll(/<c [^>]*?(?:\/>|>([\s\S]*?)<\/c>)/g)].map(
		(c) => /<v>([^<]*)<\/v>/.exec(c[1] ?? '')?.[1]
	)
);
const o2 = [];
for (const r of rows) {
	const [time, mid, min, max] = r.map(Number);
	// the header row holds shared-string indices, not numbers; ages are negative (Ma before present)
	if (![time, mid, min, max].every(Number.isFinite) || time > 0) continue;
	o2.push([-time, r1(mid), r1(min), r1(max)]);
}
o2.sort((a, b) => a[0] - b[0]);

const body = `// Generated by scripts/data/deep-time/records.mjs — do not edit by hand.
// Temperature: PhanDA, Judd et al. (2024), A 485-million-year history of Earth's surface
// temperature, Science 385, eadk3705, doi:10.1126/science.adk3705; file
// 5_Outputs/PhanDA_GMSTandCO2_percentiles.csv of https://github.com/EJJudd/PhanDA (no licence
// stated; cited as the authors ask). Stage ages are those PhanDA uses (Geologic Time Scale 2020).
// Oxygen: Mills et al. (2023), Evolution of atmospheric O2 through the Phanerozoic, revisited,
// Annu. Rev. Earth Planet. Sci. 51, 253–276, doi:10.1146/annurev-earth-032320-095425 (CC BY 4.0);
// data set https://github.com/bjwmills/AREPS_2023_O2_estimate (no licence stated).

/** PhanDA global mean surface temperature by stage, youngest first: [stage, top (Ma), base (Ma),
 * 5th, 16th, 50th, 84th, 95th percentile (°C)]. */
export const GMST: [string, number, number, number, number, number, number, number][] = ${JSON.stringify(stages)};

/** Atmospheric O₂, % of the air by volume, every 1 Myr: [age (Ma), best guess, low, high]. */
export const O2: [number, number, number, number][] = ${JSON.stringify(o2)};
`;
writeFileSync(join(out, 'records.ts'), body);
console.log(
	`stages ${stages.length}, O2 rows ${o2.length} (${o2[0][0]}–${o2[o2.length - 1][0]} Ma), bytes ${body.length}`
);
