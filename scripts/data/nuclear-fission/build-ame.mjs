#!/usr/bin/env node
/**
 * Builds `src/routes/nuclear-fission/ame2020.ts`: binding energies per nucleon and mass
 * excesses from the 2020 Atomic Mass Evaluation.
 *
 *   curl -o /tmp/ame/mass_1.mas20.txt https://www-nds.iaea.org/amdc/ame2020/mass_1.mas20.txt
 *   node scripts/data/nuclear-fission/build-ame.mjs /tmp/ame/mass_1.mas20.txt
 *
 * Source: Atomic Mass Data Center (IAEA), AME2020, file `mass_1.mas20.txt` (unrounded
 * values), https://www-nds.iaea.org/amdc/. Citation: W.J. Huang, M. Wang, F.G. Kondev,
 * G. Audi and S. Naimi, Chinese Physics C 45, 030002 (2021); M. Wang, W.J. Huang,
 * F.G. Kondev, G. Audi and S. Naimi, Chinese Physics C 45, 030003 (2021). The tables are
 * published for free use; the papers are open access (CC BY 3.0), the data file states no licence,
 * so cite the papers above.
 *
 * Subset:
 *   - `curve`: for every mass number A from 2 to the largest measured, the nuclide with the
 *     largest experimental binding energy per nucleon (values the AME marks as estimated,
 *     with `#`, are skipped). That is the bottom of the valley of stability, the curve
 *     textbooks plot.
 *   - `nuclides`: mass excess (keV) and binding energy per nucleon (keV) of the nuclides the
 *     explainer names: the neutron, light nuclei, the iron peak, the fissile and fertile
 *     actinides, the fission fragments of the splits it shows and the stable nuclei their
 *     beta decays end on.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = process.argv[2];
if (!file) {
	console.error('usage: node scripts/data/nuclear-fission/build-ame.mjs <mass_1.mas20.txt>');
	process.exit(1);
}
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/nuclear-fission/ame2020.ts');
const lines = readFileSync(file, 'utf8').split('\n');
if (!lines.some((l) => l.includes('Ame2020'))) throw new Error('not the AME2020 mass table');

// Fortran format a1,i3,i5,i5,i5,1x,a3,a4,1x,f14.6,f12.6,f13.5,1x,f10.5,...
const start = lines.findIndex((l) => /^0\s+1\s+1\s+0\s+1\s+n\b/.test(l));
if (start < 0) throw new Error('data start not found');
const rows = [];
for (const l of lines.slice(start)) {
	if (l.trim().length < 60) continue;
	const N = Number(l.slice(4, 9));
	const Z = Number(l.slice(9, 14));
	const A = Number(l.slice(14, 19));
	const el = l.slice(20, 23).trim();
	const me = l.slice(28, 42).trim();
	const ba = l.slice(54, 67).trim();
	if (!Number.isInteger(A) || N + Z !== A) throw new Error(`bad row: ${l}`);
	rows.push({
		A,
		Z,
		el,
		massExcess: me.includes('#') ? NaN : Number(me),
		perNucleon: ba.includes('#') || ba.includes('*') ? NaN : Number(ba)
	});
}

const curve = [];
for (let A = 2; A <= 300; A++) {
	const best = rows
		.filter((r) => r.A === A && Number.isFinite(r.perNucleon))
		.sort((a, b) => b.perNucleon - a.perNucleon)[0];
	if (best) curve.push(best);
}

const named = [
	['n', 1],
	['H', 1],
	['H', 2],
	['He', 4],
	['Li', 6],
	['C', 12],
	['O', 16],
	['Fe', 56],
	['Ni', 62],
	['Kr', 92],
	['Zr', 92],
	['Zr', 94],
	['Zr', 96],
	['Rb', 96],
	['Sr', 94],
	['Cs', 137],
	['Xe', 140],
	['Ba', 141],
	['Ba', 137],
	['Ce', 140],
	['Pr', 141],
	['Pb', 208],
	['U', 235],
	['U', 236],
	['U', 238],
	['Pu', 239]
];
const nuclides = named.map(([el, A]) => {
	const r = rows.find((x) => x.el === el && x.A === A);
	if (!r || !Number.isFinite(r.massExcess)) throw new Error(`missing ${el}-${A}`);
	return r;
});

const key = (r) => (r.el === 'n' ? 'n' : `${r.el}${r.A}`);
const out = `// Generated by scripts/data/nuclear-fission/build-ame.mjs — do not edit by hand.
//
// Source: AME2020 atomic mass evaluation, Atomic Mass Data Center (IAEA),
// https://www-nds.iaea.org/amdc/ (file mass_1.mas20.txt, unrounded values).
// Citation: W.J. Huang et al., Chinese Physics C 45, 030002 (2021); M. Wang et al.,
// Chinese Physics C 45, 030003 (2021), open access (CC BY 3.0); the data file itself states no
// licence and is published for free use, so the papers are cited.
//
// \`curve\`: for each mass number A, the nuclide with the largest experimental binding energy
// per nucleon (estimated '#' values skipped): [A, Z, element, B/A in keV].
// \`nuclides\`: atomic mass excess and binding energy per nucleon, in keV, of the nuclides the
// explainer names.

/** [A, Z, element, binding energy per nucleon in keV] for the most bound nuclide of each A. */
export const curve: readonly (readonly [number, number, string, number])[] = [
${curve.map((r) => `\t[${r.A}, ${r.Z}, '${r.el}', ${r.perNucleon}]`).join(',\n')}
];

export interface Nuclide {
	A: number;
	Z: number;
	element: string;
	/** Atomic mass excess, keV. */
	massExcess: number;
	/** Binding energy per nucleon, keV (0 for the neutron and hydrogen-1). */
	perNucleon: number;
}

export const nuclides = {
${nuclides
	.map(
		(r) =>
			`\t${key(r)}: { A: ${r.A}, Z: ${r.Z}, element: '${r.el}', massExcess: ${r.massExcess}, perNucleon: ${r.perNucleon} }`
	)
	.join(',\n')}
} as const satisfies Record<string, Nuclide>;
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${curve.length} curve points, ${nuclides.length} nuclides`);
