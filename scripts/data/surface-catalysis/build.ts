// Builds src/routes/surface-catalysis/curves-data.ts: the steady-state CO₂ rate and coverages of
// the ZGB model measured with the page's own lattice (`steady` in its `zgb.ts`) on a 64 × 64
// surface, and the mean-field rate equations of the same moves (`meanField`), over a grid of CO
// fractions y, for each CO desorption probability k the page offers. Each lattice point averages
// two runs with their own seeds, each started from an empty surface: 1,000 MCS to settle, then
// the averages over the next 2,000 MCS. Near y₂ the reactive state is metastable, so there the
// numbers depend on this protocol (a longer run poisons sooner); the page says so.
//
// No external data: everything is computed. Usage (Node ≥ 23 runs TypeScript directly; about
// two minutes on 6 workers):
//   node scripts/data/surface-catalysis/build.ts [workers]
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { meanField, steady, type SteadyState } from '../../../src/routes/surface-catalysis/zgb.ts';

interface Job {
	k: number;
	y: number;
	seed: number;
}

const round = (v: number, d: number) => Number(v.toFixed(d));
const K_VALUES = [0, 0.02, 0.05, 0.1, 0.2];
const SEEDS = 2;

if (isMainThread) {
	const grid = (a: number, b: number, d: number) =>
		Array.from({ length: Math.round((b - a) / d) + 1 }, (_, i) => round(a + i * d, 3));
	const ys = [...grid(0, 0.34, 0.02), ...grid(0.35, 0.65, 0.005), ...grid(0.66, 1, 0.02)];
	const jobs: Job[] = [];
	K_VALUES.forEach((k, a) =>
		ys.forEach((y, i) => {
			for (let s = 0; s < SEEDS; s++) jobs.push({ k, y, seed: 1 + 100000 * a + 100 * i + s });
		})
	);
	const workers = Number(process.argv[2]) || Math.max(1, Math.min(6, availableParallelism() - 1));
	const results = new Map<string, SteadyState[]>();
	let next = 0;
	let done = 0;
	await Promise.all(
		Array.from({ length: workers }, async () => {
			const worker = new Worker(new URL(import.meta.url), { workerData: null });
			for (;;) {
				const job = jobs[next++];
				if (!job) break;
				const res = await new Promise<SteadyState>((resolve) => {
					worker.once('message', resolve);
					worker.postMessage(job);
				});
				const key = `${job.k}|${job.y}`;
				results.set(key, [...(results.get(key) ?? []), res]);
				if (++done % 100 === 0) console.log(`${done} / ${jobs.length} runs done`);
			}
			await worker.terminate();
		})
	);
	const mean = (rs: SteadyState[], q: keyof SteadyState) =>
		rs.reduce((s, r) => s + r[q], 0) / rs.length;
	const out = K_VALUES.map((k) => {
		const rows = ys.map((y) => results.get(`${k}|${y}`)!);
		const mf = ys.map((y) => meanField(y, k));
		return {
			k,
			y: ys,
			rate: rows.map((r) => round(mean(r, 'rate'), 4)),
			co: rows.map((r) => round(mean(r, 'co'), 4)),
			o: rows.map((r) => round(mean(r, 'o'), 4)),
			mfRate: mf.map((r) => round(r.rate, 4)),
			mfCo: mf.map((r) => round(r.co, 4)),
			mfO: mf.map((r) => round(r.o, 4))
		};
	});
	const file = `// Generated by scripts/data/surface-catalysis/build.ts from the page's own lattice and mean-field
// rate equations (zgb.ts): the steady CO₂ rate (per site per MCS) and the CO and O coverages
// against the CO fraction y, for each CO desorption probability k. Do not edit by hand.
import type { Curve } from './curves.ts';

export const CURVES: Curve[] = ${JSON.stringify(out)};
`;
	writeFileSync(
		new URL('../../../src/routes/surface-catalysis/curves-data.ts', import.meta.url),
		file
	);
	console.log('wrote curves-data.ts');
} else {
	void workerData;
	parentPort!.on('message', (job: Job) => {
		parentPort!.postMessage(steady(64, job.y, job.k, job.seed, 1000, 2000));
	});
}
