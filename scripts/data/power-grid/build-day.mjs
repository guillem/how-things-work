#!/usr/bin/env node
/**
 * Builds `src/routes/power-grid/day.ts`: one real day of electricity demand and generation on
 * the Spanish mainland grid, hour by hour.
 *
 *   curl -o ree-2025-04-09.jsonp 'https://demanda.ree.es/WSvisionaMovilesPeninsulaRest/resources/demandaGeneracionPeninsula?callback=cb&curva=DEMANDAAU&fecha=2025-04-09'
 *   node scripts/data/power-grid/build-day.mjs ree-2025-04-09.jsonp
 *
 * Source: Red Eléctrica (REE), "Seguimiento de la demanda de energía eléctrica" —
 * real-time demand and generation of the peninsular electricity system,
 * https://demanda.ree.es/visiona/peninsula/demandaau/tablas/2025-04-09/1 (the web service
 * behind that page, above). Five-minute values in MW, local time (CEST, UTC+2): checked
 * against REE's REData API (apidatos.ree.es, demanda-tiempo-real), whose timestamps carry
 * +02:00 and whose curve matches this one with no shift.
 *
 * Method: keep the 288 five-minute rows of 9 April 2025 (00:00–23:55), and average the 12
 * rows of each hour, so each value is that hour's mean power (its energy in MWh). Columns:
 * demand (dem); nuclear (nuc); combined-cycle gas (cc); coal (car); hydro generation, the net
 * hydro series minus pumping (hid − conb); pumping consumption (conb, ≤ 0); wind (eol); solar
 * PV (solFot); solar thermal (solTer); cogeneration, waste and biomass (cogenResto + bio); net
 * international exchanges (inter, > 0 import). Batteries (bat, consBat) stayed under 10 MW all
 * day and fuel/gas engines (gf) at 0, so they are left out. The listed sources add up to the
 * demand to within 53–378 MW (mean 230 MW, under 1.5%): REE's real-time data are provisional.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const [file] = process.argv.slice(2);
if (!file) throw new Error('usage: build-day.mjs ree-2025-04-09.jsonp');
const DATE = '2025-04-09';
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/power-grid/day.ts');

const text = readFileSync(file, 'utf8');
const rows = JSON.parse(
	text.slice(text.indexOf('(') + 1, text.lastIndexOf(')'))
).valoresHorariosGeneracion.filter((r) => r.ts.startsWith(DATE));
if (rows.length !== 288) throw new Error(`expected 288 rows for ${DATE}, got ${rows.length}`);

const cols = {
	demand: (r) => r.dem,
	nuclear: (r) => r.nuc,
	gas: (r) => r.cc,
	coal: (r) => r.car,
	hydro: (r) => r.hid - r.conb,
	pumping: (r) => r.conb,
	wind: (r) => r.eol,
	solarPV: (r) => r.solFot,
	solarThermal: (r) => r.solTer,
	other: (r) => r.cogenResto + r.bio,
	exchange: (r) => r.inter
};

const hours = [];
for (let h = 0; h < 24; h++) {
	const hr = rows.filter((r) => Number(r.ts.slice(11, 13)) === h);
	if (hr.length !== 12) throw new Error(`hour ${h}: ${hr.length} rows`);
	const o = { hour: h };
	for (const [k, f] of Object.entries(cols)) {
		o[k] = Math.round(hr.reduce((s, r) => s + f(r), 0) / hr.length);
	}
	hours.push(o);
}

const header = readFileSync(import.meta.filename, 'utf8')
	.split('\n')
	.slice(1)
	.join('\n')
	.match(/\/\*\*[\s\S]*?\*\//)[0]
	.replace(
		'Builds `src/routes/power-grid/day.ts`:',
		'Generated by `scripts/data/power-grid/build-day.mjs`:'
	);

const fields = Object.keys(cols);
const out = `${header}
// Reuse: REE's terms (www.ree.es/en/legal-notice-privacy-policy, §5.1) allow publication for
// information, academic and non-commercial purposes, citing Red Eléctrica as the source,
// without altering the data's meaning, and giving the date of the latest update. The
// demanda.ree.es feed carries no update date; REE's matching national real-time series
// (apidatos.ree.es, demanda-tiempo-real) for the day reports its last update as
// 2025-04-09T23:58 (CEST). Downloaded on 2026-10-15. Do not edit by hand.

export interface Hour {
	/** Start of the hour, local time (0–23). */
	hour: number;
${fields.map((f) => `\t${f}: number;`).join('\n')}
}

/** Mean power in each hour of Wednesday 9 April 2025, MW. */
export const DAY: Hour[] = [
${hours.map((o) => `\t{ ${['hour', ...fields].map((k) => `${k}: ${o[k]}`).join(', ')} }`).join(',\n')}
];
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
