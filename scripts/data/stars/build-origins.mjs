#!/usr/bin/env node
/**
 * Builds `src/routes/stars/origins.ts`: where the atoms of each element in the Solar System
 * were made, as shares of six sources.
 *
 *   node scripts/data/stars/build-origins.mjs path/to/Nucleosynthesis_periodic_table.svg
 *
 * Source: Jennifer A. Johnson (Ohio State University), "Origin of the elements in the Solar
 * System" (2017; SDSS blog, 9 January 2017,
 * https://web.archive.org/web/20220226100944/http://blog.sdss.org/2017/01/09/origin-of-the-elements-in-the-solar-system/;
 * later discussed in J. A. Johnson, Science 363, 474, 2019), CC BY-SA 4.0. Johnson published
 * the table as a picture, in which each element's square is shaded by its sources. The
 * numbers here come from the redrawing of that picture by C. M. G. Lee on Wikimedia Commons,
 * https://commons.wikimedia.org/wiki/File:Nucleosynthesis_periodic_table.svg (revision of
 * 2017-11-04, CC BY-SA 3.0), whose embedded Python script stores, for each element, its
 * sources and the position x of the boundary between the first two, read off Johnson's
 * picture. This script decodes them exactly as Lee's script does: the share of the first
 * source is 2x²/185² if 2x < 185, otherwise (4·185x − 2x² − 185²)/185²; with three sources,
 * that share is split 45/55 (helium) or 37/63 (lithium) between the first two. The shares are
 * therefore read off a picture: good to a few per cent, no better.
 *
 * Elements 43 (Tc), 61 (Pm) and 95–103 have no long-lived isotopes and are marked
 * `synthetic` (neptunium, 93, has none either, but Johnson shades it, like polonium to
 * plutonium, by where its parent nuclei were made); elements above 103 are not in the table.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = process.argv[2];
if (!file) throw new Error('usage: build-origins.mjs <Nucleosynthesis_periodic_table.svg>');
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/stars/origins.ts');

const svg = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const block = svg.match(/^datass = .*'''\n([\s\S]*?)'''/m)[1];
const rows = block
	.split('\n')
	.map((l) => l.split('|').map((f) => f.trim()))
	.filter((f) => f[0]);

const X_MAX = 185;
const SOURCES = {
	b: 'bigBang',
	j: 'cosmicRays',
	y: 'lowMass',
	g: 'massive',
	c: 'whiteDwarfs',
	o: 'mergers'
};

const out = rows.map((f, i) => {
	const z = i + 1;
	const symbol = f[0];
	const x = Number(f[3]);
	const codes = f[4].split('');
	if (codes[0] === 'z') return { z, symbol, synthetic: true, shares: {} };
	const a =
		(2 * x < X_MAX ? 2 * x * x : 4 * x * X_MAX - 2 * x * x - X_MAX * X_MAX) / (X_MAX * X_MAX);
	const fractions =
		codes.length === 1
			? [1]
			: codes.length === 2
				? [a, 1 - a]
				: z === 2
					? [a * 0.45, a * 0.55, 1 - a]
					: [a * 0.37, a * 0.63, 1 - a];
	const shares = Object.fromEntries(
		codes.map((c, k) => [SOURCES[c], Number(fractions[k].toFixed(3))])
	);
	return { z, symbol, synthetic: false, shares };
});
if (out.length !== 103 || out[25].symbol !== 'Fe') throw new Error('unexpected table');

const header = readFileSync(import.meta.filename, 'utf8').match(/\/\*\*[\s\S]*?\*\//)[0];
writeFileSync(
	OUT,
	`${header.replace('Builds `src/routes/stars/origins.ts`', 'Generated by `scripts/data/stars/build-origins.mjs`')}
// Generated file: do not edit by hand.

export const origins = ${JSON.stringify(out, null, '\t')} as const;
`
);
console.log('wrote', OUT, out.length, 'elements; Fe', JSON.stringify(out[25].shares));
