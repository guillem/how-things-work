#!/usr/bin/env node
/**
 * Builds `src/routes/gravitational-waves/gw150914.ts`: the strain of GW150914 as
 * plotted in Fig. 1 of the discovery paper, at both LIGO detectors, with the
 * numerical-relativity waveform that matches it.
 *
 *   node scripts/data/gravitational-waves/reduce.mjs <dir with the downloaded files>
 *
 * Source: Gravitational Wave Open Science Center (GWOSC), the data behind Fig. 1 of
 * B. P. Abbott et al. (LIGO Scientific Collaboration and Virgo Collaboration),
 * "Observation of Gravitational Waves from a Binary Black Hole Merger",
 * Phys. Rev. Lett. 116, 061102 (2016), https://gwosc.org/events/GW150914/ :
 *   https://gwosc.org/GW150914data/P150914/fig1-observed-H.txt
 *   https://gwosc.org/GW150914data/P150914/fig1-observed-L.txt
 *   https://gwosc.org/GW150914data/P150914/fig1-waveform-H.txt
 *   https://gwosc.org/GW150914data/P150914/fig1-waveform-L.txt
 * Licence: CC BY 4.0. The numerical-relativity waveform is SXS:BBH:0305 from the
 * SXS Gravitational Waveform Database (SXS Collaboration), filtered like the data.
 *
 * The files hold strain × 10²¹ against time in seconds after 2015-09-14 09:50:45 UTC,
 * 0.25–0.46 s, sampled at 16 384 Hz. As in the paper's figure they are band-passed
 * to 35–350 Hz and notch-filtered at the instruments' spectral lines (not whitened).
 * The observed Livingston data are neither shifted nor inverted.
 *
 * Subset: every second sample (8192 Hz, still far above the 350 Hz band edge, and a
 * rate Web Audio can play), values rounded to 4 significant figures. The waveform
 * files are on a slightly different time grid; they are interpolated linearly onto
 * the data's.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: reduce.mjs <dir with fig1-*.txt>');
const OUT = path.resolve(
	import.meta.dirname,
	'../../../src/routes/gravitational-waves/gw150914.ts'
);

/** @param {string} name @returns {number[][]} */
const read = (name) =>
	readFileSync(path.join(dir, name), 'utf8')
		.split('\n')
		.filter((l) => l.trim() && !l.startsWith('#'))
		.map((l) => l.trim().split(/\s+/).map(Number));

const H = read('fig1-observed-H.txt');
const L = read('fig1-observed-L.txt');
const WH = read('fig1-waveform-H.txt');
const WL = read('fig1-waveform-L.txt');

const STEP = 2;
const RATE = 16384 / STEP;
const T0 = H[0][0];
const times = H.filter((_, i) => i % STEP === 0).map((r) => r[0]);

/** Linear interpolation of a (t, y) table at time t. */
function at(table, t) {
	let i = 1;
	while (i < table.length - 1 && table[i][0] < t) i++;
	const [t0, y0] = table[i - 1];
	const [t1, y1] = table[i];
	const u = Math.min(1, Math.max(0, (t - t0) / (t1 - t0)));
	return y0 + (y1 - y0) * u;
}
const sig = (v) => Number(v.toPrecision(4));
const pick = (rows) => rows.filter((_, i) => i % STEP === 0).map((r) => sig(r[1]));
const onGrid = (table) => times.map((t) => sig(at(table, t)));

for (const [name, rows] of [
	['H', H],
	['L', L]
]) {
	if (rows.length !== H.length || rows.some((r, i) => Math.abs(r[0] - H[i][0]) > 1e-9))
		throw new Error(`${name}: unexpected time grid`);
}

const out = `// Generated by scripts/data/gravitational-waves/reduce.mjs — do not edit.
//
// GW150914 as plotted in Fig. 1 of B. P. Abbott et al. (LIGO Scientific and Virgo
// Collaborations), "Observation of Gravitational Waves from a Binary Black Hole Merger",
// Phys. Rev. Lett. 116, 061102 (2016). Data: Gravitational Wave Open Science Center,
// https://gwosc.org/events/GW150914/ (files fig1-observed-H/L.txt, fig1-waveform-H/L.txt),
// licence CC BY 4.0. Numerical-relativity waveform SXS:BBH:0305, SXS Collaboration.
//
// Strain × 10²¹, from ${T0} s after 2015-09-14 09:50:45 UTC, ${RATE} samples a second
// (every second sample of the published 16 384 Hz series), 4 significant figures.
// Band-passed to 35–350 Hz with notches at instrumental lines, as in the paper (not
// whitened). Livingston is not shifted or inverted.

/** Time of the first sample, in seconds after 09:50:45 UTC. */
export const T0 = ${T0};
/** Samples per second. */
export const RATE = ${RATE};

/** Hanford (H1), observed. */
export const hanford: readonly number[] = ${JSON.stringify(pick(H))};
/** Livingston (L1), observed. */
export const livingston: readonly number[] = ${JSON.stringify(pick(L))};
/** Numerical-relativity waveform as Hanford would record it. */
export const nrHanford: readonly number[] = ${JSON.stringify(onGrid(WH))};
/** Numerical-relativity waveform as Livingston would record it. */
export const nrLivingston: readonly number[] = ${JSON.stringify(onGrid(WL))};
`;
writeFileSync(OUT, out);
console.log(
	`wrote ${OUT}: ${times.length} samples per series, ${(out.length / 1024).toFixed(0)} KB`
);
