#!/usr/bin/env node
/**
 * Builds src/routes/hash-tables-bloom-filters/words.ts: the keys of the hash-table and Bloom-filter
 * page, real English words from Tiny Shakespeare (Karpathy's char-rnn, MIT; Shakespeare's text is
 * public domain), the file the ngram-text-models page already ships
 * (src/routes/ngram-text-models/tinyshakespeare.txt; fetch it with
 * scripts/data/ngram-text-models/fetch.mjs).
 *
 *   node scripts/data/hash-tables-bloom-filters/build.mjs
 *
 * The text is lower-cased and split into words: runs of the letters a–z, joined across inner
 * apostrophes. Words with an apostrophe ("thou'rt", "i'll") are dropped, and every other distinct
 * word that occurs at least twice is kept: 6,353 words. They are put in a
 * fixed random order (a Fisher–Yates shuffle driven by mulberry32 with seed 2026), so that the
 * first n words are a fair sample to insert and the last ones a disjoint sample to query.
 */
import fs from 'node:fs';

const SRC = new URL('../../../src/routes/ngram-text-models/tinyshakespeare.txt', import.meta.url);
const OUT = new URL('../../../src/routes/hash-tables-bloom-filters/words.ts', import.meta.url);
const SEED = 2026;

function mulberry32(seed) {
	let a = seed >>> 0;
	return () => {
		a = (a + 0x6d2b79f5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

const text = fs.readFileSync(SRC, 'utf8').toLowerCase();
const counts = new Map();
for (const w of text.match(/[a-z]+(?:'[a-z]+)*/g) ?? [])
	if (!w.includes("'")) counts.set(w, (counts.get(w) ?? 0) + 1);
const words = [...counts]
	.filter(([, n]) => n >= 2)
	.map(([w]) => w)
	.sort();
const rand = mulberry32(SEED);
for (let i = words.length - 1; i > 0; i--) {
	const j = Math.floor(rand() * (i + 1));
	[words[i], words[j]] = [words[j], words[i]];
}

const lines = [];
for (let i = 0; i < words.length; i += 16) lines.push(words.slice(i, i + 16).join(' '));
const body = `// Generated by scripts/data/hash-tables-bloom-filters/build.mjs; do not edit.
// The ${words.length.toLocaleString('en-US')} distinct words (lower-cased, letters a–z only) that occur at least twice in Tiny
// Shakespeare (Karpathy's char-rnn, https://github.com/karpathy/char-rnn, MIT; the plays are public
// domain), in a fixed random order (mulberry32 seed ${SEED}). See docs/DATA-SOURCES.md.
const RAW =
${lines.map((l, i) => `\t'${l}${i < lines.length - 1 ? ' ' : ''}'`).join(' +\n')};

/** The words, in their fixed random order. */
export const WORDS: readonly string[] = RAW.split(' ');
`;
fs.writeFileSync(OUT, body);
console.log(`wrote ${words.length} words to ${OUT.pathname}`);
