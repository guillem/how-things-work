// Builds src/routes/ising-model/curves-data.ts: thermal averages of the Ising model measured
// with the page's own Monte Carlo (`Lattice` and `measure` in its `ising.ts`), for square
// lattices of 8, 16, 32 and 64 spins on a side and rings of 16, 64, 256 and 1,024 spins, over
// a grid of temperatures. Each temperature is an independent run with its own seed, started
// from random spins: 500 updates to settle, then the averages over the next `meas` updates
// (one update = a Metropolis sweep plus about N spins' worth of Wolff clusters).
//
// No external data: everything is computed. Usage (Node ≥ 23 runs TypeScript directly; about
// three minutes on 10 cores):
//   node scripts/data/ising-model/build.ts [workers]
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { Lattice, measure, type Averages } from '../../../src/routes/ising-model/ising.ts';

interface Job {
	key: string;
	w: number;
	h: number;
	T: number;
	seed: number;
	meas: number;
}

const round = (v: number, d: number) => Number(v.toFixed(d));

if (isMainThread) {
	const grid = (a: number, b: number, d: number) =>
		Array.from({ length: Math.round((b - a) / d) + 1 }, (_, i) => round(a + i * d, 3));
	const square = grid(1, 3.6, 0.02);
	const ring = grid(0.1, 3.6, 0.05);
	const jobs: Job[] = [];
	const sets: { key: string; dim: 1 | 2; size: number; T: number[] }[] = [];
	for (const [L, meas] of [
		[8, 20000],
		[16, 20000],
		[32, 10000],
		[64, 6000]
	]) {
		sets.push({ key: `2d-${L}`, dim: 2, size: L, T: square });
		square.forEach((T, i) =>
			jobs.push({ key: `2d-${L}`, w: L, h: L, T, seed: 1000 * L + i + 1, meas })
		);
	}
	for (const N of [16, 64, 256, 1024]) {
		sets.push({ key: `1d-${N}`, dim: 1, size: N, T: ring });
		ring.forEach((T, i) =>
			jobs.push({ key: `1d-${N}`, w: N, h: 1, T, seed: 7 * N + i + 1, meas: 10000 })
		);
	}
	// biggest first, so the workers finish together
	jobs.sort((a, b) => b.w * b.h * b.meas - a.w * a.h * a.meas);
	const workers = Number(process.argv[2]) || Math.max(1, availableParallelism() - 1);
	const results = new Map<string, Averages>();
	let next = 0;
	await Promise.all(
		Array.from({ length: workers }, async () => {
			const worker = new Worker(new URL(import.meta.url), { workerData: null });
			for (;;) {
				const job = jobs[next++];
				if (!job) break;
				const res = await new Promise<Averages>((resolve) => {
					worker.once('message', resolve);
					worker.postMessage(job);
				});
				results.set(`${job.key}|${job.T}`, res);
				if (results.size % 50 === 0) console.log(`${results.size} runs done`);
			}
			await worker.terminate();
		})
	);
	const out = sets.map((s) => {
		const rows = s.T.map((T) => results.get(`${s.key}|${T}`)!);
		return {
			dim: s.dim,
			size: s.size,
			T: s.T,
			m: rows.map((r) => round(r.m, 4)),
			e: rows.map((r) => round(r.e, 4)),
			chi: rows.map((r) => round(r.chi, 3)),
			c: rows.map((r) => round(r.c, 4))
		};
	});
	const file = `// Generated by scripts/data/ising-model/build.ts from the page's own Monte Carlo
// (ising.ts): thermal averages per spin of the square lattice (dim 2, size L × L) and the ring
// (dim 1, size N), over a grid of temperatures (k·T / J). Do not edit by hand.
import type { Curve } from './curves.ts';

export const CURVES: Curve[] = ${JSON.stringify(out)};
`;
	writeFileSync(new URL('../../../src/routes/ising-model/curves-data.ts', import.meta.url), file);
	console.log('wrote curves-data.ts');
} else {
	void workerData;
	parentPort!.on('message', (job: Job) => {
		const lat = new Lattice(job.w, job.h, job.seed);
		parentPort!.postMessage(measure(lat, job.T, 500, job.meas));
	});
}
