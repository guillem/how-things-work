#!/usr/bin/env node
/**
 * Builds `src/routes/heat-pumps-refrigeration/data.ts`: saturation and vapour properties of three
 * refrigerants for the vapour-compression cycle.
 *
 *   node scripts/data/heat-pumps-refrigeration/build.mjs <download-dir>
 *
 * Source: NIST Chemistry WebBook, SRD 69, "Thermophysical Properties of Fluid Systems" (E.W.
 * Lemmon, I.H. Bell, M.L. Huber and M.O. McLinden; https://webbook.nist.gov/chemistry/fluid/),
 * each fluid's reference equation of state as used by NIST, default reference state:
 *   R-134a (1,1,1,2-tetrafluoroethane, C811972), propane (R-290, C74986), carbon dioxide (R-744,
 *   C124389).
 * For each: saturation from -40 °C to near the critical point in 2.5 K steps, and isobars at the
 * saturation pressures of -40, -35, ... °C (plus supercritical pressures for CO2), from the
 * boiling point (or 263 K above the critical pressure) to 460 K in 5 K steps.
 *
 * The files are downloaded into <download-dir> if they are not there yet (not committed).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const RAW = process.argv[2];
if (!RAW) {
	console.error('usage: build.mjs <download-dir>');
	process.exit(1);
}
mkdirSync(RAW, { recursive: true });
const OUT = resolve(import.meta.dirname, '../../../src/routes/heat-pumps-refrigeration/data.ts');

const BASE = 'https://webbook.nist.gov/cgi/fluid.cgi?Action=Data&Wide=on&Digits=6';
const UNITS =
	'&RefState=DEF&TUnit=K&PUnit=MPa&DUnit=kg%2Fm3&HUnit=kJ%2Fkg&WUnit=m%2Fs&VisUnit=uPa*s&STUnit=N%2Fm';

async function download(name, url) {
	const path = join(RAW, name);
	if (!existsSync(path)) {
		const res = await fetch(url);
		if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
		writeFileSync(path, await res.text());
		await new Promise((r) => setTimeout(r, 300));
	}
	return readFileSync(path, 'utf8');
}
function table(text) {
	const [head, ...rows] = text.trim().split('\n');
	const cols = head.split('\t');
	return rows.map((r) => {
		const cells = r.split('\t');
		return (name) => {
			const i = cols.findIndex((c) => c.startsWith(name));
			if (i < 0) throw new Error(`no column ${name} in ${cols.join(', ')}`);
			return cells[i];
		};
	});
}

const FLUIDS = [
	{ key: 'r134a', id: 'C811972', tHigh: 373.15, tc: 374.21, pc: 4.0593, extra: [] },
	{ key: 'propane', id: 'C74986', tHigh: 368.15, tc: 369.89, pc: 4.2512, extra: [] },
	{
		key: 'co2',
		id: 'C124389',
		tHigh: 303.15,
		tc: 304.13,
		pc: 7.3773,
		extra: [7.5, 8, 8.5, 9, 9.5, 10, 11, 12]
	}
];

const out = {};
for (const f of FLUIDS) {
	// NIST names saturation tables by what is held fixed per row: SatP steps the temperature.
	const sat = table(
		await download(
			`${f.key}-sat.tsv`,
			`${BASE}&ID=${f.id}&Type=SatP&TLow=233.15&THigh=${f.tHigh}&TInc=2.5${UNITS}`
		)
	).map((r) => [
		+r('Temperature'),
		+r('Pressure'),
		+r('Enthalpy (l'),
		+r('Enthalpy (v'),
		+r('Entropy (l'),
		+r('Entropy (v')
	]);
	const pressures = sat
		.filter((row) => {
			const k = (row[0] - 233.15) / 5;
			return Math.abs(k - Math.round(k)) < 1e-6;
		})
		.map((row) => row[1])
		.concat(f.extra);
	const isobars = [];
	for (const p of pressures) {
		const tLow = p > f.pc ? 263.15 : 233.15;
		const rows = table(
			await download(
				`${f.key}-isobar-${p}.tsv`,
				`${BASE}&ID=${f.id}&Type=IsoBar&P=${p}&TLow=${tLow}&THigh=460&TInc=5${UNITS}`
			)
		)
			.filter((r) => (p > f.pc ? true : r('Phase') === 'vapor'))
			.map((r) => [+r('Temperature'), +r('Enthalpy'), +r('Entropy')])
			// The isobar's pressure is a saturation pressure on the 5 K grid, so NIST lists the
			// saturated vapour and the grid point at the same temperature: keep one.
			.filter((row, i, all) => i === 0 || Math.abs(row[0] - all[i - 1][0]) > 1e-3);
		isobars.push([p, rows]);
	}
	out[f.key] = { tc: f.tc, pc: f.pc, sat, isobars };
}

const fmt = (rows, indent) => rows.map((r) => `[${r.join(', ')}]`).join(`,\n${indent}`);
const fluid = (k) => `{
		tc: ${out[k].tc},
		pc: ${out[k].pc},
		sat: [
			${fmt(out[k].sat, '\t\t\t')}
		],
		isobars: [
			${out[k].isobars.map(([p, rows]) => `[${p}, [\n\t\t\t\t${fmt(rows, '\t\t\t\t')}\n\t\t\t]]`).join(',\n\t\t\t')}
		]
	}`;
writeFileSync(
	OUT,
	`/**
 * Refrigerant properties for the vapour-compression cycle. Generated by
 * scripts/data/heat-pumps-refrigeration/build.mjs; do not edit by hand.
 *
 * Source: NIST Chemistry WebBook, SRD 69 (Lemmon, Bell, Huber and McLinden), R-134a, propane and
 * carbon dioxide, default reference states; retrieved 2026-10-20. Terms: © U.S. Secretary of
 * Commerce on behalf of the U.S.A.; NIST Standard Reference Data under the Standard Reference Data Act.
 * Units: K, MPa, kJ/kg, kJ/(kg·K). Each fluid has its own enthalpy and entropy zero.
 */

export interface FluidData {
	/** Critical temperature (K) and pressure (MPa). */
	tc: number;
	pc: number;
	/** Saturation: T, p, hf, hg, sf, sg. */
	sat: readonly (readonly number[])[];
	/** Isobars (MPa) of vapour (or supercritical fluid): rows of T, h, s. */
	isobars: readonly (readonly [number, readonly (readonly number[])[]])[];
}

export const FLUIDS: Record<'r134a' | 'propane' | 'co2', FluidData> = {
	r134a: ${fluid('r134a')},
	propane: ${fluid('propane')},
	co2: ${fluid('co2')}
};
`
);
console.log(`wrote ${OUT}`);
