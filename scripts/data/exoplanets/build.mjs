#!/usr/bin/env node
/**
 * Builds `src/routes/exoplanets/archive.ts`: a few real planets and the count of
 * known planets by discovery method and year, from the NASA Exoplanet Archive.
 *
 *   node scripts/data/exoplanets/build.mjs
 *
 * Source: NASA Exoplanet Archive, Planetary Systems Composite Parameters table
 * (`pscomppars`), queried through its TAP service,
 * https://exoplanetarchive.ipac.caltech.edu/TAP/sync (NASA Exoplanet Science
 * Institute, doi:10.26133/NEA13). The composite table takes each parameter from
 * one paper (the archive's default choice), so different values of one planet
 * may come from different papers: the script keeps each value's reference.
 * Public data; the archive asks users to acknowledge it (see the header written
 * into the output).
 *
 * Subset: (1) six planets chosen for the explainer, with their orbit, size, mass,
 * the measured transit depth and radial-velocity amplitude, and their star;
 * (2) the number of planets per discovery year and method, all planets.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const TAP = 'https://exoplanetarchive.ipac.caltech.edu/TAP/sync';
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/exoplanets/archive.ts');
const NAMES = [
	'51 Peg b',
	'HD 209458 b',
	'HD 189733 b',
	'Kepler-22 b',
	'Kepler-452 b',
	'Kepler-186 f',
	'TRAPPIST-1 e',
	'Proxima Cen b'
];
const COLS = [
	'pl_name',
	'discoverymethod',
	'disc_year',
	'pl_orbper',
	'pl_orbsmax',
	'pl_rade',
	'pl_bmasse',
	'pl_bmassprov',
	'pl_bmasselim',
	'pl_orbincl',
	'pl_orbeccen',
	'pl_rvamp',
	'pl_trandep',
	'pl_insol',
	'st_teff',
	'st_rad',
	'st_mass',
	'st_lum',
	'sy_dist',
	'st_spectype',
	'pl_orbper_reflink',
	'pl_rade_reflink',
	'pl_bmasse_reflink',
	'pl_orbincl_reflink',
	'pl_rvamp_reflink',
	'pl_trandep_reflink',
	'st_rad_reflink',
	'st_mass_reflink',
	'st_teff_reflink'
];

const planetsQuery = `select ${COLS.join(',')} from pscomppars where pl_name in (${NAMES.map((n) => `'${n}'`).join(',')})`;
const censusQuery =
	'select disc_year,discoverymethod,count(*) as n from pscomppars group by disc_year,discoverymethod';

async function tap(query) {
	const url = `${TAP}?query=${encodeURIComponent(query)}&format=json`;
	const res = await fetch(url);
	if (!res.ok) throw new Error(`${res.status} ${url}`);
	return { url, rows: await res.json() };
}

/** The reference's name from the archive's `<a href=…>Name</a>` link; `null` for "Calculated Value". */
function ref(link) {
	if (!link) return null;
	const text = link.replace(/<[^>]*>/g, '').trim();
	const name = text
		.replace(/&aacute;/g, 'á')
		.replace(/&ntilde;/g, 'ñ')
		.replace(/&eacute;/g, 'é')
		.replace(/&[a-z]+;/g, '');
	return name === 'Calculated Value' ? 'calculated by the archive' : name;
}

const planets = await tap(planetsQuery);
const census = await tap(censusQuery);
const fetched = new Date().toISOString().slice(0, 10);

const out = planets.rows
	.sort((a, b) => NAMES.indexOf(a.pl_name) - NAMES.indexOf(b.pl_name))
	.map((r) => ({
		name: r.pl_name,
		method: r.discoverymethod,
		year: r.disc_year,
		period: r.pl_orbper,
		a: r.pl_orbsmax,
		radius: r.pl_rade,
		mass: r.pl_bmasse,
		massKind: r.pl_bmassprov,
		massIsUpperLimit: r.pl_bmasselim === 1,
		incl: r.pl_orbincl,
		ecc: r.pl_orbeccen,
		rvAmp: r.pl_rvamp,
		depthPercent: r.pl_trandep,
		insolation: r.pl_insol,
		star: {
			teff: r.st_teff,
			radius: r.st_rad,
			mass: r.st_mass,
			logLum: r.st_lum,
			spectralType: r.st_spectype,
			distancePc: r.sy_dist
		},
		refs: {
			period: ref(r.pl_orbper_reflink),
			radius: ref(r.pl_rade_reflink),
			mass: ref(r.pl_bmasse_reflink),
			incl: ref(r.pl_orbincl_reflink),
			rvAmp: ref(r.pl_rvamp_reflink),
			depth: ref(r.pl_trandep_reflink),
			starRadius: ref(r.st_rad_reflink),
			starMass: ref(r.st_mass_reflink),
			starTeff: ref(r.st_teff_reflink)
		}
	}));

// Census: methods folded into five groups; years as [year, transit, rv, microlensing, imaging, other].
const GROUP = {
	Transit: 1,
	'Radial Velocity': 2,
	Microlensing: 3,
	Imaging: 4
};
const byYear = new Map();
const byMethod = {};
for (const r of census.rows) {
	byMethod[r.discoverymethod] = (byMethod[r.discoverymethod] ?? 0) + r.n;
	const row = byYear.get(r.disc_year) ?? [r.disc_year, 0, 0, 0, 0, 0];
	row[GROUP[r.discoverymethod] ?? 5] += r.n;
	byYear.set(r.disc_year, row);
}
const years = [...byYear.values()].sort((a, b) => a[0] - b[0]);
const total = Object.values(byMethod).reduce((s, n) => s + n, 0);

const ts = `/**
 * Real planets and the census of known planets, from the NASA Exoplanet Archive.
 * Generated by \`scripts/data/exoplanets/build.mjs\` on ${fetched}; do not edit by hand.
 *
 * Source: NASA Exoplanet Archive, Planetary Systems Composite Parameters table
 * (pscomppars), NASA Exoplanet Science Institute, doi:10.26133/NEA13, TAP queries
 *   ${planets.url}
 *   ${census.url}
 * "This research has made use of the NASA Exoplanet Archive, which is operated by the
 * California Institute of Technology, under contract with the National Aeronautics and
 * Space Administration under the Exoplanet Exploration Program."
 *
 * Units: period in days, a in AU, radius in Earth radii, mass in Earth masses,
 * incl in degrees, rvAmp in m/s, depthPercent in %, insolation in Earth fluxes;
 * star radius and mass in solar units, logLum = log₁₀(L/L☉), teff in K, distance in pc.
 * \`null\`: not in the table. A reference "calculated by the archive" means the
 * archive derived the value (for example a radius from a mass–radius relation): it
 * was not measured. \`massKind\` is "Mass" (true mass), "Msini" (minimum mass) or
 * "M-R relationship" (estimated from the radius); \`massIsUpperLimit\`: only an
 * upper limit is known.
 */

export interface ArchiveStar {
	teff: number;
	radius: number;
	mass: number;
	logLum: number;
	spectralType: string | null;
	distancePc: number;
}

export interface ArchivePlanet {
	name: string;
	method: string;
	year: number;
	period: number;
	a: number;
	radius: number;
	mass: number;
	massKind: string;
	massIsUpperLimit: boolean;
	incl: number | null;
	ecc: number | null;
	rvAmp: number | null;
	depthPercent: number | null;
	insolation: number | null;
	star: ArchiveStar;
	refs: Record<string, string | null>;
}

export const FETCHED = '${fetched}';

export const ARCHIVE_PLANETS: ArchivePlanet[] = ${JSON.stringify(out, null, '\t')};

/** Planets known on ${fetched}, by discovery method (the archive's own method names). */
export const BY_METHOD: Record<string, number> = ${JSON.stringify(byMethod, null, '\t')};

export const TOTAL = ${total};

/** Per discovery year: [year, transit, radial velocity, microlensing, imaging, other methods]. */
export const BY_YEAR: [number, number, number, number, number, number][] = ${JSON.stringify(years)};
`;
writeFileSync(OUT, ts);
console.log(`wrote ${OUT}: ${out.length} planets, ${total} in the census`);
