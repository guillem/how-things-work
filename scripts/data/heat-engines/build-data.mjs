#!/usr/bin/env node
/**
 * Builds `src/routes/heat-engines/steam-data.ts`: the properties of water and
 * steam that the steam-turbine (Rankine) cycle of the explainer needs.
 *
 *   node scripts/data/heat-engines/build-data.mjs <download-dir>
 *
 * Source: NIST Chemistry WebBook, SRD 69, "Thermophysical Properties of Fluid
 * Systems" (E.W. Lemmon, I.H. Bell, M.L. Huber and M.O. McLinden), water
 * (https://webbook.nist.gov/chemistry/fluid/), computed from the IAPWS-95
 * formulation (Wagner and Pruss, J. Phys. Chem. Ref. Data 31, 387, 2002),
 * default reference state (u = s = 0 for the liquid at the triple point).
 * The files are downloaded into <download-dir> if they are not there yet
 * (not committed):
 *   sat-t.tsv   saturation, 15–100 °C in steps of 1 °C
 *   sat-p.tsv   saturation at 15 MPa (the boiler)
 *   isobar.tsv  15 MPa, 345–650 °C in steps of 5 °C (superheated steam)
 *
 * Kept: temperature (K), pressure (MPa), specific volume (m³/kg), enthalpy
 * (kJ/kg) and entropy (kJ/(kg·K)), rounded to the digits NIST prints.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const RAW = process.argv[2];
if (!RAW) {
	console.error('usage: build-data.mjs <download-dir>');
	process.exit(1);
}
mkdirSync(RAW, { recursive: true });
const OUT = resolve(import.meta.dirname, '../../../src/routes/heat-engines/steam-data.ts');

const BASE = 'https://webbook.nist.gov/cgi/fluid.cgi?Action=Data&Wide=on&ID=C7732185&Digits=6';
const UNITS =
	'&RefState=DEF&TUnit=K&PUnit=MPa&DUnit=kg%2Fm3&HUnit=kJ%2Fkg&WUnit=m%2Fs&VisUnit=uPa*s&STUnit=N%2Fm';
// NIST names the saturation tables by what is held fixed per row: SatP steps the temperature,
// SatT the pressure.
const BOILER_MPA = 15;
const FILES = {
	'sat-t.tsv': `${BASE}&Type=SatP&TLow=288.15&THigh=373.15&TInc=1${UNITS}`,
	'sat-p.tsv': `${BASE}&Type=SatT&PLow=${BOILER_MPA}&PHigh=${BOILER_MPA}&PInc=1${UNITS}`,
	'isobar.tsv': `${BASE}&Type=IsoBar&P=${BOILER_MPA}&TLow=618.15&THigh=923.15&TInc=5${UNITS}`
};

async function get(name) {
	const path = join(RAW, name);
	if (!existsSync(path)) {
		const res = await fetch(FILES[name]);
		if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
		writeFileSync(path, await res.text());
	}
	const [head, ...rows] = readFileSync(path, 'utf8').trim().split('\n');
	const cols = head.split('\t');
	return rows.map((r) => {
		const cells = r.split('\t');
		return (name_) => {
			const i = cols.indexOf(name_);
			if (i < 0) throw new Error(`${name}: no column ${name_}`);
			return Number(cells[i]);
		};
	});
}

const sat = (await get('sat-t.tsv')).map((c) => [
	c('Temperature (K)'),
	c('Pressure (MPa)'),
	c('Volume (l, m3/kg)'),
	c('Volume (v, m3/kg)'),
	c('Enthalpy (l, kJ/kg)'),
	c('Enthalpy (v, kJ/kg)'),
	c('Entropy (l, J/g*K)'),
	c('Entropy (v, J/g*K)')
]);
const [b] = await get('sat-p.tsv');
const boiler = [
	b('Temperature (K)'),
	b('Pressure (MPa)'),
	b('Volume (l, m3/kg)'),
	b('Volume (v, m3/kg)'),
	b('Enthalpy (l, kJ/kg)'),
	b('Enthalpy (v, kJ/kg)'),
	b('Entropy (l, J/g*K)'),
	b('Entropy (v, J/g*K)')
];
const superheated = (await get('isobar.tsv'))
	.map((c) => [
		c('Temperature (K)'),
		c('Volume (m3/kg)'),
		c('Enthalpy (kJ/kg)'),
		c('Entropy (J/g*K)'),
		c('Phase')
	])
	.filter((r) => r[0] > boiler[0]);
for (const r of superheated) r.pop();

const row = (r) => `[${r.join(', ')}]`;
writeFileSync(
	OUT,
	`/**
 * Properties of water and steam for the steam-turbine cycle. Generated by
 * scripts/data/heat-engines/build-data.mjs; do not edit by hand.
 *
 * Source: NIST Chemistry WebBook, SRD 69, Thermophysical Properties of Fluid Systems
 * (Lemmon, Bell, Huber and McLinden; https://webbook.nist.gov/chemistry/fluid/), water,
 * from the IAPWS-95 formulation (Wagner and Pruss, J. Phys. Chem. Ref. Data 31, 387, 2002),
 * default reference state; retrieved ${new Date().toISOString().slice(0, 10)}.
 * Terms: © U.S. Secretary of Commerce on behalf of the U.S.A., all rights reserved; NIST
 * Standard Reference Data under the Standard Reference Data Act
 * (https://www.nist.gov/open/copyright-fair-use-and-licensing-statements-srd-data-software-and-technical-series-publications#SRD).
 *
 * Units: K, MPa, m³/kg, kJ/kg, kJ/(kg·K).
 */

/** [T, p, v liquid, v vapour, h liquid, h vapour, s liquid, s vapour] */
export type SatRow = readonly [number, number, number, number, number, number, number, number];

/** Saturated water and steam, 15–100 °C in steps of 1 °C (the condenser). */
export const SATURATION: readonly SatRow[] = [
${sat.map((r) => '\t' + row(r)).join(',\n')}
];

/** Boiler pressure, MPa. */
export const BOILER_MPA = ${BOILER_MPA};

/** Saturated water and steam at the boiler pressure. */
export const BOILER_SAT: SatRow = ${row(boiler)};

/** [T, v, h, s] of superheated steam at the boiler pressure, every 5 K. */
export const SUPERHEATED: readonly (readonly [number, number, number, number])[] = [
${superheated.map((r) => '\t' + row(r)).join(',\n')}
];
`
);
console.log(`wrote ${OUT}: ${sat.length} saturation rows, ${superheated.length} superheated`);
