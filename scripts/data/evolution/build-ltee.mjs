#!/usr/bin/env node
/**
 * Builds `src/routes/evolution/ltee.ts`: the mean fitness of Lenski's twelve
 * long-term evolution experiment (LTEE) populations of E. coli, 0–50,000
 * generations, relative to their common ancestor.
 *
 *   node scripts/data/evolution/build-ltee.mjs [path/to/Concatenated.LTEE.data.all.csv]
 *
 * Source: Wiser, M. J., Ribeck, N. & Lenski, R. E. (2013), "Long-term dynamics
 * of adaptation in asexual populations", Science 342, 1364–1367,
 * https://doi.org/10.1126/science.1243357; data: Wiser, Ribeck & Lenski (2013),
 * Dryad, https://doi.org/10.5061/dryad.0hc2m, file Concatenated.LTEE.data.all.csv
 * (licence CC0 1.0). Dryad serves the file only to signed-in users, so by
 * default this script reads the copy kept by B. H. Good in
 * https://github.com/benjaminhgood/LTEE-metagenomic (additional_data/).
 *
 * Each row of the file is one competition of an evolved population against
 * the marked ancestor; `Fitness` is the ratio of their realised growth rates
 * (evolved over ancestor), so 1 means "as fit as the ancestor".
 *
 * Subset: for each population and generation, the mean of its replicate
 * competitions (rows without a fitness value are skipped), rounded to 3
 * decimals. The grand mean averages the nine populations whose record is
 * complete (`Complete` = Yes; Ara−2, Ara−3 and Ara+6 have gaps; leaving
 * them out is our choice). The power law w = (b·t + 1)^a is fitted here to those grand means
 * by least squares (grid search over b, ternary search over a):
 * it is our fit, in the form Wiser et al. used, not their published values.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const URL =
	'https://raw.githubusercontent.com/benjaminhgood/LTEE-metagenomic/master/additional_data/Concatenated.LTEE.data.all.csv';
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/evolution/ltee.ts');

const text = process.argv[2]
	? readFileSync(process.argv[2], 'utf8')
	: await (await fetch(URL)).text();
const lines = text.split(/\r?\n/).filter((l) => l.trim());
const header = lines[0].split(',');
const col = (name) => header.indexOf(name);
const [iGen, iPop, iFit, iComplete] = ['Generation', 'Population', 'Fitness', 'Complete'].map(col);

/** population → generation → fitness values */
const byPop = new Map();
const complete = new Set();
for (const line of lines.slice(1)) {
	const c = line.split(',');
	const pop = c[iPop].replace(/\s+/g, ''); // "Ara - 1" → "Ara-1"
	const gen = Number(c[iGen]);
	if (c[iComplete] === 'Yes') complete.add(pop);
	if (c[iFit] === '') continue;
	const fit = Number(c[iFit]);
	if (!Number.isFinite(fit)) continue;
	if (!byPop.has(pop)) byPop.set(pop, new Map());
	const g = byPop.get(pop);
	if (!g.has(gen)) g.set(gen, []);
	g.get(gen).push(fit);
}
const pops = [...byPop.keys()].sort((a, b) => {
	const sa = a.includes('-') ? 0 : 1;
	const sb = b.includes('-') ? 0 : 1;
	return sa - sb || Number(a.slice(4)) - Number(b.slice(4));
});
const gens = [...new Set(pops.flatMap((p) => [...byPop.get(p).keys()]))].sort((a, b) => a - b);
const mean = (xs) => xs.reduce((s, x) => s + x, 0) / xs.length;
const r3 = (v) => Math.round(v * 1000) / 1000;

const series = pops.map((p) => ({
	population: p,
	complete: complete.has(p),
	fitness: gens.map((g) => (byPop.get(p).has(g) ? r3(mean(byPop.get(p).get(g))) : null))
}));
const grand = gens.map((g, k) => {
	const vals = series.filter((s) => s.complete && s.fitness[k] !== null).map((s) => s.fitness[k]);
	return r3(mean(vals));
});

// Least-squares fit of w = (b t + 1)^a to the grand means.
let best = { a: 0, b: 0, sse: Infinity };
for (let lb = -5; lb <= -1; lb += 0.001) {
	const b = 10 ** lb;
	// For fixed b, ln w = a ln(bt + 1): fit a by least squares on w itself with a 1-D search.
	let lo = 0;
	let hi = 1;
	for (let it = 0; it < 60; it++) {
		const m1 = lo + (hi - lo) / 3;
		const m2 = hi - (hi - lo) / 3;
		const sse = (a) => gens.reduce((s, t, k) => s + ((b * t + 1) ** a - grand[k]) ** 2, 0);
		if (sse(m1) < sse(m2)) hi = m2;
		else lo = m1;
	}
	const a = (lo + hi) / 2;
	const sse = gens.reduce((s, t, k) => s + ((b * t + 1) ** a - grand[k]) ** 2, 0);
	if (sse < best.sse) best = { a, b, sse };
}

const out = `// Generated by scripts/data/evolution/build-ltee.mjs — do not edit by hand.
//
// Mean fitness of the twelve LTEE populations of E. coli relative to their
// ancestor (1 = as fit as the ancestor), from Wiser, Ribeck & Lenski (2013),
// Science 342: 1364–1367, data on Dryad https://doi.org/10.5061/dryad.0hc2m
// (CC0). Per population: the mean of its replicate competitions at each
// generation (null = not measured). grand: the mean of the nine populations
// with a complete record. powerLaw: our least-squares fit of
// w = (b·t + 1)^a to the grand means (the form used in the paper).

export const LTEE_GENERATIONS: readonly number[] = ${JSON.stringify(gens)};

export const LTEE_POPULATIONS: readonly {
	population: string;
	complete: boolean;
	fitness: readonly (number | null)[];
}[] = ${JSON.stringify(series)};

export const LTEE_GRAND_MEAN: readonly number[] = ${JSON.stringify(grand)};

export const LTEE_POWER_LAW = { a: ${best.a.toFixed(4)}, b: ${best.b.toPrecision(4)} } as const;
`;
writeFileSync(OUT, out);
console.log(
	`wrote ${OUT}: ${pops.length} populations, ${gens.length} time points; grand mean at 0: ${grand[0]}, at 50k: ${grand.at(-1)}; fit a=${best.a.toFixed(4)} b=${best.b.toPrecision(4)}`
);
