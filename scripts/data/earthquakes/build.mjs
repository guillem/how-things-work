#!/usr/bin/env node
// Builds the earthquakes explainer's data (src/routes/earthquakes/data/*.ts) from raw downloads.
// No dependencies. Usage:
//
//   node scripts/data/earthquakes/build.mjs <raw-dir>
//
// <raw-dir> must contain (download them there first, outside the repository):
//
//   ak135t.html
//     http://rses.anu.edu.au/seismology/ak135/ak135t.html
//     The ak135 velocity model, "travel time version" (continental crust), as used for the ak135
//     travel-time tables: Kennett, B.L.N., Engdahl, E.R. & Buland, R. (1995), Constraints on
//     seismic velocities in the Earth from travel times, Geophys. J. Int. 122, 108–124,
//     doi:10.1111/j.1365-246X.1995.tb03540.x. Also distributed by the EarthScope (IRIS) Earth
//     Model Collaboration as EMC-ak135-f (doi:10.17611/DP/9991801).
//   gsn.txt
//     https://service.iris.edu/fdsnws/station/1/query?net=IU,II&level=station&format=text&endafter=2015-05-01&startbefore=2015-04-25
//     Station coordinates of the Global Seismographic Network (networks IU and II).
//   gorkha.json
//     https://earthquake.usgs.gov/fdsnws/event/1/query?eventid=us20002926&format=geojson
//     The USGS origin of the 25 April 2015 Gorkha (Nepal) earthquake (public domain).
//   channels.txt
//     https://service.iris.edu/fdsnws/station/1/query?net=IU,II&sta=ANTO,TATO,DGAR&cha=BH?&level=channel&format=text&starttime=2015-04-25T06:00:00&endtime=2015-04-25T07:00:00
//     Orientation and sensitivity (counts per m/s) of each channel.
//   <station>-<channel>.mseed for ANTO, TATO, DGAR and BHZ, BH1, BH2
//     https://service.iris.edu/fdsnws/dataselect/1/query?net=<IU|II>&sta=<station>&loc=<10|00>&cha=<channel>&starttime=2015-04-25T06:11:00&endtime=2015-04-25T06:33:00
//     Broadband seismograms (vertical and two horizontal components) of the Gorkha earthquake at
//     IU.ANTO (Ankara, location 10: its location-00 sensor recorded only noise that day), IU.TATO
//     (Taipei) and II.DGAR (Diego Garcia), from the EarthScope (IRIS) data centre. GSN data:
//     networks IU (doi:10.7914/SN/IU, Albuquerque Seismological Laboratory/USGS) and II
//     (doi:10.7914/SN/II, Scripps Institution of Oceanography), open access.
//
// What the script does:
// - ak135: the depth, P speed and S speed of every row of the model (136 rows; the density
//   columns are dropped). Rows repeat a depth at each discontinuity, the upper value first.
// - seismograms: decodes the miniSEED records (Steim-2), keeps the 1,200 seconds after the
//   origin time, converts counts to ground velocity, applies a one-pole high-pass filter (corner
//   50 s) to remove the slow drift of the broadband sensor, rotates the two horizontal
//   components into the transverse direction (across the path from the earthquake), and keeps
//   the minimum and maximum of each second of the vertical and transverse motion (an envelope
//   that draws like the full trace at this scale), in units of the largest value in the first
//   1,000 s (before the big surface waves), ×1000, rounded. The P wave's arrival is picked
//   automatically on the vertical motion with an STA/LTA trigger (1 s against the 60 s before).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const raw = process.argv[2];
if (!raw) {
	console.error('usage: node scripts/data/earthquakes/build.mjs <raw-dir>');
	process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../src/routes/earthquakes/data');
mkdirSync(out, { recursive: true });

// ---------------------------------------------------------------- ak135
const html = readFileSync(join(raw, 'ak135t.html'), 'utf8').replace(/<[^>]*>/g, '');
const lines = html.split('\n');
const start = lines.findIndex((l) => /depth\s+P vel/.test(l));
const rows = [];
for (const l of lines.slice(start + 1)) {
	const f = l.trim().split(/\s+/).map(Number);
	if (f.length < 4 || f.some((x) => !Number.isFinite(x))) continue;
	const [depth, vp, vs] = f;
	const prev = rows.at(-1);
	// The page repeats one row (2740 km) verbatim; keep a repeated depth only if a speed jumps.
	if (prev && prev[0] === depth && prev[1] === vp && prev[2] === vs) continue;
	rows.push([depth, vp, vs]);
}
if (rows.length < 130 || rows[0][0] !== 0 || rows.at(-1)[0] !== 6371)
	throw new Error('ak135 parse');
writeFileSync(
	join(out, 'ak135.ts'),
	`// Generated by scripts/data/earthquakes/build.mjs — do not edit by hand.
// The ak135 model of the speed of seismic waves inside the Earth, travel-time version (continental
// crust): Kennett, B.L.N., Engdahl, E.R. & Buland, R. (1995), Constraints on seismic velocities in
// the Earth from travel times, Geophys. J. Int. 122, 108–124, doi:10.1111/j.1365-246X.1995.tb03540.x.
// Source: http://rses.anu.edu.au/seismology/ak135/ak135t.html (Research School of Earth Sciences,
// ANU), also distributed by the EarthScope (IRIS) Earth Model Collaboration (doi:10.17611/DP/9991801).
// Licence: none stated at the source; the model is published for use in seismology and is cited
// here as its authors and the EMC ask.
// The model is pointwise: speeds are linearly interpolated in radius between rows; a depth that
// appears twice is a discontinuity (the upper value first).

/** [depth km, P speed km/s, S speed km/s] for each of the ${rows.length} rows, from the surface down. */
export const AK135: [number, number, number][] = ${JSON.stringify(rows)};
`
);
console.log(`ak135: ${rows.length} rows`);

// ---------------------------------------------------------------- stations, origin
const gsn = readFileSync(join(raw, 'gsn.txt'), 'utf8')
	.split('\n')
	.filter((l) => l && !l.startsWith('#'))
	.map((l) => l.split('|'));
const event = JSON.parse(readFileSync(join(raw, 'gorkha.json'), 'utf8'));
const origin = event.properties.time; // ms since 1970, UTC
const [elon, elat, edepth] = event.geometry.coordinates;

// ---------------------------------------------------------------- miniSEED (Steim-2)
function decodeSteim2(buf, off, nframes, nsamp) {
	const out = [];
	let x0 = 0;
	const diffs = [];
	for (let f = 0; f < nframes; f++) {
		const base = off + f * 64;
		const w0 = buf.readUInt32BE(base);
		for (let i = 0; i < 16; i++) {
			const code = (w0 >>> (30 - 2 * i)) & 3;
			const word = buf.readUInt32BE(base + 4 * i);
			if (f === 0 && i === 1) x0 = buf.readInt32BE(base + 4);
			if (i === 0 || (f === 0 && (i === 1 || i === 2))) continue;
			const sext = (v, bits) => (v << (32 - bits)) >> (32 - bits);
			if (code === 1) {
				for (let k = 0; k < 4; k++) diffs.push(sext((word >>> (24 - 8 * k)) & 0xff, 8));
			} else if (code === 2) {
				const dnib = word >>> 30;
				if (dnib === 1) diffs.push(sext(word & 0x3fffffff, 30));
				else if (dnib === 2)
					for (let k = 0; k < 2; k++) diffs.push(sext((word >>> (15 - 15 * k)) & 0x7fff, 15));
				else if (dnib === 3)
					for (let k = 0; k < 3; k++) diffs.push(sext((word >>> (20 - 10 * k)) & 0x3ff, 10));
			} else if (code === 3) {
				const dnib = word >>> 30;
				if (dnib === 0)
					for (let k = 0; k < 5; k++) diffs.push(sext((word >>> (24 - 6 * k)) & 0x3f, 6));
				else if (dnib === 1)
					for (let k = 0; k < 6; k++) diffs.push(sext((word >>> (25 - 5 * k)) & 0x1f, 5));
				else if (dnib === 2)
					for (let k = 0; k < 7; k++) diffs.push(sext((word >>> (24 - 4 * k)) & 0xf, 4));
			}
		}
	}
	let last = x0;
	out.push(x0);
	for (let i = 1; i < nsamp; i++) {
		last += diffs[i];
		out.push(last);
	}
	return out;
}

function readMseed(path) {
	const buf = readFileSync(path);
	const records = [];
	for (let off = 0; off + 48 <= buf.length;) {
		const year = buf.readUInt16BE(off + 20);
		const doy = buf.readUInt16BE(off + 22);
		const [hh, mm, ss] = [buf[off + 24], buf[off + 25], buf[off + 26]];
		const frac = buf.readUInt16BE(off + 28); // 0.0001 s
		const nsamp = buf.readUInt16BE(off + 30);
		const factor = buf.readInt16BE(off + 32);
		const mult = buf.readInt16BE(off + 34);
		const rate = (factor > 0 ? factor : -1 / factor) * (mult > 0 ? mult : -1 / mult);
		const dataOff = buf.readUInt16BE(off + 44);
		let b = buf.readUInt16BE(off + 46);
		let enc = 0;
		let reclen = 512;
		while (b) {
			if (buf.readUInt16BE(off + b) === 1000) {
				enc = buf[off + b + 4];
				reclen = 1 << buf[off + b + 6];
			}
			b = buf.readUInt16BE(off + b + 2);
		}
		if (enc !== 11) throw new Error(`${path}: encoding ${enc}, only Steim-2 is supported`);
		const t0 = Date.UTC(year, 0, 1, hh, mm, ss) + (doy - 1) * 86400e3 + frac / 10;
		const nframes = (reclen - dataOff) / 64;
		records.push({ t0, rate, samples: decodeSteim2(buf, off + dataOff, nframes, nsamp) });
		off += reclen;
	}
	return records;
}

const STATIONS = [
	{ net: 'IU', sta: 'ANTO', loc: '10', name: 'Ankara' },
	{ net: 'IU', sta: 'TATO', loc: '00', name: 'Taipei' },
	{ net: 'II', sta: 'DGAR', loc: '00', name: 'Diego Garcia' }
];
const WINDOW = 1200;
const channels = readFileSync(join(raw, 'channels.txt'), 'utf8')
	.split('\n')
	.filter((l) => l && !l.startsWith('#'))
	.map((l) => l.split('|'));
const rad = Math.PI / 180;

/** Ground velocity (m/s) of one channel on the origin-time grid, mean removed, high-passed. */
function channel(s, cha) {
	const meta = channels.find((c) => c[1] === s.sta && c[2] === s.loc && c[3] === cha);
	if (!meta) throw new Error(`no metadata for ${s.sta}.${s.loc}.${cha}`);
	const recs = readMseed(join(raw, `${s.sta}-${cha}.mseed`));
	const rate = recs[0].rate;
	const n = Math.round(WINDOW * rate);
	const y = new Float64Array(n).fill(NaN);
	for (const r of recs)
		r.samples.forEach((v, i) => {
			const k = Math.round(((r.t0 - origin) / 1000 + i / r.rate) * rate);
			if (k >= 0 && k < n) y[k] = v;
		});
	if (y.some((v) => Number.isNaN(v))) throw new Error(`${s.sta}.${cha}: gap in the data`);
	const scale = Number(meta[11]); // counts per m/s
	// One-pole high-pass, corner period 50 s (it also removes the mean).
	const rc = 50 / (2 * Math.PI);
	const a = rc / (rc + 1 / rate);
	const hp = new Float64Array(n);
	for (let i = 1; i < n; i++) hp[i] = a * (hp[i - 1] + (y[i] - y[i - 1]) / scale);
	return { rate, azimuth: Number(meta[8]), v: hp };
}

/** Min and max of each second, ×1000 of the largest value in the first 1,000 s. */
function envelope(v, rate) {
	let peak = 0;
	for (let i = 0; i < 1000 * rate; i++) peak = Math.max(peak, Math.abs(v[i]));
	const env = [];
	for (let sec = 0; sec < WINDOW; sec++) {
		let lo = Infinity;
		let hi = -Infinity;
		for (let i = Math.round(sec * rate); i < Math.round((sec + 1) * rate); i++) {
			lo = Math.min(lo, v[i]);
			hi = Math.max(hi, v[i]);
		}
		env.push(Math.round((lo / peak) * 1000), Math.round((hi / peak) * 1000));
	}
	return { env, peak };
}

/** Azimuth (degrees clockwise from north) from point 1 to point 2 on a sphere. */
function azimuth(lat1, lon1, lat2, lon2) {
	const [p1, p2, dl] = [lat1 * rad, lat2 * rad, (lon2 - lon1) * rad];
	const y = Math.sin(dl) * Math.cos(p2);
	const x = Math.cos(p1) * Math.sin(p2) - Math.sin(p1) * Math.cos(p2) * Math.cos(dl);
	return (Math.atan2(y, x) / rad + 360) % 360;
}

const traces = STATIONS.map((s) => {
	const g = gsn.find((r) => r[0] === s.net && r[1] === s.sta);
	if (!g) throw new Error(`no coordinates for ${s.sta}`);
	const [lat, lon] = [Number(g[2]), Number(g[3])];
	const z = channel(s, 'BHZ');
	const h1 = channel(s, 'BH1');
	const h2 = channel(s, 'BH2');
	if (h1.rate !== z.rate || h2.rate !== z.rate) throw new Error(`${s.sta}: mixed rates`);
	// Horizontal components → north/east → transverse (perpendicular to the path from the
	// earthquake, where S waves shake the ground and P waves barely do).
	const baz = azimuth(lat, lon, elat, elon) * rad;
	const n = z.v.length;
	const tr = new Float64Array(n);
	for (let i = 0; i < n; i++) {
		const north = h1.v[i] * Math.cos(h1.azimuth * rad) + h2.v[i] * Math.cos(h2.azimuth * rad);
		const east = h1.v[i] * Math.sin(h1.azimuth * rad) + h2.v[i] * Math.sin(h2.azimuth * rad);
		tr[i] = north * Math.sin(baz) - east * Math.cos(baz);
	}
	// The P wave's arrival, picked automatically: the first moment after 200 s where the mean
	// shaking of the last second exceeds 5× that of the 60 s before it (an STA/LTA trigger).
	const absz = z.v.map(Math.abs);
	const mean = (a, b) => {
		let sum = 0;
		for (let i = a; i < b; i++) sum += absz[i];
		return sum / (b - a);
	};
	let pPick = NaN;
	for (let i = 200 * z.rate; i < z.v.length; i++) {
		const sta = mean(i - z.rate, i);
		const lta = mean(i - 61 * z.rate, i - z.rate);
		if (sta > 5 * lta) {
			pPick = Math.round((i / z.rate) * 10) / 10;
			break;
		}
	}
	const Z = envelope(z.v, z.rate);
	const T = envelope(tr, z.rate);
	console.log(`${s.sta}: P picked at ${pPick} s`);
	console.log(
		`${s.sta}: ${z.rate} sps; peak before 1,000 s: Z ${Z.peak.toExponential(2)} m/s, T ${T.peak.toExponential(2)} m/s`
	);
	return {
		...s,
		lat,
		lon,
		site: g[5],
		pPick,
		z: Z.env,
		t: T.env,
		ratio: Math.round((T.peak / Z.peak) * 100) / 100
	};
});

writeFileSync(
	join(out, 'seismograms.ts'),
	`// Generated by scripts/data/earthquakes/build.mjs — do not edit by hand.
// The 25 April 2015 Gorkha (Nepal) earthquake, M 7.8: origin from the USGS (event us20002926,
// public domain), https://earthquake.usgs.gov/earthquakes/eventpage/us20002926.
// Seismograms: broadband recordings at three stations of the Global Seismographic Network
// (location 10 at ANTO, 00 elsewhere), from the EarthScope (IRIS) data centre (FDSN dataselect web
// service); networks IU (doi:10.7914/SN/IU) and II (doi:10.7914/SN/II), open access. Station
// coordinates and channel metadata from the FDSN station web service. Processing (see the
// script): ground velocity, one-pole high-pass at 50 s, horizontals rotated to the transverse
// direction, then the minimum and maximum of each second, scaled so that the largest value in
// the first 1,000 s is 1000.

export const ORIGIN = {
	time: '${new Date(origin).toISOString()}',
	lat: ${elat},
	lon: ${elon},
	depth: ${edepth},
	mag: ${event.properties.mag}
};

export interface Recording {
	net: string;
	sta: string;
	loc: string;
	name: string;
	site: string;
	lat: number;
	lon: number;
	/** Seconds after the origin when the P wave arrives, picked automatically (STA/LTA). */
	pPick: number;
	/** Vertical ground motion, per second after the origin time: [min, max, min, max, …], ×1000 of
	 * its largest value before 1,000 s. */
	z: number[];
	/** The same for the transverse horizontal motion (across the path from the earthquake). */
	t: number[];
	/** Largest transverse motion before 1,000 s ÷ largest vertical motion before 1,000 s. */
	ratio: number;
}

export const RECORDINGS: Recording[] = ${JSON.stringify(traces)};
`
);
