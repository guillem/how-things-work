#!/usr/bin/env node
/**
 * Builds `src/routes/pcr-copying-dna/sequences-data.ts`: the two stretches of DNA a COVID-19
 * PCR test copies, and the primers that pick them out.
 *
 *   node scripts/data/pcr-copying-dna/build-sequences.mjs
 *
 * Sources (fetched by the script from NCBI E-utilities; public domain):
 *   - SARS-CoV-2 reference genome, NCBI RefSeq NC_045512.2 (isolate Wuhan-Hu-1), the N gene
 *     around the CDC N1 target;
 *   - human RPP30 (ribonuclease P/MRP subunit p30), GRCh38 chromosome 10, NCBI RefSeq
 *     NC_000010.11, exon 1 around the CDC RNase P target.
 * Primers: CDC 2019-nCoV Real-Time RT-PCR Diagnostic Panel, "Research Use Only 2019-Novel
 * Coronavirus (2019-nCoV) Real-time RT-PCR Primers and Probes" (a US federal work, public
 * domain), https://www.cdc.gov/coronavirus/2019-ncov/lab/rt-pcr-panel-primer-probes.html, read
 * from the Internet Archive copy of 2020-12-31
 * (https://web.archive.org/web/20201231171227/https://www.cdc.gov/coronavirus/2019-ncov/lab/rt-pcr-panel-primer-probes.html;
 * the live page has been withdrawn). Each primer at 500 nM, each probe at 125 nM.
 *
 * The script finds each forward primer, and the reverse complement of each reverse primer, in
 * its genome stretch, and fails unless both (and the probe) occur exactly once.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const OUT = resolve(import.meta.dirname, '../../../src/routes/pcr-copying-dna/sequences-data.ts');
const FLANK = 12;

const targets = [
	{
		id: 'n1',
		name: 'SARS-CoV-2 N gene (CDC N1)',
		accession: 'NC_045512.2',
		from: 28250,
		to: 28400,
		forward: 'GACCCCAAAATCAGCGAAAT',
		reverse: 'TCTGGTTACTGCCAGTTGAATCTG',
		probe: 'ACCCCGCATTACGTTTGGTGGACC'
	},
	{
		id: 'rp',
		name: 'human RPP30 gene (CDC RNase P)',
		accession: 'NC_000010.11',
		from: 90871900,
		to: 90872150,
		forward: 'AGATTTGGACCTGCGAGCG',
		reverse: 'GAGCGGCTGTCTCCACAAGT',
		probe: 'TTCTGACCTGAAGGCTCTGCGCG'
	}
];

const complement = { A: 'T', T: 'A', G: 'C', C: 'G' };
const revcomp = (s) =>
	s
		.split('')
		.reverse()
		.map((c) => complement[c])
		.join('');
const once = (hay, needle, what) => {
	const i = hay.indexOf(needle);
	if (i < 0 || hay.indexOf(needle, i + 1) >= 0) throw new Error(`${what}: not exactly one match`);
	return i;
};

const out = [];
for (const t of targets) {
	const url = `https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi?db=nuccore&id=${t.accession}&rettype=fasta&retmode=text&seq_start=${t.from}&seq_stop=${t.to}`;
	const fasta = await (await fetch(url)).text();
	const seq = fasta.split('\n').slice(1).join('').trim().toUpperCase();
	if (!/^[ACGT]+$/.test(seq)) throw new Error(`${t.id}: unexpected letters`);
	const f = once(seq, t.forward, `${t.id} forward`);
	const r = once(seq, revcomp(t.reverse), `${t.id} reverse`) + t.reverse.length;
	once(seq.slice(f, r), t.probe, `${t.id} probe`);
	const start = f - FLANK;
	const end = r + FLANK;
	out.push({
		id: t.id,
		name: t.name,
		source: `${t.accession}:${t.from + start}-${t.from + end - 1}`,
		ampliconSource: `${t.accession}:${t.from + f}-${t.from + r - 1}`,
		top: seq.slice(start, end),
		forward: t.forward,
		reverse: t.reverse,
		probe: t.probe,
		ampliconLength: r - f
	});
	console.log(t.id, 'amplicon', r - f, 'bp at', `${t.from + f}-${t.from + r - 1}`);
}

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
	OUT,
	`/**
 * GENERATED by scripts/data/pcr-copying-dna/build-sequences.mjs — do not edit by hand.
 *
 * Two stretches of DNA a COVID-19 PCR test copies, as the top strand 5′→3′, each with
 * ${FLANK} letters of its genome on either side of the copied piece, and the CDC primers (both
 * written 5′→3′; the reverse primer pairs with the top strand).
 *   - SARS-CoV-2 N gene, NCBI RefSeq NC_045512.2 (Wuhan-Hu-1), around the CDC N1 target;
 *   - human RPP30, GRCh38 chromosome 10, NCBI RefSeq NC_000010.11, exon 1, around the CDC
 *     RNase P target (the test's check that the swab collected human cells).
 * Primers: CDC 2019-nCoV Real-Time RT-PCR Diagnostic Panel, Research Use Only primers and
 * probes (US federal work, public domain; Internet Archive copy of 2020-12-31).
 * Retrieved ${today}. NCBI sequence records are in the public domain (NCBI usage policy).
 */

export interface Target {
	id: 'n1' | 'rp';
	name: string;
	/** Accession and 1-based coordinates of \`top\`. */
	source: string;
	/** Accession and coordinates of the copied piece (the amplicon). */
	ampliconSource: string;
	/** Top strand, 5′→3′. */
	top: string;
	forward: string;
	reverse: string;
	probe: string;
	ampliconLength: number;
}

export const TARGETS: readonly Target[] = ${JSON.stringify(out, null, '\t')};
`
);
console.log('wrote', OUT);
