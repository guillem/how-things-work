#!/usr/bin/env node
/**
 * Builds src/routes/vision-color/cone-data.ts: the Stockman & Sharpe (2000) 2° cone fundamentals
 * (the CIE 2006 "physiologically relevant" LMS functions) and the CIE 2012 2° XYZ colour-matching
 * functions derived from them, both from the Colour & Vision Research Laboratory (CVRL, UCL).
 *
 *   node scripts/data/vision-color/build.mjs <cache dir>
 *
 * 1. Fetch. CVRL's own files linss2_10e_1.csv (linear energy, 1 nm, each function normalised
 *    to a peak of 1) and lin2012xyz2e_1_7sf.csv (CIE 170-2:2015), from
 *    http://www.cvrl.org/database/data/ (cvrl.org answers on plain http only). The downloads are
 *    cached in the given directory (outside the repository). History: on 2026-10-14 cvrl.org did
 *    not answer, so the tables were first read from the colour-science library's verbatim copy
 *    (BSD-3-Clause, colour/colorimetry/datasets/cmfs.py at commit
 *    046ad1aa8a988d6d4033c604c1f2f7c2b5585845). On 2026-10-17 CVRL's files were reachable: the
 *    LMS rows from 390 to 780 nm were identical to that copy, and the XYZ rows agreed to the
 *    6 significant figures stored here.
 * 2. Subset. Every nanometre from 390 to 780 nm (the light the page uses; above 780 nm all
 *    values are below 1e-4 of their peaks). CVRL leaves S blank above 615 nm; stored as 0.
 * 3. Check. Fits the 3 × 3 matrix from LMS to XYZ by least squares and prints it with its worst
 *    residual, to compare with the matrix of CIE 170-2 used in the model.
 */
import fs from 'node:fs';
import path from 'node:path';

const BASE = 'http://www.cvrl.org/database/data/';
const FILES = { lms: 'cones/linss2_10e_1.csv', xyz: 'cienewxyz/lin2012xyz2e_1_7sf.csv' };
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/vision-color/cone-data.ts');
const FROM = 390;
const TO = 780;

const cache = process.argv[2];
if (!cache) {
	console.error('usage: node scripts/data/vision-color/build.mjs <cache dir>');
	process.exit(1);
}
fs.mkdirSync(cache, { recursive: true });
/** Rows `nm, a, b, c` of a CVRL csv file; a blank cell (S above 615 nm) is stored as 0. */
async function table(rel) {
	const file = path.join(cache, path.basename(rel));
	if (!fs.existsSync(file)) {
		const res = await fetch(BASE + rel);
		if (!res.ok) throw new Error(`${BASE + rel}: ${res.status}`);
		fs.writeFileSync(file, await res.text());
	}
	const rows = new Map();
	for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
		if (!line.trim()) continue;
		const cells = line.split(',').map((s) => s.trim());
		if (cells.length < 4 || !/^\d+$/.test(cells[0])) throw new Error(`${rel}: bad row "${line}"`);
		rows.set(
			Number(cells[0]),
			cells.slice(1, 4).map((s) => (s === '' ? 0 : Number(s)))
		);
	}
	return rows;
}
const lms = await table(FILES.lms);
const xyz = await table(FILES.xyz);

const pick = (rows) => {
	const out = [];
	for (let nm = FROM; nm <= TO; nm++) {
		const r = rows.get(nm);
		if (!r || r.some((v) => !Number.isFinite(v))) throw new Error(`bad row ${nm}`);
		out.push(r);
	}
	return out;
};
const L = pick(lms);
const X = pick(xyz);

// Least-squares fit X ≈ A·LMS, row by row (normal equations, 3 × 3).
const solve3 = (m, v) => {
	const det = (a) =>
		a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1]) -
		a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0]) +
		a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0]);
	const d = det(m);
	return [0, 1, 2].map((c) => det(m.map((row, i) => row.map((x, j) => (j === c ? v[i] : x)))) / d);
};
const AtA = [0, 1, 2].map((i) => [0, 1, 2].map((j) => L.reduce((s, r) => s + r[i] * r[j], 0)));
const fit = [0, 1, 2].map((k) =>
	solve3(
		AtA,
		[0, 1, 2].map((i) => L.reduce((s, r, n) => s + r[i] * X[n][k], 0))
	)
);
let worst = 0;
L.forEach((r, n) =>
	fit.forEach((row, k) => {
		worst = Math.max(worst, Math.abs(row[0] * r[0] + row[1] * r[1] + row[2] * r[2] - X[n][k]));
	})
);
console.log('LMS → XYZ least-squares fit:');
for (const row of fit) console.log('  ', row.map((v) => v.toFixed(8)).join('  '));
console.log('worst residual', worst.toExponential(2));

const fmt = (v) => (v === 0 ? '0' : Number(v.toPrecision(6)).toString());
const rows = (t) => t.map((r) => `[${r.map(fmt).join(',')}]`).join(',');
const out = `// Generated by scripts/data/vision-color/build.mjs: do not edit.
//
// Source: Colour & Vision Research Laboratory (CVRL), UCL, http://www.cvrl.org/
//   LMS: Stockman, A. & Sharpe, L. T. (2000). The spectral sensitivities of the middle- and
//   long-wavelength-sensitive cones derived from measurements in observers of known genotype.
//   Vision Research 40, 1711–1737; adopted as CIE 170-1:2006. CVRL file linss2_10e_1: 2° field,
//   linear energy units, each cone's curve normalised to a peak of 1.
//   XYZ: CIE 2012 2° colour-matching functions (CIE 170-2:2015), CVRL file lin2012xyz2e_1_7sf,
//   which CVRL derives from the LMS functions above.
// Read from CVRL's own files (http://www.cvrl.org/database/data/, downloaded 2026-10-17). They
// were first taken from the colour-science library's verbatim copy (BSD-3-Clause) while cvrl.org
// was down on 2026-10-14; the two agree (LMS identical, XYZ to the 6 significant figures kept).
// Subset: every nanometre from ${FROM} to ${TO} nm. CVRL leaves S blank above 615 nm (stored as 0).

/** First wavelength of the tables, in nm; row i is ${FROM} + i nm. */
export const NM0 = ${FROM};
/** Last wavelength of the tables, in nm. */
export const NM1 = ${TO};

/** [L, M, S] cone sensitivities (linear energy, peak 1), one row per nm. */
export const LMS: readonly (readonly [number, number, number])[] = [${rows(L)}];

/** [x̄, ȳ, z̄] CIE 2012 2° colour-matching functions, one row per nm. */
export const XYZ: readonly (readonly [number, number, number])[] = [${rows(X)}];
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${(out.length / 1024).toFixed(1)} KB)`);
