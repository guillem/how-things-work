#!/usr/bin/env node
/**
 * Builds e2e/fixtures/glove-float-sample.ts: the original (32-bit text) GloVe vectors of a few
 * words the embeddings page uses, so a test can check that the page's 8-bit vectors
 * (glove-data.ts, made by build.mjs) give the same similarities.
 *
 *   node scripts/data/embeddings/build-fixture.mjs <cache dir>
 *
 * Fetches only the start of glove.6B.100d.txt from the official glove.6B.zip, the way build.mjs
 * does (the zip's central directory, then the first FETCH compressed bytes of the member), and
 * keeps the WORDS rows as they are in the file. Source: GloVe "glove.6B" 100d, Stanford NLP,
 * https://nlp.stanford.edu/projects/glove/ (Pennington, Socher & Manning, EMNLP 2014),
 * Open Data Commons PDDL 1.0. Test fixture only: not shipped with the site.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const ZIP_URL = 'https://downloads.cs.stanford.edu/nlp/data/glove.6B.zip';
const MEMBER = 'glove.6B.100d.txt';
const FETCH = 2_000_000; // compressed bytes: the ~5 000 most frequent words
const OUT = path.resolve(import.meta.dirname, '../../../e2e/fixtures/glove-float-sample.ts');

// Words the page names (similarities, analogies, neighbours), spread over the frequencies.
const WORDS = `king queen man woman prince cat dog horse car train paris france london britain
rome italy good bad better best happy sad love music song doctor teacher computer money water
red blue`
	.split(/\s+/)
	.filter(Boolean);

async function get(url, start, end) {
	const res = await fetch(url, { headers: { Range: `bytes=${start}-${end}` } });
	if (res.status !== 206) throw new Error(`${url} bytes ${start}-${end}: HTTP ${res.status}`);
	return Buffer.from(await res.arrayBuffer());
}

async function cached(dir, name, make) {
	const file = path.join(dir, name);
	if (fs.existsSync(file)) return fs.readFileSync(file);
	const buf = await make();
	fs.writeFileSync(file, buf);
	return buf;
}

const dir = process.argv[2];
if (!dir) {
	console.error('usage: node scripts/data/embeddings/build-fixture.mjs <cache dir>');
	process.exit(1);
}
const head = await fetch(ZIP_URL, { method: 'HEAD' });
const size = Number(head.headers.get('content-length'));
if (!size) throw new Error('no content-length for ' + ZIP_URL);
const tail = await cached(dir, 'glove6B-tail.bin', () => get(ZIP_URL, size - 65536, size - 1));
let offset = -1;
for (let i = tail.indexOf('PK\x01\x02'); i !== -1; i = tail.indexOf('PK\x01\x02', i + 4)) {
	const nameLength = tail.readUInt16LE(i + 28);
	const name = tail.toString('latin1', i + 46, i + 46 + nameLength);
	if (name === MEMBER) offset = tail.readUInt32LE(i + 42);
}
if (offset < 0) throw new Error(`${MEMBER} not found in the zip's central directory`);
const part = await cached(dir, `glove6B-100d-start-${FETCH}.bin`, () =>
	get(ZIP_URL, offset, offset + FETCH - 1)
);
if (part.readUInt32LE(0) !== 0x04034b50) throw new Error('not a local file header');
const start = 30 + part.readUInt16LE(26) + part.readUInt16LE(28);
const text = zlib
	.inflateRawSync(part.subarray(start), { finishFlush: zlib.constants.Z_SYNC_FLUSH })
	.toString('utf8');
const lines = text.slice(0, text.lastIndexOf('\n')).split('\n');

const rows = new Map();
for (const line of lines) {
	const word = line.slice(0, line.indexOf(' '));
	if (WORDS.includes(word) && !rows.has(word)) rows.set(word, line);
}
const missing = WORDS.filter((w) => !rows.has(w));
if (missing.length) throw new Error(`not in the first ${lines.length} rows: ${missing.join(' ')}`);
for (const w of WORDS) {
	const nums = rows.get(w).split(' ').slice(1);
	if (nums.length !== 100 || nums.some((x) => !Number.isFinite(Number(x))))
		throw new Error(`bad row for ${w}`);
}

const body = `/**
 * Test fixture: the original GloVe vectors (glove.6B, 100 dimensions, as printed in
 * glove.6B.100d.txt) of ${WORDS.length} words, to check the page's 8-bit copy against. GENERATED by
 * scripts/data/embeddings/build-fixture.mjs from the first ${FETCH} compressed bytes of
 * glove.6B.100d.txt in https://downloads.cs.stanford.edu/nlp/data/glove.6B.zip (retrieved
 * 2026-10-17). GloVe: Pennington, Socher & Manning, EMNLP 2014; Open Data Commons PDDL 1.0.
 * Not shipped with the site.
 */
export const FLOAT_VECTORS: Record<string, string> = {
${WORDS.map((w) => `\t${w}: '${rows.get(w).split(' ').slice(1).join(' ')}'`).join(',\n')}
};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${WORDS.length} words from ${lines.length} rows`);
