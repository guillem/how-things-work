// Builds src/routes/speculative-decoding/drafts-data.ts: the draft models of the speculative
// decoding page, all over the alphabet of the target (the trained tiny GPT of kv-cache-inference):
//
// - a smaller tiny GPT (width 16 instead of 32, the same 2 layers, 4 heads and 64-character
//   context), trained with the training page's own code (`train.ts`, imported as it is) for the
//   same 3,000 steps on the same text;
// - the character counts (unigram) and the counts of each character after each character
//   (bigram) of the same training text.
//
// Data: Tiny Shakespeare (Karpathy's char-rnn, MIT; the text is public domain), the copy the
// n-gram page ships, split as nanoGPT does (first 90% to learn from).
//
// Usage (Node ≥ 23 runs TypeScript directly; a few minutes on one core):
//   node scripts/data/speculative-decoding/build.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { Alphabet, split } from '../../../src/routes/ngram-text-models/ngram.ts';
import { Run } from '../../../src/routes/training-a-tiny-language-model/train.ts';

const ROUTE = new URL('../../../src/routes/speculative-decoding/', import.meta.url);
const TEXT = new URL('../../../src/routes/ngram-text-models/tinyshakespeare.txt', import.meta.url);

const WIDTH = 16;
const CONTEXT = 64;

const text = readFileSync(TEXT, 'utf8');
const chars = new Alphabet(text).chars;
const index = new Map(chars.map((c, i) => [c, i]));
const enc = (s: string) => Int32Array.from(Array.from(s), (c) => index.get(c) ?? 0);
const { train, heldOut } = split(text);
const codes = enc(train);

const V = chars.length;
const unigram = new Array<number>(V).fill(0);
const bigram = new Array<number>(V * V).fill(0);
for (let i = 0; i < codes.length; i++) {
	unigram[codes[i]]++;
	if (i > 0) bigram[codes[i - 1] * V + codes[i]]++;
}

const run = new Run(chars, codes, enc(heldOut), WIDTH, CONTEXT, Infinity);
const t0 = performance.now();
while (!run.done) {
	run.advance();
	if (run.step % 250 === 0)
		console.log(`step ${run.step}, ${((performance.now() - t0) / 1000).toFixed(0)} s`);
}
const last = run.progress.points[run.progress.points.length - 1];
console.log(`train ${last.train.toFixed(3)}, held-out ${last.val.toFixed(3)} nats/char`);

const f32 = Float32Array.from(run.model.weights);
const b64 = Buffer.from(f32.buffer).toString('base64');
const out = `// Generated by scripts/data/speculative-decoding/build.ts: do not edit.
// Draft models over Tiny Shakespeare (public domain; the char-rnn copy is MIT), first 90%:
// character counts (unigram), counts of each character after each character (bigram, row =
// previous character), and a smaller tiny GPT (width ${WIDTH}, ${run.model.config.heads} heads,
// ${run.model.config.layers} layers, context ${CONTEXT}) trained with the training page's code for
// ${run.step} steps: held-out loss ${last.val.toFixed(3)} nats per character. Weights as
// little-endian float32, base64.
export const draftsData = {
	chars: ${JSON.stringify(chars.join(''))},
	unigram: [${unigram.join(', ')}],
	bigram: [${bigram.join(', ')}],
	small: {
		width: ${WIDTH},
		context: ${CONTEXT},
		heads: ${run.model.config.heads},
		layers: ${run.model.config.layers},
		heldOutLoss: ${last.val.toFixed(4)},
		weights:
			'${b64}'
	}
};
`;
writeFileSync(new URL('drafts-data.ts', ROUTE), out);
console.log(`wrote drafts-data.ts (${(out.length / 1024).toFixed(0)} kB)`);
