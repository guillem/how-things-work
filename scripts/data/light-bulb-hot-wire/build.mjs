#!/usr/bin/env node
/**
 * Builds src/routes/light-bulb-hot-wire/cie-data.ts: the CIE 1931 2° colour-matching functions
 * x̄, ȳ, z̄ every 5 nm from 360 to 830 nm, from the CIE's own open-access datasets.
 *
 *   node scripts/data/light-bulb-hot-wire/build.mjs <cache dir>
 *
 * 1. Fetch. CIE_xyz_1931_2deg.csv (DOI 10.25039/CIE.DS.xvudnb9b) and CIE_sle_photopic.csv
 *    (V(λ), DOI 10.25039/CIE.DS.dktna2s3), 1 nm rows from 360 to 830 nm, from
 *    https://files.cie.co.at/Publications-datasets/ (linked from cie.co.at/data-tables). Their
 *    metadata files (`<name>_metadata.json`) give the licence: CC BY-SA 4.0. The downloads are
 *    cached in the given directory (outside the repository).
 * 2. Check. The photopic V(λ) must equal the 1931 ȳ at every nanometre (the CIE defined ȳ to be
 *    V(λ)), so the page stores ȳ once and uses it as the eye's sensitivity.
 * 3. Subset. Every 5 nm (the page integrates smooth Planck spectra; 5 nm steps change the
 *    integrals by less than 0.1%).
 */
import fs from 'node:fs';
import path from 'node:path';

const BASE = 'https://files.cie.co.at/Publications-datasets/';
const OUT = path.resolve(
	import.meta.dirname,
	'../../../src/routes/light-bulb-hot-wire/cie-data.ts'
);

const cache = process.argv[2];
if (!cache) {
	console.error('usage: node scripts/data/light-bulb-hot-wire/build.mjs <cache dir>');
	process.exit(1);
}
fs.mkdirSync(cache, { recursive: true });

/** Rows of a CIE csv file, keyed by wavelength. */
async function table(name) {
	const file = path.join(cache, name);
	if (!fs.existsSync(file)) {
		const res = await fetch(BASE + name);
		if (!res.ok) throw new Error(`${BASE + name}: ${res.status}`);
		fs.writeFileSync(file, await res.text());
	}
	const rows = new Map();
	for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
		if (!line.trim()) continue;
		const cells = line.split(',').map((s) => s.trim());
		if (!/^\d+$/.test(cells[0])) throw new Error(`${name}: bad row "${line}"`);
		rows.set(Number(cells[0]), cells.slice(1).map(Number));
	}
	return rows;
}

const xyz = await table('CIE_xyz_1931_2deg.csv');
const v = await table('CIE_sle_photopic.csv');
for (const [nm, [y]] of v) {
	if (xyz.get(nm)?.[1] !== y) throw new Error(`V(${nm} nm) = ${y} differs from ȳ`);
}

const rows = [];
for (let nm = 360; nm <= 830; nm += 5) {
	const r = xyz.get(nm);
	if (!r) throw new Error(`missing ${nm} nm`);
	rows.push(`\t[${r.map((x) => String(Number(x.toPrecision(7)))).join(', ')}]`);
}

const out = `// Generated by scripts/data/light-bulb-hot-wire/build.mjs: do not edit.
//
// Source: CIE 2019, Colour-matching functions of CIE 1931 standard colorimetric observer,
// International Commission on Illumination (CIE), Vienna, DOI 10.25039/CIE.DS.xvudnb9b, file
// CIE_xyz_1931_2deg.csv from https://files.cie.co.at/Publications-datasets/ (cie.co.at/data-tables).
// Licence: CC BY-SA 4.0 (the dataset's metadata). The CIE photopic V(λ) (DOI
// 10.25039/CIE.DS.dktna2s3) equals ȳ at every nanometre; the build checks it.
// Subset: every 5 nm from 360 to 830 nm.

/** First wavelength of the table, in nm; row i is 360 + 5i nm. */
export const CMF_NM0 = 360;
/** Spacing of the rows, in nm. */
export const CMF_STEP = 5;

/** [x̄, ȳ, z̄] of the CIE 1931 2° observer; ȳ is also V(λ), the eye's sensitivity in daylight. */
export const CMF: readonly (readonly [number, number, number])[] = [
${rows.join(',\n')}
];
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${rows.length} rows`);
