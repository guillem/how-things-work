#!/usr/bin/env node
/**
 * Builds `src/routes/carbon-cycle/gcb2025.ts`: the annual global CO₂ budget,
 * 1750–2024, from the Global Carbon Budget 2025.
 *
 *   node scripts/data/carbon-cycle/build-budget.mjs [path/to/historical-budget.csv]
 *
 * Source: Friedlingstein, P. et al. (2026), "Global Carbon Budget 2025",
 * Earth System Science Data 18, 3211–3288, https://doi.org/10.5194/essd-18-3211-2026,
 * data file Global_Carbon_Budget_2025_v1.0.xlsx, sheet "Historical Budget"
 * (https://doi.org/10.18160/GCP-2025), licence CC BY 4.0.
 *
 * The ICOS portal serves the xlsx only behind a licence click-through, so this
 * script reads openclimatedata's CSV conversion of that sheet (same numbers,
 * full precision):
 * https://openclimatedata.github.io/global-carbon-budget/data/global-carbon-budget-2025-historical-budget.csv
 * The script checks the conversion against the paper: the 2015–2024 means must
 * reproduce Table 7 (9.8, 1.4, 5.6, 3.2, 2.4 GtC/yr) and the 1850–2024 sums
 * Table 8 (495, 250, 290, 200, 175 GtC, rounded to 5).
 *
 * Subset: per year, fossil emissions INCLUDING the cement carbonation sink
 * (the paper's E_FOS: the CSV column excludes it, so we subtract it), land-use
 * change emissions (from 1850; the sheet has none before), and the observed
 * atmospheric growth, ocean sink and land sink. All GtC/yr, rounded to 3
 * decimals. Before 1850 the sheet has no land-use emissions; Table 8 gives
 * 280 GtC for 1750–2024 against 250 for 1850–2024, so the missing 30 GtC is
 * spread evenly over 1750–1849 (0.3 GtC/yr), flagged in `lucFilled`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const URL =
	'https://openclimatedata.github.io/global-carbon-budget/data/global-carbon-budget-2025-historical-budget.csv';
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/carbon-cycle/gcb2025.ts');

const text = process.argv[2]
	? readFileSync(process.argv[2], 'utf8')
	: await (await fetch(URL)).text();
const lines = text.split('\n').filter((l) => l.trim() && !l.startsWith('#'));
const header = lines[0].split(',');
const col = (name) => {
	const i = header.indexOf(name);
	if (i < 0) throw new Error(`missing column ${name}`);
	return i;
};
const iF = col('fossil emissions excluding carbonation');
const iL = col('land-use change emissions');
const iG = col('atmospheric growth');
const iO = col('ocean sink');
const iS = col('land sink');
const iC = col('cement carbonation sink');

const rows = lines.slice(1).map((l) => {
	const c = l.split(',');
	const n = (i) => (c[i] === '' || c[i] === undefined ? null : Number(c[i]));
	return {
		year: Number(c[0]),
		fos: (n(iF) ?? 0) - (n(iC) ?? 0),
		luc: n(iL),
		atm: n(iG),
		ocean: n(iO),
		land: n(iS)
	};
});

const mean = (key, a, b) => {
	const r = rows.filter((x) => x.year >= a && x.year <= b);
	return r.reduce((s, x) => s + (x[key] ?? 0), 0) / r.length;
};
const sum = (key, a, b) =>
	rows.filter((x) => x.year >= a && x.year <= b).reduce((s, x) => s + (x[key] ?? 0), 0);
const expect = (label, got, want, tol) => {
	if (Math.abs(got - want) > tol)
		throw new Error(`${label}: ${got.toFixed(2)}, paper says ${want}`);
};
expect('E_FOS 2015–2024', mean('fos', 2015, 2024), 9.8, 0.05);
expect('E_LUC 2015–2024', mean('luc', 2015, 2024), 1.4, 0.05);
expect('G_ATM 2015–2024', mean('atm', 2015, 2024), 5.6, 0.05);
expect('S_OCEAN 2015–2024', mean('ocean', 2015, 2024), 3.2, 0.05);
expect('S_LAND 2015–2024', mean('land', 2015, 2024), 2.4, 0.05);
expect('E_FOS 1850–2024', sum('fos', 1850, 2024), 495, 2.5);
expect('E_LUC 1850–2024', sum('luc', 1850, 2024), 250, 2.5);
expect('G_ATM 1850–2024', sum('atm', 1850, 2024), 290, 2.5);
expect('S_OCEAN 1850–2024', sum('ocean', 1850, 2024), 200, 2.5);
expect('S_LAND 1850–2024', sum('land', 1850, 2024), 175, 2.5);

const PRE1850_LUC = 30 / 100;
const r3 = (v) => (v === null ? 'null' : String(Math.round(v * 1000) / 1000));
const first = rows[0].year;
const series = (key, fill) => rows.map((x) => r3(x[key] ?? fill(x))).join(',');

const out = `/**
 * Annual global CO₂ budget, ${first}–${rows.at(-1).year}, GtC per year. GENERATED by
 * scripts/data/carbon-cycle/build-budget.mjs: do not edit by hand.
 *
 * Source: Friedlingstein, P. et al. (2026), "Global Carbon Budget 2025",
 * Earth System Science Data 18, 3211–3288, https://doi.org/10.5194/essd-18-3211-2026;
 * data: Global_Carbon_Budget_2025_v1.0.xlsx, "Historical Budget" sheet,
 * https://doi.org/10.18160/GCP-2025 (read through openclimatedata's CSV
 * conversion, checked against the paper's Tables 7 and 8). Licence CC BY 4.0.
 *
 * - fossil: fossil CO₂ emissions including the cement carbonation sink (E_FOS)
 * - luc: net land-use change emissions (E_LUC); before 1850 the sheet has none,
 *   and 0.3 GtC/yr is filled in (Table 8: 280 GtC for 1750–2024 minus 250 for
 *   1850–2024, spread evenly over 1750–1849)
 * - atm, ocean, land: the observed atmospheric growth, ocean sink and land sink
 */
export const FIRST_YEAR = ${first};
export const LUC_FILLED_BEFORE = 1850;
export const fossil: readonly number[] = [${series('fos', () => 0)}];
export const luc: readonly number[] = [${series('luc', () => PRE1850_LUC)}];
export const atm: readonly (number | null)[] = [${series('atm', () => null)}];
export const ocean: readonly (number | null)[] = [${series('ocean', () => null)}];
export const land: readonly (number | null)[] = [${series('land', () => null)}];
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${rows.length} years)`);
