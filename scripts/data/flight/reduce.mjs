#!/usr/bin/env node
/**
 * Builds `src/routes/flight/naca0012.ts`: the measured lift and drag of the NACA 0012
 * wing section from Ladson's wind-tunnel tests, through the stall.
 *
 *   curl -O https://tmbwg.github.io/turbmodels/NACA0012_validation/CLCD_Ladson_expdata.dat
 *   node scripts/data/flight/reduce.mjs CLCD_Ladson_expdata.dat
 *
 * Source: C. L. Ladson, "Effects of Independent Variation of Mach and Reynolds Numbers on
 * the Low-Speed Aerodynamic Characteristics of the NACA 0012 Airfoil Section", NASA TM-4074
 * (1988), Langley Low-Turbulence Pressure Tunnel; Reynolds number 6 million, Mach 0.15,
 * transition fixed with trip strips of 80, 120 and 180 grit. A work of the US Government,
 * in the public domain. Transcribed by the NASA Turbulence Modeling Resource
 * (https://turbmodels.larc.nasa.gov/naca0012_val.html, mirrored at
 * https://tmbwg.github.io/turbmodels/naca0012_val.html), file CLCD_Ladson_expdata.dat.
 *
 * Subset: all of it (three runs of 17–18 angles each); numbers as in the file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = process.argv[2];
if (!file) throw new Error('usage: reduce.mjs <CLCD_Ladson_expdata.dat>');
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/flight/naca0012.ts');

/** @type {{grit: number, rows: number[][]}[]} */
const zones = [];
for (const line of readFileSync(file, 'utf8').split('\n')) {
	const z = /zone, t="(\d+) grit"/.exec(line);
	if (z) zones.push({ grit: Number(z[1]), rows: [] });
	else if (zones.length && /^\s*-?[\d.]/.test(line))
		zones[zones.length - 1].rows.push(line.trim().split(/\s+/).map(Number));
}
if (zones.length !== 3) throw new Error(`expected 3 zones, found ${zones.length}`);

const body = zones
	.map(
		(z) =>
			`\t{\n\t\tgrit: ${z.grit},\n\t\trows: [\n${z.rows.map((r) => `\t\t\t[${r.join(', ')}]`).join(',\n')}\n\t\t]\n\t}`
	)
	.join(',\n');

writeFileSync(
	OUT,
	`/**
 * Measured lift and drag of the NACA 0012 wing section, through the stall.
 *
 * C. L. Ladson, "Effects of Independent Variation of Mach and Reynolds Numbers on the
 * Low-Speed Aerodynamic Characteristics of the NACA 0012 Airfoil Section", NASA TM-4074
 * (1988). Langley Low-Turbulence Pressure Tunnel, Reynolds number 6 million, Mach 0.15,
 * transition fixed by trip strips of 80, 120 and 180 grit. A work of the US Government,
 * in the public domain. Transcribed by the NASA Turbulence Modeling Resource
 * (https://turbmodels.larc.nasa.gov/naca0012_val.html), file CLCD_Ladson_expdata.dat.
 * Generated by scripts/data/flight/reduce.mjs; all rows, numbers as in the file.
 */

/** Angle of attack (degrees), lift coefficient c_l, drag coefficient c_d. */
export const LADSON: readonly {
	grit: number;
	rows: readonly (readonly [number, number, number])[];
}[] = [
${body}
];
`
);
console.log(`wrote ${OUT}`);
