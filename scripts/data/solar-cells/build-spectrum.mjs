#!/usr/bin/env node
/**
 * Builds `src/routes/solar-cells/spectrum.ts`: the standard sunlight a solar cell is rated
 * in, reduced to photon-energy bins.
 *
 *   node scripts/data/solar-cells/build-spectrum.mjs <path to ASTMG173.csv>
 *
 * Source: ASTM G173-03, "Standard Tables for Reference Solar Spectral Irradiances: Direct
 * Normal and Hemispherical on 37° Tilted Surface" (ASTM International, 2003), as
 * distributed by the National Laboratory of the Rockies (formerly NREL):
 * https://www.nlr.gov/grid/solar-resource/spectra-am1.5 (file astmg173.zip, ASTMG173.csv;
 * formerly rredc.nrel.gov/solar/spectra/am1.5). The tables were computed with Gueymard's
 * SMARTS 2.9.2 model. Column "Global tilt" (AM1.5G: direct + diffuse light on a surface
 * tilted 37° towards the sun, air mass 1.5) is used; it is the spectrum every solar-cell
 * efficiency is quoted for. No licence is stated on the NLR page; cite ASTM G173-03 and
 * the NLR page.
 *
 * Reduction: the original grid (0.5 nm steps from 280 to 400 nm, 1 nm to 1700 nm, 5 nm to
 * 4000 nm; 2002 rows) is integrated with the trapezoid rule, each interval split into 50
 * sub-steps, and every sub-step's photons and power are added to the 0.01 eV photon-energy
 * bin that contains it. Bins run from 0.30 eV to 4.43 eV (4133 nm to 280 nm). Photon energy
 * E = hc/λ with hc = 1239.841984 eV·nm (CODATA 2018).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = process.argv[2];
if (!file) throw new Error('usage: build-spectrum.mjs <ASTMG173.csv>');
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/solar-cells/spectrum.ts');

const HC = 1239.841984; // eV·nm
const Q = 1.602176634e-19; // J per eV
const E0 = 0.3;
const DE = 0.01;
const NBINS = Math.ceil((4.43 - E0) / DE);

const rows = readFileSync(file, 'utf8')
	.split(/\r?\n/)
	.map((l) => l.split(','))
	.filter((c) => c.length >= 3 && Number.isFinite(Number(c[0])) && c[0].trim() !== '')
	.map((c) => [Number(c[0]), Number(c[2])]);
if (rows.length !== 2002) throw new Error(`expected 2002 rows, got ${rows.length}`);

const flux = new Float64Array(NBINS); // photons m⁻² s⁻¹ per bin
const power = new Float64Array(NBINS); // W m⁻² per bin
let total = 0;
const SUB = 50;
for (let i = 0; i + 1 < rows.length; i++) {
	const [l0, g0] = rows[i];
	const [l1, g1] = rows[i + 1];
	for (let s = 0; s < SUB; s++) {
		const u = (s + 0.5) / SUB;
		const lam = l0 + (l1 - l0) * u;
		const g = g0 + (g1 - g0) * u; // W m⁻² nm⁻¹
		const p = (g * (l1 - l0)) / SUB; // W m⁻²
		const e = HC / lam;
		const bin = Math.floor((e - E0) / DE);
		if (bin < 0 || bin >= NBINS) throw new Error(`photon energy ${e} out of range`);
		power[bin] += p;
		flux[bin] += p / (e * Q);
		total += p;
	}
}

const fmt = (v) => Number(v.toPrecision(5));
const src = `/**
 * Standard sunlight, ASTM G173-03 AM1.5 global (37° tilt), in photon-energy bins.
 * GENERATED by scripts/data/solar-cells/build-spectrum.mjs — do not edit by hand.
 *
 * Source: ASTM G173-03 reference spectra (SMARTS 2.9.2, Gueymard), distributed by the
 * National Laboratory of the Rockies (formerly NREL),
 * https://www.nlr.gov/grid/solar-resource/spectra-am1.5 (ASTMG173.csv, column "Global
 * tilt"). No licence is stated; cite ASTM G173-03 and the NLR page.
 *
 * Subset: the 2002-point table (280–4000 nm) integrated (trapezoid rule) into ${NBINS} bins
 * of ${DE} eV from ${E0} eV; bin i covers [${E0} + ${DE}·i, ${E0} + ${DE}·(i + 1)) eV. Total
 * irradiance ${total.toFixed(2)} W/m².
 */

/** Lower edge of the first bin (eV). */
export const E_START = ${E0};
/** Bin width (eV). */
export const E_STEP = ${DE};
/** Photons per m² per second in each bin. */
export const FLUX: readonly number[] = [${Array.from(flux, fmt).join(', ')}];
/** Power per m² in each bin (W/m²). */
export const POWER: readonly number[] = [${Array.from(power, fmt).join(', ')}];
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: ${NBINS} bins, ${total.toFixed(2)} W/m²`);
