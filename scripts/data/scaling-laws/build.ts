// Builds src/routes/scaling-laws/sweep-data.ts: a small scaling sweep of the tiny character-level
// GPT of training-a-tiny-language-model, trained with that page's own code (`Run` in its
// `train.ts`, imported as it is: the same seeds, schedule and 3,000 steps of 1,024 characters)
// at seven widths and five amounts of training text, all with a context of 32 characters.
// For every run it keeps the train and held-out losses at the page's measurement steps; the
// sweep reads off the lowest held-out loss (early stopping, as Kaplan et al. 2020 did for L(D)).
//
// Data: Tiny Shakespeare (Karpathy's char-rnn, MIT; the text is public domain), the copy the
// n-gram page ships, split as nanoGPT does: the first 90% to learn from, the last 10% held out.
//
// Usage (Node ≥ 23 runs TypeScript directly; about 35 minutes on 10 cores, bound by the
// width-96 runs, ~0.55 s a step):
//   node scripts/data/scaling-laws/build.ts [workers]
import { readFileSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { Alphabet, split } from '../../../src/routes/ngram-text-models/ngram.ts';
import {
	Run,
	runKey,
	type Point
} from '../../../src/routes/training-a-tiny-language-model/train.ts';

const ROUTE = new URL('../../../src/routes/scaling-laws/', import.meta.url);
const TEXT = new URL('../../../src/routes/ngram-text-models/tinyshakespeare.txt', import.meta.url);

/** The sweep's axes (kept in step with `SWEEP_WIDTHS` and `SWEEP_DATA` in sweep.ts). */
const WIDTHS = [8, 16, 24, 32, 48, 64, 96];
const DATA = [10_000, 30_000, 100_000, 300_000, Infinity];
const CONTEXT = 32;

function load() {
	const text = readFileSync(TEXT, 'utf8');
	const chars = new Alphabet(text).chars;
	const index = new Map(chars.map((c, i) => [c, i]));
	const enc = (s: string) => Int32Array.from(Array.from(s), (c) => index.get(c) ?? 0);
	const { train, heldOut } = split(text);
	return { chars, train: enc(train), val: enc(heldOut) };
}

interface Job {
	width: number;
	data: number;
}
interface Result {
	key: string;
	points: Point[];
	minutes: number;
}

const r4 = (v: number) => Math.round(v * 1e4) / 1e4;

if (!isMainThread) {
	const job = workerData as Job;
	const { chars, train, val } = load();
	const t0 = performance.now();
	const run = new Run(chars, train, val, job.width, CONTEXT, job.data);
	while (!run.done) run.advance();
	parentPort?.postMessage({
		key: runKey(job.width, CONTEXT, job.data),
		points: run.progress.points,
		minutes: (performance.now() - t0) / 60000
	} satisfies Result);
} else {
	const jobs: Job[] = [];
	for (const width of WIDTHS) for (const data of DATA) jobs.push({ width, data });
	jobs.sort((a, b) => b.width - a.width); // the slowest first
	const workers = Number(process.argv[2] ?? Math.max(1, availableParallelism() - 2));
	const results: Result[] = [];
	let next = 0;
	await new Promise<void>((resolve, reject) => {
		let running = 0;
		const launch = () => {
			if (next >= jobs.length) {
				if (running === 0) resolve();
				return;
			}
			const job = jobs[next++];
			running++;
			const w = new Worker(new URL(import.meta.url), { workerData: job });
			w.on('message', (r: Result) => {
				results.push(r);
				const best = r.points.reduce((a, b) => (b.val < a.val ? b : a));
				console.log(
					`${r.key}: best held-out ${best.val.toFixed(4)} at step ${best.step}, ${r.minutes.toFixed(1)} min`
				);
			});
			w.on('error', reject);
			w.on('exit', () => {
				running--;
				launch();
			});
		};
		for (let i = 0; i < workers; i++) launch();
	});
	results.sort((a, b) => (a.key < b.key ? -1 : 1));
	const runs: Record<string, number[][]> = {};
	for (const r of results) runs[r.key] = r.points.map((p) => [p.step, r4(p.train), r4(p.val)]);
	const out = `// Generated by scripts/data/scaling-laws/build.ts: do not edit.
// A sweep of training-a-tiny-language-model's tiny GPT on Tiny Shakespeare (the text is public
// domain; the char-rnn copy is MIT): [step, train loss, held-out loss] in nats per character.
export const data = ${JSON.stringify({ context: CONTEXT, widths: WIDTHS, data: DATA.map((d) => (Number.isFinite(d) ? d : 'all')), runs })};
`;
	writeFileSync(new URL('sweep-data.ts', ROUTE), out);
	console.log(`wrote sweep-data.ts (${(out.length / 1024).toFixed(0)} kB)`);
}
