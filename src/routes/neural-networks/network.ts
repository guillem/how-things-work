// ---------------------------------------------------------------------- one example at a time

/** The step-through network: 2 inputs, 2 hidden tanh neurons, 1 output, on the four corners. */
export const STEP_SIZES = [2, 2, 1];
export const STEP_LR = 0.5;
const stepNets: Net[] = [];
let stepOrder: number[] = [];

/**
 * The step-through network after `n` single-example gradient-descent steps (η = 0.5), taken on
 * the four-corners examples in a fixed shuffled order. Example n is the one the next step
 * trains on.
 */
export function stepThrough(n: number): { net: Net; example: Example } {
	const data = dataset('xor');
	if (!stepNets.length) {
		const rand = rng(99);
		stepOrder = data.map((_, i) => i);
		for (let i = stepOrder.length - 1; i > 0; i--) {
			const j = Math.floor(rand() * (i + 1));
			[stepOrder[i], stepOrder[j]] = [stepOrder[j], stepOrder[i]];
		}
		stepNets.push(createNet(STEP_SIZES, 'tanh', 1));
	}
	const ex = (k: number) => data[stepOrder[k % data.length]];
	while (stepNets.length <= n) {
		const k = stepNets.length - 1;
		const next = cloneNet(stepNets[k]);
		applyStep(next, gradient(next, [ex(k)]), STEP_LR);
		stepNets.push(next);
	}
	return { net: stepNets[n], example: ex(n) };
}
