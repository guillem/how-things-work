// Builds src/routes/wind-turbine-aerodynamics/nrel5mw.ts from the files fetch.mjs downloaded:
//   node scripts/data/wind-turbine-aerodynamics/build.mjs <raw-dir>
// Keeps, for each of the eight airfoil tables, the angle of attack, lift and drag columns (the
// pitching moment is not used), and from the AeroDyn blade table the 17 analysis nodes of
// Jonkman et al. (2009), Table 2-1: radius from the rotor centre, twist, chord and airfoil.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: build.mjs <raw-dir>');
const out = new URL('../../../src/routes/wind-turbine-aerodynamics/nrel5mw.ts', import.meta.url);

// AeroDyn's AFNames order in the NREL 5-MW AeroDyn input (AFID 1…8).
const AIRFOILS = [
	'Cylinder1',
	'Cylinder2',
	'DU40_A17',
	'DU35_A17',
	'DU30_A17',
	'DU25_A17',
	'DU21_A17',
	'NACA64_A17'
];

function polar(name) {
	const lines = readFileSync(join(dir, `${name}.dat`), 'utf8').split(/\r?\n/);
	const i = lines.findIndex((l) => /\bNumAlf\b/.test(l));
	const n = parseInt(lines[i].trim().split(/\s+/)[0], 10);
	const rows = [];
	for (let k = i + 1; rows.length < n && k < lines.length; k++) {
		const l = lines[k].trim();
		if (!l || l.startsWith('!')) continue;
		const [a, cl, cd] = l.split(/\s+/).map(Number);
		rows.push([a, cl, cd]);
	}
	if (rows.length !== n) throw new Error(`${name}: ${rows.length} of ${n} rows`);
	return rows;
}

const HUB = 1.5;
const blade = readFileSync(join(dir, 'NRELOffshrBsline5MW_AeroDyn_blade.dat'), 'utf8')
	.split(/\r?\n/)
	.filter((l) => /^\s*[0-9.]+E[+-]\d+\s/.test(l))
	.map((l) => l.trim().split(/\s+/).map(Number))
	.map((c) => ({ span: c[0], twist: c[4], chord: c[5], af: c[6] }));
// The table lists 19 nodes (AeroDyn reads NumBlNds = 19 rows and ignores a spare tip row after
// them); the interior 17 are the element centres of Jonkman et al. (2009), Table 2-1, and the
// first and last are the blade root and tip.
const nodes = blade.slice(1, 18);
if (nodes.length !== 17) throw new Error('expected 17 interior nodes');
// Element lengths (DRNodes) of Table 2-1: they add up to the 61.5 m from the hub to the tip.
const DR = [
	2.7333, 2.7333, 2.7333, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 4.1, 2.7333, 2.7333,
	2.7333
];

const fmt = (v) => Number(v.toFixed(4));
let ts = `// Generated by scripts/data/wind-turbine-aerodynamics/build.mjs: do not edit by hand.
//
// NREL 5-MW reference wind turbine (Jonkman, Butterfield, Musial & Scott 2009, "Definition of a
// 5-MW Reference Wind Turbine for Offshore System Development", NREL/TP-500-38060): the blade's
// aerodynamic nodes (Table 2-1) and its airfoil polars, as distributed in the OpenFAST r-test
// repository (glue-codes/openfast/5MW_Baseline, Apache License 2.0). The DU and NACA64 polars
// are wind-tunnel data from the DOWEC project, corrected for rotational stall delay and
// extrapolated to ±180° (Viterna) by Jonkman; columns: angle of attack (deg), Cl, Cd. Licence
// text: OPENFAST-R-TEST-LICENSE.txt beside this file. Changes: the pitching-moment column and the
// unsteady-aerodynamics parameters are dropped, and the blade table cut to its 17 analysis nodes.

export type PolarRow = readonly [alpha: number, cl: number, cd: number];

export interface Airfoil {
	name: string;
	rows: readonly PolarRow[];
}

export interface BladeNode {
	/** Distance from the rotor centre (m). */
	r: number;
	/** Length of blade the node stands for (m). */
	dr: number;
	/** Aerodynamic twist (deg), measured from the rotor plane, positive toward feather. */
	twist: number;
	/** Chord (m). */
	chord: number;
	/** Index into AIRFOILS. */
	af: number;
}

export const AIRFOILS: readonly Airfoil[] = [
`;
for (const name of AIRFOILS) {
	ts += `\t{\n\t\tname: '${name}',\n\t\trows: [\n`;
	ts += polar(name)
		.map((r) => `\t\t\t[${r.map(fmt).join(', ')}]`)
		.join(',\n');
	ts += `\n\t\t]\n\t},\n`;
}
ts += `];

export const BLADE: readonly BladeNode[] = [
`;
ts += nodes
	.map(
		(n, i) =>
			`\t{ r: ${fmt(n.span + HUB)}, dr: ${DR[i]}, twist: ${fmt(n.twist)}, chord: ${fmt(n.chord)}, af: ${n.af - 1} }`
	)
	.join(',\n');
ts += `\n];\n`;
writeFileSync(out, ts);
console.log('wrote', out.pathname);
