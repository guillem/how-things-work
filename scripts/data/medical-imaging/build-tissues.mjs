#!/usr/bin/env node
/**
 * Builds `src/routes/medical-imaging/tissues.ts`: the tissue data behind the
 * medical-imaging explainer.
 *
 *   node scripts/data/medical-imaging/build-tissues.mjs <nist-dir> <itis-txt>
 *
 * 1. X-ray mass attenuation coefficients μ/ρ (cm²/g), 20–150 keV, from
 *    J. H. Hubbell and S. M. Seltzer, "Tables of X-Ray Mass Attenuation
 *    Coefficients and Mass Energy-Absorption Coefficients", NIST Standard
 *    Reference Database 126 (public domain),
 *    https://physics.nist.gov/PhysRefData/XrayMassCoef/ComTab/<name>.html
 *    for water, tissue (Tissue, Soft ICRU-44), adipose (ICRU-44), bone
 *    (Bone, Cortical ICRU-44), lung (Lung Tissue ICRU-44) and air. <nist-dir>
 *    holds those pages saved as water.html, tissue.html, … . Densities are the
 *    ones NIST pairs with each composition (its Table 2), except inflated lung.
 * 2. Acoustic and MR properties from the IT'IS Foundation tissue database:
 *    P. A. Hasgall et al., "IT'IS Database for thermal and electromagnetic
 *    parameters of biological tissues", Version 4.1, 22 Feb 2022,
 *    doi:10.13099/VIP21000-04-1 (itis.swiss/database). <itis-txt> is
 *    "Thermal_dielectric_acoustic_MR properties_database_V4.1(Excel).txt" from
 *    the V4.1 download. Taken per tissue: the average density (kg/m³), speed of
 *    sound (m/s), attenuation α = α₀ f^b (α₀ in Np/m/MHz) and the 1.5 T T1 and
 *    T2 averages (ms). The inflated-lung density (394 kg/m³, the average of five
 *    studies) also comes from IT'IS, because NIST's lung entry is the tissue
 *    itself at 1.05 g/cm³.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const [nistDir, itisTxt] = process.argv.slice(2);
if (!nistDir || !itisTxt) {
	console.error('usage: build-tissues.mjs <nist-dir> <itis-txt>');
	process.exit(1);
}
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/medical-imaging/tissues.ts');

// ---- NIST ------------------------------------------------------------------------------
const NIST = {
	water: { file: 'water', name: 'Water, Liquid', density: 1.0 },
	soft: { file: 'tissue', name: 'Tissue, Soft (ICRU-44)', density: 1.06 },
	fat: { file: 'adipose', name: 'Adipose Tissue (ICRU-44)', density: 0.95 },
	bone: { file: 'bone', name: 'Bone, Cortical (ICRU-44)', density: 1.92 },
	lung: { file: 'lung', name: 'Lung Tissue (ICRU-44)', density: NaN },
	air: { file: 'air', name: 'Air, Dry (near sea level)', density: 1.205e-3 }
};
const ENERGIES = [20, 30, 40, 50, 60, 80, 100, 150]; // keV, all NIST grid points

const nist = {};
for (const [key, m] of Object.entries(NIST)) {
	const html = readFileSync(path.join(nistDir, `${m.file}.html`), 'utf8');
	const text = html.replace(/<[^>]*>/g, ' ');
	const rows = [...text.matchAll(/(\d\.\d+E[-+]\d+)\s+(\d\.\d+E[-+]\d+)\s+(\d\.\d+E[-+]\d+)/g)].map(
		(r) => [Number(r[1]) * 1000, Number(r[2])]
	);
	nist[key] = ENERGIES.map((e) => {
		const row = rows.find((r) => Math.abs(r[0] - e) < 1e-6);
		if (!row) throw new Error(`${key}: no row at ${e} keV`);
		return row[1];
	});
}

// ---- IT'IS ---------------------------------------------------------------------------
const rows = readFileSync(itisTxt, 'latin1')
	.split(/\r?\n/)
	.map((l) => l.split('\t'));
const col = { rho: 1, c: 64, a0: 74, b: 75, t1: 76, t2: 81 };
function itis(name) {
	const r = rows.find((r) => r[0].trim() === name);
	if (!r) throw new Error(`IT'IS: no ${name}`);
	const num = (i) => (r[i] && r[i].trim() !== '' ? Number(r[i]) : null);
	return {
		density: num(col.rho),
		speed: num(col.c),
		alpha0: num(col.a0),
		alphaPower: num(col.b),
		t1: num(col.t1),
		t2: num(col.t2)
	};
}
const ITIS = {
	air: 'Air',
	skin: 'Skin',
	fat: 'Fat',
	subcutaneousFat: 'SAT (Subcutaneous Fat)',
	muscle: 'Muscle',
	liver: 'Liver',
	blood: 'Blood',
	bone: 'Bone (Cortical)',
	lungInflated: 'Lung (Inflated)',
	whiteMatter: 'Brain (White Matter)',
	greyMatter: 'Brain (Grey Matter)',
	spleen: 'Spleen'
};
const tissue = Object.fromEntries(
	Object.entries(ITIS).map(([k, n]) => [k, { name: n, ...itis(n) }])
);
NIST.lung.density = tissue.lungInflated.density / 1000;

const r4 = (x) => (x === null ? null : Number(x.toPrecision(6)));
const out = `/**
 * Tissue data for the medical-imaging explainer. GENERATED by
 * scripts/data/medical-imaging/build-tissues.mjs — do not edit by hand.
 *
 * X-ray: mass attenuation coefficients μ/ρ (cm²/g, coherent scattering
 * included) from J. H. Hubbell and S. M. Seltzer, "Tables of X-Ray Mass
 * Attenuation Coefficients and Mass Energy-Absorption Coefficients", NIST
 * Standard Reference Database 126 (public domain),
 * https://physics.nist.gov/PhysRefData/XrayMassCoef/ (Table 4, ICRU-44
 * compositions), at their tabulated energies from 20 to 150 keV. Densities
 * (g/cm³) are the ones NIST pairs with each composition, except inflated lung,
 * whose density is the IT'IS average (NIST's lung entry is the tissue at 1.05).
 *
 * Ultrasound and MRI: average values from P. A. Hasgall et al., "IT'IS Database
 * for thermal and electromagnetic parameters of biological tissues", Version
 * 4.1 (22 Feb 2022), doi:10.13099/VIP21000-04-1, https://itis.swiss/database:
 * density (kg/m³), speed of sound (m/s), attenuation α = α₀·f^b with α₀ in
 * Np/m/MHz, and T1 and T2 at 1.5 T (ms). null where the database has no value.
 */

/** Photon energies of the X-ray table, keV. */
export const ENERGIES_KEV = ${JSON.stringify(ENERGIES)} as const;

export type XrayMaterial = ${Object.keys(NIST)
	.map((k) => `'${k}'`)
	.join(' | ')};

export const XRAY: Record<XrayMaterial, { name: string; density: number; muRho: readonly number[] }> = {
${Object.entries(NIST)
	.map(
		([k, m]) =>
			`\t${k}: { name: ${JSON.stringify(m.name)}, density: ${r4(m.density)}, muRho: ${JSON.stringify(nist[k])} }`
	)
	.join(',\n')}
};

export interface TissueProps {
	name: string;
	density: number | null;
	speed: number | null;
	alpha0: number | null;
	alphaPower: number | null;
	t1: number | null;
	t2: number | null;
}

export type Tissue = ${Object.keys(ITIS)
	.map((k) => `'${k}'`)
	.join(' | ')};

export const TISSUE: Record<Tissue, TissueProps> = {
${Object.entries(tissue)
	.map(
		([k, v]) =>
			`\t${k}: { name: ${JSON.stringify(v.name)}, density: ${r4(v.density)}, speed: ${r4(v.speed)}, alpha0: ${r4(v.alpha0)}, alphaPower: ${r4(v.alphaPower)}, t1: ${r4(v.t1)}, t2: ${r4(v.t2)} }`
	)
	.join(',\n')}
};
`;
writeFileSync(OUT, out);
console.log('wrote', OUT);
