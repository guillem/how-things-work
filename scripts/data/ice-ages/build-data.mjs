#!/usr/bin/env node
/**
 * Builds `src/routes/ice-ages/orbit-data.ts` (Earth's orbital elements, 800,000
 * years ago to 100,000 years ahead) and `src/routes/ice-ages/icecore-data.ts`
 * (Antarctic temperature and CO₂ from ice cores, 800,000 years).
 *
 *   node scripts/data/ice-ages/build-data.mjs <dir with the downloads>
 *
 * Downloads (put them in one directory, outside the repository):
 *
 * 1. La2004 orbital solution (Laskar, J., Robutel, P., Joutel, F., Gastineau, M.,
 *    Correia, A.C.M., Levrard, B., 2004: A long-term numerical solution for the
 *    insolation quantities of the Earth. Astronomy & Astrophysics 428, 261–285,
 *    https://doi.org/10.1051/0004-6361:20041335), from the IMCCE:
 *    http://vo.imcce.fr/insola/earth/online/earth/La2004/INSOLN.LA2004.BTL.ASC (past)
 *    http://vo.imcce.fr/insola/earth/online/earth/La2004/INSOLP.LA2004.BTL.ASC (future)
 *    Columns: time (kyr from J2000, negative in the past), eccentricity,
 *    obliquity (rad), longitude of perihelion from the moving equinox (rad).
 *    Licence not stated on the IMCCE page (free download); cite Laskar et al. 2004.
 * 2. EPICA Dome C deuterium and temperature, EDC3 age scale (Jouzel, J. et al.,
 *    2007: Orbital and millennial Antarctic climate variability over the past
 *    800,000 years. Science 317, 793–797, https://doi.org/10.1126/science.1141038),
 *    NOAA NCEI World Data Service for Paleoclimatology:
 *    https://www.ncei.noaa.gov/pub/data/paleo/icecore/antarctica/epica_domec/edc3deuttemp2007.txt
 *    Column 5: temperature difference from the average of the last 1000 years, °C.
 * 3. Antarctic CO₂ composite, 800 kyr, AICC2012 gas ages (Bereiter, B. et al.,
 *    2015: Revision of the EPICA Dome C CO₂ record from 800 to 600 kyr before
 *    present. Geophysical Research Letters 42, 542–549,
 *    https://doi.org/10.1002/2014GL061957), NOAA NCEI:
 *    https://www.ncei.noaa.gov/pub/data/paleo/icecore/antarctica/antarctica2015co2composite.txt
 * 4. Today's CO₂: NOAA GML global annual mean (Lan, X., Tans, P. and Thoning, K.W.,
 *    NOAA Global Monitoring Laboratory):
 *    https://gml.noaa.gov/webdata/ccgg/trends/co2/co2_annmean_gl.txt
 * NOAA NCEI paleo data and NOAA GML data are distributed freely (US government /
 * contributed data, "please cite").
 *
 * Subset:
 * - Orbit: every 1,000 years from 800 kyr ago to 100 kyr ahead (the files'
 *   own step). e to 6 decimals, obliquity in degrees to 4, perihelion longitude
 *   in degrees to 2. La2004's time origin is J2000; the ice cores count from
 *   1950: the 50-year offset is far below the 1 kyr step and is ignored.
 * - Dome C temperature: mean of the samples in each 500-year bin of EDC3 age
 *   (bins with no sample are left out), to 2 decimals; age of the bin's mean.
 *   The top samples, with no temperature, are dropped.
 * - CO₂: the composite's samples older than 1850 (age ≥ 100 yr BP) averaged in
 *   500-year bins the same way, to 1 decimal. The industrial era is left out of
 *   the record; today's value is kept separately (latest year of the NOAA file).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) {
	console.error('usage: build-data.mjs <dir with the downloads>');
	process.exit(1);
}
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/ice-ages');
const read = (f) => readFileSync(path.join(dir, f), 'utf8');
const num = (s) => Number(s.replace('D', 'E'));
const deg = (r) => (r * 180) / Math.PI;

// ---------------------------------------------------------------- orbit
const rows = new Map();
for (const f of ['INSOLN.LA2004.BTL.ASC', 'INSOLP.LA2004.BTL.ASC']) {
	for (const line of read(f).split('\n')) {
		const p = line.trim().split(/\s+/);
		if (p.length < 4) continue;
		const t = Math.round(num(p[0]));
		if (t < -800 || t > 100) continue;
		rows.set(t, [num(p[1]), deg(num(p[2])), ((deg(num(p[3])) % 360) + 360) % 360]);
	}
}
const times = [...rows.keys()].sort((a, b) => a - b);
if (times.length !== 901) throw new Error(`expected 901 orbit rows, got ${times.length}`);
const ecc = times.map((t) => rows.get(t)[0].toFixed(6));
const obl = times.map((t) => rows.get(t)[1].toFixed(4));
const peri = times.map((t) => rows.get(t)[2].toFixed(2));
const wrap = (a) => a.join(',').replace(/((?:[^,]*,){12})/g, '$1\n\t');

writeFileSync(
	path.join(OUT, 'orbit-data.ts'),
	`/**
 * Earth's orbital elements, every 1,000 years from 800,000 years ago to
 * 100,000 years ahead: the La2004 solution (Laskar et al. 2004, A&A 428, 261,
 * https://doi.org/10.1051/0004-6361:20041335), from the IMCCE. GENERATED by
 * scripts/data/ice-ages/build-data.mjs: do not edit by hand. Sources, licence
 * and how the subset was made: see that script's header.
 */
/** Time of the first row, kyr (negative: in the past). Rows are 1 kyr apart. */
export const ORBIT_FIRST_KYR = ${times[0]};
/** Eccentricity of the orbit. */
export const ECCENTRICITY: readonly number[] = [
\t${wrap(ecc)}
];
/** Obliquity (tilt of the axis), degrees. */
export const OBLIQUITY: readonly number[] = [
\t${wrap(obl)}
];
/** Longitude of perihelion from the moving vernal equinox (heliocentric), degrees. */
export const PERIHELION: readonly number[] = [
\t${wrap(peri)}
];
`
);

// ---------------------------------------------------------------- ice cores
function bin(samples, width, digits) {
	const bins = new Map();
	for (const [age, v] of samples) {
		const k = Math.floor(age / width);
		const b = bins.get(k) ?? { a: 0, v: 0, n: 0 };
		b.a += age;
		b.v += v;
		b.n++;
		bins.set(k, b);
	}
	return [...bins.keys()]
		.sort((a, b) => a - b)
		.map((k) => {
			const b = bins.get(k);
			return [Math.round(b.a / b.n), Number((b.v / b.n).toFixed(digits))];
		});
}

const edc = [];
for (const line of read('edc3deuttemp2007.txt').split('\n')) {
	const p = line.trim().split(/\s+/);
	if (p.length !== 5 || !/^\d+$/.test(p[0])) continue;
	edc.push([Number(p[2]), Number(p[4])]);
}
const temp = bin(edc, 500, 2);

const co2raw = [];
let inData = false;
for (const line of read('antarctica2015co2composite.txt').split('\n')) {
	if (line.startsWith('age_gas_calBP')) {
		inData = true;
		continue;
	}
	if (!inData || line.startsWith('#')) continue;
	const p = line.trim().split(/\s+/);
	if (p.length < 2) continue;
	const age = Number(p[0]);
	if (age >= 100) co2raw.push([age, Number(p[1])]);
}
const co2 = bin(co2raw, 500, 1);

const gml = read('co2_annmean_gl.txt')
	.split('\n')
	.filter((l) => /^\s*\d{4}\s/.test(l))
	.map((l) => l.trim().split(/\s+/).map(Number));
const [nowYear, nowPpm] = gml[gml.length - 1];

const pairs = (a) =>
	a
		.map(([x, y]) => `${x},${y}`)
		.join(',')
		.replace(/((?:[^,]*,){16})/g, '$1\n\t');

writeFileSync(
	path.join(OUT, 'icecore-data.ts'),
	`/**
 * Ice-core records of the last 800,000 years. GENERATED by
 * scripts/data/ice-ages/build-data.mjs: do not edit by hand. Sources and how
 * the subset was made: see that script's header.
 *
 * - Antarctic temperature: EPICA Dome C, Jouzel et al. (2007), Science 317, 793,
 *   EDC3 age scale; change from the average of the last 1000 years, °C.
 * - CO₂: Antarctic composite, Bereiter et al. (2015), GRL 42, 542, AICC2012 gas ages, ppm.
 * - Today's CO₂: NOAA GML global annual mean.
 */
/** [age in years before 1950, Antarctic temperature change °C] pairs, flattened, 500-year bin means. */
export const DOME_C_TEMPERATURE: readonly number[] = [
\t${pairs(temp)}
];
/** [age in years before 1950, CO₂ ppm] pairs, flattened, 500-year bin means, before 1850 only. */
export const CO2_RECORD: readonly number[] = [
\t${pairs(co2)}
];
/** Global mean CO₂ in the latest full year of NOAA GML's record, ppm. */
export const CO2_NOW = { year: ${nowYear}, ppm: ${nowPpm} };
`
);
console.log(
	`orbit ${times.length} rows; temperature ${temp.length} bins; CO₂ ${co2.length} bins; now ${nowYear} ${nowPpm}`
);
