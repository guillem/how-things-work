#!/usr/bin/env node
/**
 * Builds `src/routes/dna-to-protein/genes-data.ts`: the real sequences of the two
 * genes the "DNA to protein" explainer reads.
 *
 *   node scripts/data/dna-to-protein/build-genes.mjs <download-dir>
 *
 * <download-dir> holds these downloads (not committed):
 *   NM_000518.5.gb      NCBI RefSeq record of the human β-globin (HBB) mRNA, GenBank format:
 *                       https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi?db=nuccore&id=NM_000518.5&rettype=gb&retmode=text
 *   HBB-genomic.txt     the HBB gene on chromosome 11 (GRCh38 11:5,225,464–5,227,071, minus
 *                       strand, so it reads 5′→3′ like the mRNA), from the Ensembl REST API:
 *                       https://rest.ensembl.org/sequence/region/human/11:5225464..5227071:-1?content-type=text/plain
 *   ENST00000335295.json  the exons of transcript HBB-201 (Ensembl release 116):
 *                       https://rest.ensembl.org/lookup/id/ENST00000335295?expand=1;content-type=application/json
 *   trpL.fasta          the E. coli trp operon leader peptide gene (trpL, b1265), NCBI RefSeq
 *                       NC_000913.3 complement(1323038..1323082):
 *                       https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi?db=nuccore&id=NC_000913.3&seq_start=1323038&seq_stop=1323082&strand=2&rettype=fasta&retmode=text
 *
 * The script checks that the exons of the genomic sequence, joined, are exactly the RefSeq
 * mRNA, and that the RefSeq CDS has the length its /translation implies.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const RAW = process.argv[2];
if (!RAW) {
	console.error('usage: build-genes.mjs <download-dir>');
	process.exit(1);
}
const OUT = resolve(import.meta.dirname, '../../../src/routes/dna-to-protein/genes-data.ts');

const gb = readFileSync(join(RAW, 'NM_000518.5.gb'), 'utf8');
const origin = gb.slice(gb.indexOf('\nORIGIN'));
const mrna = origin.replace(/[^acgt]/g, '').toUpperCase();
const cds = gb.match(/^\s+CDS\s+(\d+)\.\.(\d+)/m);
if (!cds) throw new Error('no CDS in the GenBank record');
const [cdsStart, cdsEnd] = [Number(cds[1]), Number(cds[2])];
const translation = (gb.match(/\/translation="([^"]+)"/)?.[1] ?? '').replace(/\s+/g, '');
if ((cdsEnd - cdsStart + 1) / 3 !== translation.length + 1)
	throw new Error('CDS length does not match the translation');

const genomic = readFileSync(join(RAW, 'HBB-genomic.txt'), 'utf8').trim().toUpperCase();
const tx = JSON.parse(readFileSync(join(RAW, 'ENST00000335295.json'), 'utf8'));
// Minus strand: the gene's first letter is at tx.end; exons in transcript order.
const exons = tx.Exon.map((e) => ({ start: tx.end - e.end, end: tx.end - e.start + 1 })).sort(
	(a, b) => a.start - b.start
);
const joined = exons.map((e) => genomic.slice(e.start, e.end)).join('');
if (genomic.length !== tx.end - tx.start + 1) throw new Error('genomic length mismatch');
if (joined !== mrna) throw new Error('the exons joined are not the RefSeq mRNA');

const trpL = readFileSync(join(RAW, 'trpL.fasta'), 'utf8')
	.split('\n')
	.slice(1)
	.join('')
	.trim()
	.toUpperCase();

const wrap = (s) =>
	s
		.match(/.{1,80}/g)
		.map((l) => `\t\t'${l}'`)
		.join(' +\n');

writeFileSync(
	OUT,
	`/**
 * GENERATED by scripts/data/dna-to-protein/build-genes.mjs — do not edit by hand.
 *
 * Real gene sequences, written as the coding (sense) strand of the DNA, 5′→3′.
 *
 * Human β-globin, HBB (chromosome 11p15.4):
 *   - gene: GRCh38 chr11:${tx.start}–${tx.end}, minus strand (${genomic.length} bp), from the Ensembl REST API,
 *     transcript ${tx.id}.${tx.version} (HBB-201, the MANE Select transcript), Ensembl release 116;
 *   - mRNA: NCBI RefSeq NM_000518.5 (${mrna.length} nt), CDS ${cdsStart}..${cdsEnd}, whose
 *     /translation is the ${translation.length}-residue protein NP_000509.1. The exons of the gene,
 *     joined, are exactly this mRNA (checked by the build script).
 * E. coli trp operon leader peptide, trpL (b1265): NCBI RefSeq NC_000913.3
 *   complement(1323038..1323082), K-12 MG1655, ${trpL.length} bp.
 *
 * Retrieved 2026-10-14. NCBI sequence records are in the public domain (NCBI usage policy);
 * Ensembl data are free to use without restriction (Ensembl disclaimer).
 */

/** HBB: the whole gene, exons and introns, as transcribed. */
export const HBB_GENE =
${wrap(genomic)};

/** HBB: where each exon sits in HBB_GENE, 0-based, end exclusive. */
export const HBB_EXONS: readonly { start: number; end: number }[] = ${JSON.stringify(exons)};

/** HBB mRNA NM_000518.5 (as DNA letters), the coding sequence from 1-based ${cdsStart} to ${cdsEnd}. */
export const HBB_MRNA =
${wrap(mrna)};
export const HBB_CDS = { start: ${cdsStart - 1}, end: ${cdsEnd} } as const;

/** The protein, NP_000509.1, as given by the RefSeq record (no stop sign). */
export const HBB_PROTEIN =
${wrap(translation)};

/** trpL: the coding sequence, start codon to stop codon. */
export const TRPL_GENE = '${trpL}';
`
);
console.log(`wrote ${OUT}`);
