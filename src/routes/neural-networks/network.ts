/**
 * A small fully connected neural network, trained in the browser.
 *
 * Model (the textbook multilayer perceptron, e.g. Goodfellow, Bengio & Courville, "Deep
 * Learning", ch. 6, and Rumelhart, Hinton & Williams, Nature 323, 533–536, 1986):
 *
 *   input a⁰ = (x₁, x₂)
 *   for every layer l:  zˡ = Wˡ aˡ⁻¹ + bˡ,   aˡ = f(zˡ)
 *   the hidden layers use the chosen activation f (tanh, ReLU or none), the single output
 *   neuron uses the logistic sigmoid σ(z) = 1 / (1 + e⁻ᶻ), read as the probability of class 1.
 *
 * Loss: binary cross-entropy, L = −[y log p + (1 − y) log(1 − p)], averaged over the examples.
 * With a sigmoid output its error signal is simply ∂L/∂z = p − y.
 *
 * Backpropagation (the chain rule, layer by layer from the output back):
 *   δᴸ = p − y
 *   δˡ = (Wˡ⁺¹ᵀ δˡ⁺¹) ⊙ f′(zˡ)
 *   ∂L/∂Wˡ = δˡ (aˡ⁻¹)ᵀ,   ∂L/∂bˡ = δˡ
 * checked against finite differences in e2e/neural-networks-model.e2e.ts.
 *
 * Training: stochastic gradient descent on shuffled mini-batches of 10 examples; one epoch is
 * one pass through all of them. Weights start random (LeCun scaling √(1/n_in), He scaling
 * √(2/n_in) for ReLU hidden layers), biases at 0. Everything is seeded, so a run is the same on every machine.
 *
 * The datasets are generated by the computer (seeded), the classic toy problems of
 * the TensorFlow Playground and scikit-learn: two clusters, four XOR corners, a circle in a ring,
 * two moons and two spirals.
 */
import { rng } from '#lib/draw/math.ts';

// ---------------------------------------------------------------------- activations

export type Activation = 'tanh' | 'relu' | 'linear' | 'sigmoid';
export const ACTIVATIONS: Activation[] = ['tanh', 'relu', 'linear', 'sigmoid'];

export function activate(f: Activation, z: number): number {
	switch (f) {
		case 'tanh':
			return Math.tanh(z);
		case 'relu':
			return z > 0 ? z : 0;
		case 'linear':
			return z;
		case 'sigmoid':
			return sigmoid(z);
	}
}

/** The slope f′(z) of the activation. */
export function slope(f: Activation, z: number): number {
	switch (f) {
		case 'tanh': {
			const a = Math.tanh(z);
			return 1 - a * a;
		}
		case 'relu':
			return z > 0 ? 1 : 0;
		case 'linear':
			return 1;
		case 'sigmoid': {
			const s = sigmoid(z);
			return s * (1 - s);
		}
	}
}

export function sigmoid(z: number) {
	return z >= 0 ? 1 / (1 + Math.exp(-z)) : Math.exp(z) / (1 + Math.exp(z));
}

/** Cross-entropy of one example, from the output neuron's sum z (stable for large |z|). */
export function crossEntropy(z: number, y: number) {
	// −[y log σ(z) + (1 − y) log(1 − σ(z))] = max(z, 0) − y z + log(1 + e^−|z|)
	return Math.max(z, 0) - y * z + Math.log1p(Math.exp(-Math.abs(z)));
}

// ---------------------------------------------------------------------- the network

export interface Net {
	/** Neurons per layer, inputs first, the single output last: e.g. [2, 4, 1]. */
	sizes: number[];
	/** Activation of the hidden layers (the output always uses the sigmoid). */
	act: Activation;
	/** W[l] maps layer l to layer l + 1: sizes[l + 1] rows × sizes[l] columns, row-major. */
	W: Float64Array[];
	b: Float64Array[];
}

export function layerAct(net: Net, l: number): Activation {
	// l counts weight layers: 0 … sizes.length − 2; the last one is the output.
	return l === net.sizes.length - 2 ? 'sigmoid' : net.act;
}

/** Normal deviate from a uniform generator (Box–Muller). */
function gauss(rand: () => number) {
	const u = Math.max(rand(), 1e-12);
	return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rand());
}

export function createNet(sizes: number[], act: Activation, seed = 1): Net {
	const rand = rng(seed * 7919 + 13);
	const W: Float64Array[] = [];
	const b: Float64Array[] = [];
	for (let l = 0; l + 1 < sizes.length; l++) {
		const nIn = sizes[l];
		const nOut = sizes[l + 1];
		const sd = act === 'relu' && l + 2 < sizes.length ? Math.sqrt(2 / nIn) : Math.sqrt(1 / nIn);
		const w = new Float64Array(nOut * nIn);
		for (let i = 0; i < w.length; i++) w[i] = sd * gauss(rand);
		W.push(w);
		b.push(new Float64Array(nOut));
	}
	return { sizes: [...sizes], act, W, b };
}

export function cloneNet(net: Net): Net {
	return {
		sizes: [...net.sizes],
		act: net.act,
		W: net.W.map((w) => w.slice()),
		b: net.b.map((v) => v.slice())
	};
}

export interface Forward {
	/** z[l]: the sums of layer l + 1 (before the activation). */
	z: number[][];
	/** a[0] is the input; a[l] the outputs of layer l. */
	a: number[][];
}

export function forward(net: Net, x: readonly number[]): Forward {
	const a: number[][] = [[...x]];
	const z: number[][] = [];
	for (let l = 0; l + 1 < net.sizes.length; l++) {
		const nIn = net.sizes[l];
		const nOut = net.sizes[l + 1];
		const w = net.W[l];
		const prev = a[l];
		const zl: number[] = new Array<number>(nOut);
		const al: number[] = new Array<number>(nOut);
		const f = layerAct(net, l);
		for (let j = 0; j < nOut; j++) {
			let s = net.b[l][j];
			for (let i = 0; i < nIn; i++) s += w[j * nIn + i] * prev[i];
			zl[j] = s;
			al[j] = activate(f, s);
		}
		z.push(zl);
		a.push(al);
	}
	return { z, a };
}

/** The network's probability of class 1 at a point. */
export function predict(net: Net, x: readonly number[]) {
	const { a } = forward(net, x);
	return a[a.length - 1][0];
}

export interface Backward {
	/** delta[l]: ∂L/∂z for the neurons of layer l + 1 (same shape as Forward.z). */
	delta: number[][];
	gW: Float64Array[];
	gb: Float64Array[];
}

/** Backpropagation for one example with label y (0 or 1). */
export function backward(net: Net, fw: Forward, y: number): Backward {
	const L = net.sizes.length - 1;
	const delta: number[][] = new Array<number[]>(L);
	const p = fw.a[L][0];
	delta[L - 1] = [p - y];
	for (let l = L - 2; l >= 0; l--) {
		const n = net.sizes[l + 1];
		const nNext = net.sizes[l + 2];
		const w = net.W[l + 1];
		const f = layerAct(net, l);
		const d: number[] = new Array<number>(n);
		for (let i = 0; i < n; i++) {
			let s = 0;
			for (let j = 0; j < nNext; j++) s += w[j * n + i] * delta[l + 1][j];
			d[i] = s * slope(f, fw.z[l][i]);
		}
		delta[l] = d;
	}
	const gW: Float64Array[] = [];
	const gb: Float64Array[] = [];
	for (let l = 0; l < L; l++) {
		const nIn = net.sizes[l];
		const nOut = net.sizes[l + 1];
		const g = new Float64Array(nOut * nIn);
		for (let j = 0; j < nOut; j++)
			for (let i = 0; i < nIn; i++) g[j * nIn + i] = delta[l][j] * fw.a[l][i];
		gW.push(g);
		gb.push(Float64Array.from(delta[l]));
	}
	return { delta, gW, gb };
}

// ---------------------------------------------------------------------- data

export interface Example {
	x: number;
	y: number;
	/** Class: 0 or 1. */
	label: number;
}

export type DatasetId = 'clusters' | 'xor' | 'circle' | 'moons' | 'spiral';
export const DATASET_IDS: DatasetId[] = ['clusters', 'xor', 'circle', 'moons', 'spiral'];
export const DATASET_NAMES: Record<DatasetId, string> = {
	clusters: 'Two clusters',
	xor: 'Four corners (XOR)',
	circle: 'Circle in a ring',
	moons: 'Two moons',
	spiral: 'Two spirals'
};

/** The plane shown on the stage: both inputs run from −1 to 1. */
export const EXTENT = 1;

function makeDataset(id: DatasetId): Example[] {
	const rand = rng({ clusters: 11, xor: 22, circle: 33, moons: 55, spiral: 44 }[id]);
	const out: Example[] = [];
	const N = 200;
	if (id === 'clusters') {
		for (let i = 0; i < N; i++) {
			const label = i % 2;
			const c = label ? 0.42 : -0.42;
			let x: number, y: number;
			do {
				x = c + 0.2 * gauss(rand);
				y = c * 0.8 + 0.2 * gauss(rand);
			} while (Math.abs(x) > 0.95 || Math.abs(y) > 0.95 || (label ? x + y < 0.15 : x + y > -0.15));
			out.push({ x, y, label });
		}
	} else if (id === 'xor') {
		// Four clusters at the corners; opposite corners share a class (the XOR pattern).
		for (let i = 0; i < N; i++) {
			const sx = i % 2 ? 1 : -1;
			const sy = i % 4 < 2 ? 1 : -1;
			let x: number, y: number;
			do {
				x = 0.5 * sx + 0.14 * gauss(rand);
				y = 0.5 * sy + 0.14 * gauss(rand);
			} while (x * sx < 0.2 || y * sy < 0.2 || Math.abs(x) > 0.95 || Math.abs(y) > 0.95);
			out.push({ x, y, label: sx === sy ? 1 : 0 });
		}
	} else if (id === 'circle') {
		for (let i = 0; i < N; i++) {
			const label = i % 2;
			const r = label ? 0.42 * Math.sqrt(rand()) : 0.62 + 0.32 * rand();
			const th = 2 * Math.PI * rand();
			out.push({ x: r * Math.cos(th), y: r * Math.sin(th), label });
		}
	} else if (id === 'moons') {
		// Two interlocking half-circles (the "two moons" of scikit-learn's make_moons), scaled into the plane.
		for (let i = 0; i < N; i++) {
			const label = i % 2;
			const th = Math.PI * rand();
			const x = label ? 1 - Math.cos(th) : Math.cos(th);
			const y = label ? 0.25 - Math.sin(th) : Math.sin(th);
			out.push({
				x: (x - 0.5) * 0.6 + 0.04 * gauss(rand),
				y: (y - 0.12) * 0.6 + 0.04 * gauss(rand),
				label
			});
		}
	} else {
		const n = N / 2;
		for (let i = 0; i < n; i++) {
			for (const label of [0, 1]) {
				const u = i / n;
				const r = 0.08 + 0.84 * u;
				const th = 1.5 * 2 * Math.PI * u + label * Math.PI;
				out.push({
					x: r * Math.sin(th) + 0.02 * gauss(rand),
					y: r * Math.cos(th) + 0.02 * gauss(rand),
					label
				});
			}
		}
	}
	return out;
}

const dataCache = new Map<DatasetId, Example[]>();
export function dataset(id: DatasetId): Example[] {
	let d = dataCache.get(id);
	if (!d) {
		d = makeDataset(id);
		dataCache.set(id, d);
	}
	return d;
}

// ---------------------------------------------------------------------- loss and training

export function meanLoss(net: Net, data: readonly Example[]) {
	let s = 0;
	for (const e of data) {
		const { z } = forward(net, [e.x, e.y]);
		s += crossEntropy(z[z.length - 1][0], e.label);
	}
	return s / data.length;
}

/** Share of the examples on the right side of the boundary (p > 0.5 ⇔ class 1). */
export function accuracy(net: Net, data: readonly Example[]) {
	let right = 0;
	for (const e of data) if (predict(net, [e.x, e.y]) > 0.5 === (e.label === 1)) right++;
	return right / data.length;
}

/** Mean gradient of the loss over some examples. */
export function gradient(net: Net, data: readonly Example[]) {
	const gW = net.W.map((w) => new Float64Array(w.length));
	const gb = net.b.map((v) => new Float64Array(v.length));
	for (const e of data) {
		const g = backward(net, forward(net, [e.x, e.y]), e.label);
		for (let l = 0; l < gW.length; l++) {
			for (let i = 0; i < gW[l].length; i++) gW[l][i] += g.gW[l][i] / data.length;
			for (let i = 0; i < gb[l].length; i++) gb[l][i] += g.gb[l][i] / data.length;
		}
	}
	return { gW, gb };
}

/** One gradient-descent step in place: every weight moves by −η × its slope. */
export function applyStep(net: Net, g: { gW: Float64Array[]; gb: Float64Array[] }, lr: number) {
	for (let l = 0; l < net.W.length; l++) {
		for (let i = 0; i < net.W[l].length; i++) net.W[l][i] -= lr * g.gW[l][i];
		for (let i = 0; i < net.b[l].length; i++) net.b[l][i] -= lr * g.gb[l][i];
	}
}

export const BATCH = 10;

/** One epoch of mini-batch SGD, in place. */
export function trainEpoch(net: Net, data: readonly Example[], lr: number, rand: () => number) {
	const order = data.map((_, i) => i);
	for (let i = order.length - 1; i > 0; i--) {
		const j = Math.floor(rand() * (i + 1));
		[order[i], order[j]] = [order[j], order[i]];
	}
	for (let s = 0; s < order.length; s += BATCH) {
		const batch = order.slice(s, s + BATCH).map((i) => data[i]);
		applyStep(net, gradient(net, batch), lr);
	}
}

export interface RunSpec {
	data: DatasetId;
	/** Neurons in each hidden layer, e.g. [4, 4]; [] for no hidden layer. */
	hidden: number[];
	act: Activation;
	lr: number;
	seed: number;
}

/** Whether every weight and bias of a network is a finite number. */
export function isFiniteNet(net: Net) {
	return [...net.W, ...net.b].every((v) => v.every(Number.isFinite));
}

export const runKey = (s: RunSpec) => [s.data, s.hidden.join('-'), s.act, s.lr, s.seed].join('|');

/** A training run that extends itself lazily, keeping the network after every epoch. */
export class Run {
	readonly spec: RunSpec;
	readonly data: Example[];
	readonly nets: Net[] = [];
	readonly losses: number[] = [];
	readonly accuracies: number[] = [];
	/** The first epoch at which a weight stopped being a finite number (the steps were too big), or −1. */
	divergedAt = -1;
	private rand: () => number;
	private live: Net;

	constructor(spec: RunSpec) {
		this.spec = spec;
		this.data = dataset(spec.data);
		this.live = createNet([2, ...spec.hidden, 1], spec.act, spec.seed);
		this.rand = rng(spec.seed * 104729 + 7);
		this.record();
	}

	private record() {
		this.nets.push(cloneNet(this.live));
		const l = meanLoss(this.live, this.data);
		this.losses.push(Number.isFinite(l) ? l : Infinity);
		this.accuracies.push(accuracy(this.live, this.data));
		if (this.divergedAt < 0 && !isFiniteNet(this.live)) this.divergedAt = this.nets.length - 1;
	}

	/** The network after `epoch` epochs of training. */
	at(epoch: number): Net {
		const k = Math.max(0, Math.floor(epoch));
		while (this.nets.length <= k) {
			trainEpoch(this.live, this.data, this.spec.lr, this.rand);
			this.record();
		}
		return this.nets[k];
	}

	/** The first epoch at which every example is classified correctly, or −1 (searched up to `max`). */
	solvedAt(max: number) {
		for (let k = 0; k <= max; k++) {
			this.at(k);
			if (this.accuracies[k] === 1) return k;
		}
		return -1;
	}
}

const runCache = new Map<string, Run>();
/** The run for a spec, shared between frames and steps (a few kept, oldest dropped first). */
export function runFor(spec: RunSpec): Run {
	const key = runKey(spec);
	let r = runCache.get(key);
	if (r) {
		runCache.delete(key);
	} else {
		r = new Run(spec);
	}
	runCache.set(key, r);
	while (runCache.size > 12) runCache.delete(runCache.keys().next().value!);
	return r;
}

// ---------------------------------------------------------------------- the plane through a layer

/** A layer's three moves on a point: multiply by W, add b, apply the activation. */
export function layerStages(net: Net, l: number, p: readonly number[]) {
	const nIn = net.sizes[l];
	const nOut = net.sizes[l + 1];
	const lin: number[] = [];
	for (let j = 0; j < nOut; j++) {
		let s = 0;
		for (let i = 0; i < nIn; i++) s += net.W[l][j * nIn + i] * p[i];
		lin.push(s);
	}
	const shifted = lin.map((v, j) => v + net.b[l][j]);
	const out = shifted.map((v) => activate(layerAct(net, l), v));
	return { lin, shifted, out };
}

/** Collapses a network whose hidden layers are all linear into one neuron: z = w·x + b. */
export function collapseLinear(net: Net) {
	if (net.act !== 'linear') throw new Error('only a linear network collapses');
	// Track the affine map x ↦ M x + c through every layer but the output's sigmoid.
	let M: number[][] = [
		[1, 0],
		[0, 1]
	];
	let c = [0, 0];
	for (let l = 0; l + 1 < net.sizes.length; l++) {
		const nIn = net.sizes[l];
		const nOut = net.sizes[l + 1];
		const M2: number[][] = [];
		const c2: number[] = [];
		for (let j = 0; j < nOut; j++) {
			const row = [0, 0];
			let s = net.b[l][j];
			for (let i = 0; i < nIn; i++) {
				const w = net.W[l][j * nIn + i];
				row[0] += w * M[i][0];
				row[1] += w * M[i][1];
				s += w * c[i];
			}
			M2.push(row);
			c2.push(s);
		}
		M = M2;
		c = c2;
	}
	return { w: M[0], b: c[0] };
}

