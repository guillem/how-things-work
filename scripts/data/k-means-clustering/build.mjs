// Downloads the Palmer penguins measurements (palmerpenguins by Horst, Hill and Gorman, CC0, data
// from Palmer Station LTER and Dr. Kristen Gorman) and writes the two the page clusters on, bill
// length and flipper length, with each bird's species, into the k-means-clustering route. The two
// birds with no measurements are left out (342 of 344 remain).
// Usage: node scripts/data/k-means-clustering/build.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const URL =
	'https://raw.githubusercontent.com/allisonhorst/palmerpenguins/main/inst/extdata/penguins.csv';
const SHA256 = 'f204db2c753b0937caac3cb35258562c14f073e4bbc76be24b4c51ce22767a93';
const OUT = new globalThis.URL(
	'../../../src/routes/k-means-clustering/penguins.ts',
	import.meta.url
);
const SPECIES = ['Adelie', 'Chinstrap', 'Gentoo'];

const res = await fetch(URL);
if (!res.ok) throw new Error(`HTTP ${res.status}`);
const text = await res.text();
const sum = createHash('sha256').update(text).digest('hex');
if (sum !== SHA256) throw new Error(`unexpected SHA-256 ${sum}`);

const [header, ...lines] = text.trim().split('\n');
const col = header.split(',');
const at = (name) => col.indexOf(name);
const rows = [];
for (const line of lines) {
	const f = line.split(',');
	const bill = Number(f[at('bill_length_mm')]);
	const flipper = Number(f[at('flipper_length_mm')]);
	if (!Number.isFinite(bill) || !Number.isFinite(flipper) || f[at('flipper_length_mm')] === 'NA')
		continue;
	rows.push(`[${bill}, ${flipper}, ${SPECIES.indexOf(f[at('species')])}]`);
}

writeFileSync(
	OUT,
	`// Generated by scripts/data/k-means-clustering/build.mjs from palmerpenguins (Horst, Hill and
// Gorman; CC0; Palmer Station LTER). Do not edit by hand.

/** Species names, indexed by the third number of each row. */
export const SPECIES = ['Adélie', 'Chinstrap', 'Gentoo'] as const;

/** One row per penguin: bill length (mm), flipper length (mm), species index. */
export const PENGUINS: readonly (readonly [number, number, number])[] = [
	${rows.join(',\n\t')}
];
`
);
console.log(`wrote ${rows.length} penguins to ${OUT.pathname}`);
