#!/usr/bin/env node
/**
 * Builds `src/routes/atoms-periodic-table/isotopes.ts`: for every element (Z = 1–118), the mass
 * numbers of the isotopes that have ever been observed, as ranges.
 *
 *   curl -o /tmp/nubase/nubase_4.mas20.txt https://www-nds.iaea.org/amdc/ame2020/nubase_4.mas20.txt
 *   node scripts/data/atoms-periodic-table/build-nubase.mjs /tmp/nubase/nubase_4.mas20.txt
 *
 * Source: Atomic Mass Data Center (IAEA), NUBASE2020, file `nubase_4.mas20.txt`,
 * https://www-nds.iaea.org/amdc/ (retrieved 2026-10-17). Citation: F.G. Kondev, M. Wang,
 * W.J. Huang, S. Naimi and G. Audi, Chinese Physics C 45, 030001 (2021). The tables are
 * published for free use; the data file states no licence, so cite the paper above.
 *
 * Subset: the ground states (isomer digit 0). A nuclide counts as observed when NUBASE gives
 * it a year of discovery (columns 115–118; Thoennessen's discovery criteria) and does not flag
 * its existence as questioned (origin code 'EU' or 'RN', e.g. 260Fm, 289Lv, 293Og). The others
 * are estimates from the systematics of the mass surface: no such nucleus has been seen.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const file = process.argv[2];
if (!file) {
	console.error(
		'usage: node scripts/data/atoms-periodic-table/build-nubase.mjs <nubase_4.mas20.txt>'
	);
	process.exit(1);
}
const OUT = path.resolve(
	import.meta.dirname,
	'../../../src/routes/atoms-periodic-table/isotopes.ts'
);
const lines = readFileSync(file, 'utf8').split('\n');
if (!lines[0]?.includes('Nubase2020')) throw new Error('not the NUBASE2020 table');

/** Observed ground-state mass numbers per Z. */
const seen = new Map();
let observed = 0;
let skipped = 0;
for (const l of lines) {
	if (l.startsWith('#') || l.trim().length < 20) continue;
	const A = Number(l.slice(0, 3));
	const Z = Number(l.slice(4, 7));
	const state = l.slice(7, 8);
	if (!Number.isInteger(A) || !Number.isInteger(Z)) throw new Error(`bad row: ${l}`);
	if (state !== '0' || Z < 1) continue;
	const origin = l.slice(65, 67).trim();
	const year = l.slice(114, 118).trim();
	if (!/^\d{4}$/.test(year) || origin === 'EU' || origin === 'RN') {
		skipped++;
		continue;
	}
	if (!seen.has(Z)) seen.set(Z, []);
	seen.get(Z).push(A);
	observed++;
}
if (seen.size !== 118) throw new Error(`expected 118 elements, found ${seen.size}`);

/** [[from, to], …] covering exactly the observed mass numbers. */
const ranges = (list) => {
	const out = [];
	for (const a of [...new Set(list)].sort((x, y) => x - y)) {
		const last = out.at(-1);
		if (last && a === last[1] + 1) last[1] = a;
		else out.push([a, a]);
	}
	return out;
};
const known = Array.from({ length: 118 }, (_, i) => ranges(seen.get(i + 1)));

const body = `/**
 * Known isotopes for the atoms explainer: for each element (index Z − 1), the mass numbers of
 * the ground-state nuclei that have ever been observed, as inclusive ranges [from, to].
 * Generated by scripts/data/atoms-periodic-table/build-nubase.mjs from NUBASE2020
 * (Kondev, Wang, Huang, Naimi & Audi, Chinese Physics C 45, 030001, 2021; Atomic Mass Data
 * Center, IAEA, file nubase_4.mas20.txt, retrieved 2026-10-17; the data file states no licence,
 * the tables are published for free use with citation). Observed = NUBASE gives a year of
 * discovery and does not flag the nuclide's existence as questioned. ${observed} nuclides;
 * ${skipped} ground states without a discovery (estimated from systematics, or questioned) are
 * left out.
 */
export default {
	source: 'NUBASE2020 (Kondev et al., Chinese Physics C 45, 030001, 2021), nubase_4.mas20.txt',
	known: ${JSON.stringify(known)} as [number, number][][]
};
`;
writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${observed} observed nuclides, ${skipped} skipped`);
