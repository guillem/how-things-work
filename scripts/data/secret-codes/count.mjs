// Counts the letters (and the commonest words) of Alice's Adventures in Wonderland, the plain-text
// edition of Project Gutenberg eBook #11 (public domain in the United States), and writes
// src/routes/secret-codes/english.ts: the "ordinary English" the secret-codes page compares
// secret messages with.
//
// Usage: download the text first (it is not committed), then pass its path:
//   curl -sSL -o <dir>/pg11.txt https://www.gutenberg.org/cache/epub/11/pg11.txt
//   node scripts/data/secret-codes/count.mjs <dir>/pg11.txt
//
// What is counted: only Carroll's story. Project Gutenberg's header (everything up to the
// "*** START OF THE PROJECT GUTENBERG EBOOK" line) and its licence footer (from the "*** END OF"
// line) are cut off, then the title page and the table of contents up to the first chapter
// heading, and the one "[Illustration]" marker Gutenberg inserts. Letters are counted A to Z
// without regard to case; accents are dropped first (the "Où" of "Où est ma chatte?" counts as
// an O and a U). Words are runs of letters (so "don’t" is "DON" and "T"); the common-word list
// keeps words of two letters or more. Then the story's letters are cut into pieces of 25, 100,
// 300 and 1,000 letters (one after another, the last short piece dropped), and for each length
// the script counts the pieces in which E is the tallest bar on its own (no other letter as
// common): how often counting letters finds E in a message of that length.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [file] = process.argv.slice(2);
if (!file) throw new Error('usage: node scripts/data/secret-codes/count.mjs <path to pg11.txt>');
const OUT = new URL('../../../src/routes/secret-codes/english.ts', import.meta.url);
const COMMON = 200;

const raw = readFileSync(file);
const sha = createHash('sha256').update(raw).digest('hex');
const text = raw.toString('utf8').replace(/\r\n/g, '\n');

const start = text.search(/^\*\*\* START OF THE PROJECT GUTENBERG EBOOK .*\*\*\*$/m);
const end = text.search(/^\*\*\* END OF THE PROJECT GUTENBERG EBOOK .*\*\*\*$/m);
if (start < 0 || end < 0) throw new Error('Gutenberg START/END markers not found');
let body = text.slice(text.indexOf('\n', start) + 1, end);
const chapterOne = body.search(/^CHAPTER I\.$/m);
if (chapterOne < 0) throw new Error('first chapter heading not found');
body = body.slice(chapterOne).replace(/\[Illustration\]/g, '');
if (!/THE END\s*$/.test(body)) throw new Error('the story should end with "THE END"');

const plain = body.normalize('NFD').replace(/\p{M}/gu, '').toUpperCase();
const letters = new Array(26).fill(0);
for (const ch of plain) {
	const i = ch.charCodeAt(0) - 65;
	if (i >= 0 && i < 26) letters[i]++;
}
const total = letters.reduce((a, b) => a + b, 0);

const stream = [...plain].filter((ch) => ch >= 'A' && ch <= 'Z');
const pieces = [25, 100, 300, 1000].map((length) => {
	let count = 0;
	let eTallest = 0;
	for (let i = 0; i + length <= stream.length; i += length) {
		const n = new Array(26).fill(0);
		for (let k = i; k < i + length; k++) n[stream[k].charCodeAt(0) - 65]++;
		count++;
		if (n.every((c, j) => j === 4 || c < n[4])) eTallest++;
	}
	return { length, count, eTallest };
});

const words = new Map();
for (const w of plain.match(/[A-Z]+/g) ?? []) words.set(w, (words.get(w) ?? 0) + 1);
const common = [...words]
	.filter(([w]) => w.length >= 2)
	.sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
	.slice(0, COMMON);

const ts = `// Generated by scripts/data/secret-codes/count.mjs: do not edit by hand.
// Source: Lewis Carroll, Alice's Adventures in Wonderland (1865), Project Gutenberg eBook #11,
// https://www.gutenberg.org/ebooks/11 (plain text https://www.gutenberg.org/cache/epub/11/pg11.txt),
// public domain in the United States. Text counted: SHA-256
// ${sha}.
// Project Gutenberg's header and licence footer, the title page and the contents are not counted.

/** How many times each letter, A to Z, appears in the story. */
export const LETTER_COUNTS: readonly number[] = [${letters.join(', ')}];

/** All the letters counted. */
export const LETTER_TOTAL = ${total};

/**
 * The story cut into pieces of \`length\` letters: how many pieces there were, and in how many of
 * them E was the tallest bar on its own.
 */
export const E_TALLEST: readonly { length: number; count: number; eTallest: number }[] = [
${pieces.map((p) => `\t{ length: ${p.length}, count: ${p.count}, eTallest: ${p.eTallest} }`).join(',\n')}
];

/** The story's ${COMMON} commonest words of two letters or more, commonest first. */
export const COMMON_WORDS: readonly string[] = (
	'${common.map(([w]) => w).join(' ')}'
).split(' ');
`;
writeFileSync(OUT, ts);
console.log(`${total} letters, ${words.size} different words; wrote ${OUT.pathname}`);
console.log(
	letters
		.map((n, i) => [String.fromCharCode(65 + i), n])
		.sort((a, b) => b[1] - a[1])
		.map(([l, n]) => `${l} ${((100 * n) / total).toFixed(1)}%`)
		.join(', ')
);
for (const p of pieces)
	console.log(`pieces of ${p.length}: E tallest in ${p.eTallest} of ${p.count}`);
