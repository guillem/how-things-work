#!/usr/bin/env node
/**
 * Builds `src/routes/solar-cells/records.ts`: a few record solar-cell efficiencies.
 *
 *   unzip cell-efficiency-data-table.xlsx -d <dir>
 *   node scripts/data/solar-cells/build-records.mjs <dir>
 *
 * Source: National Laboratory of the Rockies (formerly NREL), "Best Research-Cell
 * Efficiency Chart", https://www.nlr.gov/pv/cell-efficiency, data table
 * https://www.nlr.gov/docs/libraries/pv/cell-efficiency-data-table.xlsx (page last updated
 * 14 Aug 2026, downloaded 15 Oct 2026). NLR: "The plot is not copyrighted and may be used in
 * presentations and publications, with a notation that states: 'This plot is courtesy of the
 * National Laboratory of the Rockies, Golden, CO.'" Every value was checked against the
 * flags of the chart image (rev. 07-17-2026).
 *
 * Subset: the current record of each technology below, by the table's record identifier
 * (column A). The table mixes units, so they are normalised here: Voc in volts (one row is
 * in mV), fill factor in % (old rows are fractions), Jsc in mA/cm² from the "Revised/New
 * Jsc" column when present. Efficiency is the "Combined efficiency" column (the charted one).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: build-records.mjs <dir with the unzipped xlsx>');
const OUT = path.resolve(import.meta.dirname, '../../../src/routes/solar-cells/records.ts');

/** [record id, our key, how the page names the technology]. */
const PICK = [
	['559', 'si', 'Crystalline silicon'],
	['00459', 'gaas', 'Gallium arsenide (thin film)'],
	['560', 'perovskite', 'Perovskite'],
	['00511', 'cigs', 'CIGS (copper indium gallium selenide)'],
	['00541', 'cdte', 'Cadmium telluride'],
	['561', 'perovskiteSi', 'Perovskite on silicon (2 junctions)'],
	['00503', 'threeJunction', 'III–V, 3 junctions'],
	['00508', 'concentrator', 'III–V, 4 junctions, 665 suns']
];

const unxml = (s) =>
	s
		.replace(/<[^>]+>/g, '')
		.replace(/&lt;/g, '<')
		.replace(/&gt;/g, '>')
		.replace(/&quot;/g, '"')
		.replace(/&apos;/g, "'")
		.replace(/&amp;/g, '&');
const shared = [
	...readFileSync(path.join(dir, 'xl/sharedStrings.xml'), 'utf8').matchAll(/<si>([\s\S]*?)<\/si>/g)
].map((m) => unxml(m[1]));
const sheet = readFileSync(path.join(dir, 'xl/worksheets/sheet1.xml'), 'utf8');

const rows = [];
for (const r of sheet.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
	const cells = {};
	for (const c of r[1].matchAll(/<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
		const v = /<v>([\s\S]*?)<\/v>/.exec(c[3] ?? '');
		if (!v) continue;
		cells[c[1]] = /t="s"/.test(c[2]) ? shared[Number(v[1])] : v[1];
	}
	rows.push(cells);
}
const header = rows[0];
if (header.A !== 'Record Identifier' || header.M !== 'Combined efficiency (%)')
	throw new Error('unexpected columns');

const num = (v) => (v === undefined || v === '' ? null : Number(v));
const round = (v, d) => (v === null ? null : Number(v.toFixed(d)));
const out = [];
for (const [id, key, name] of PICK) {
	const row = rows.find((r) => r.A === id);
	if (!row) throw new Error(`record ${id} missing`);
	let voc = num(row.Q);
	if (voc !== null && voc > 10) voc /= 1000;
	let ff = num(row.T);
	if (ff !== null && ff <= 1) ff *= 100;
	out.push({
		key,
		id,
		name,
		efficiency: round(num(row.M), 2),
		year: Number(row.D),
		group: row.J,
		suns: num(row.U) ?? 1,
		voc: round(voc, 4),
		jsc: round(num(row.S) ?? num(row.R), 2),
		ff: round(ff, 2)
	});
}

const src = `/**
 * Record solar-cell efficiencies (confirmed, standard test conditions).
 * GENERATED by scripts/data/solar-cells/build-records.mjs — do not edit by hand.
 *
 * Source: National Laboratory of the Rockies (formerly NREL), Best Research-Cell
 * Efficiency Chart, https://www.nlr.gov/pv/cell-efficiency, data table
 * cell-efficiency-data-table.xlsx (page updated 14 Aug 2026). "This plot is courtesy of the
 * National Laboratory of the Rockies, Golden, CO." Values checked against the chart's flags.
 * Subset: the current record of each technology listed; \`id\` is the table's record
 * identifier. Units normalised: voc V, jsc mA/cm², ff %, efficiency %.
 */

export interface CellRecord {
	key: string;
	/** Record identifier in the NLR table. */
	id: string;
	name: string;
	efficiency: number;
	year: number;
	group: string;
	/** Light concentration the cell was measured under (1 = ordinary sunlight). */
	suns: number;
	voc: number | null;
	jsc: number | null;
	ff: number | null;
}

export const RECORDS: readonly CellRecord[] = ${JSON.stringify(out, null, '\t')};
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: ${out.length} records`);
